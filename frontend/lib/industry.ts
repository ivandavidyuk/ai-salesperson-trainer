// Отрасль организации на фронте: медицина или нет.
//
// Свободный текст из формы руководителя разбирает тот же разборщик, что
// собирает промпт (industryRules): всё, где нет недвижимости, — клиника.
// Здесь только то, что нужно роутам: у немедицинских отраслей случаи пишутся
// заранее в пресете, и генерация из кабинета для них закрыта — эксперта
// по недвижимости у нас нет, а медицинский конвейер собрал бы им диагнозы
// (каркас недвижимости, п. 8, решение 17.09).

import { industryKey } from "@/scripts/patient-prompt";

/** Клиника ли это — то есть работает ли для неё сборка случаев */
export function медицинскаяОтрасль(industry: string): boolean {
  return industryKey(industry) === "медицина";
}

/** Текст отказа на пересборку у немедицинской организации — один на оба роута */
