// Кого задела правка формы клиники.
//
// Сохранение формы всегда пересобирало всех 21 пациента, даже когда
// руководитель поправил одну цену. Это несколько минут ожидания и около
// 300 ₽ на ровном месте, но хуже другое: пересборка стирает вычитанные
// врачом случаи и документы диагностики у пациентов, которых правка
// вообще не касалась.
//
// Здесь — единственный ответ на вопрос «кого касается». Функция чистая
// и лежит отдельно от роутов намеренно: она решает, за что мы заплатим
// и что потеряем, и её проверяет `npm run check:staleness`.
//
// ЧЕГО ЗДЕСЬ НЕТ: цены. Она доходит до модели (case_generator.py:407 кладёт
// её в прайс промпта), но в готовых текстах случаев не остаётся: по всем 42
// пресетным файлам сумма встречается только в clinic.ts, а в анамнезах,
// описаниях и возражениях — ни одной. Цену называет менеджер вслух во время
// разговора. Значит самая частая правка руководителя не стоит ни рубля.
//
// А вот описание услуги здесь ЕСТЬ, и это не симметрия ради красоты: оно
// уходит отдельной строкой «что входит» в подбор услуги под диагноз
// (clinical_picture.py:305-312) и в написание прозы (case_generator.py:407),
// а слот «помогает» у случая построен вокруг того, что входит в сумму.
// Переписали описание — изменилось то, чем менеджер снимает страх.

/** Клиника до и после правки — только то, от чего зависит случай. */
export interface СнимокКлиники {
  city: string | null;
  industry: string;
  services: { name: string; description: string | null }[];
  diagnoses: { name: string; complaint: string }[];
}

/** Случай глазами сверки: чей он и из чего вырос. */
export interface ПроисхождениеСлучая {
  patientId: string;
  diagnosisName: string | null;
  serviceName: string | null;
}

/**
 * Сравнение имён нечувствительно к регистру и краям.
 *
 * Иначе исправленный пробел в конце названия услуги читался бы как
 * «услуга исчезла» и оплачивался пересборкой двадцати одного пациента.
 */
const ключ = (значение: string) => значение.trim().toLowerCase();

/**
 * Чьи случаи правка сделала неверными. Возвращает patientId.
 *
 * Правило одно: случай затронут, если исчезла или переписана та часть
 * клиники, на которой он стоит. Всё остальное — не наше дело.
 */
export function затронутыеСлучаи(
  было: СнимокКлиники,
  стало: СнимокКлиники,
  случаи: ПроисхождениеСлучая[]
): string[] {
  // Отрасль задаёт болезнь, город — быт: транспорт, районы, расстояния.
  // Меняется любое из двух — прежними не остаётся никто
  if (
    ключ(было.industry) !== ключ(стало.industry) ||
    ключ(было.city ?? "") !== ключ(стало.city ?? "")
  ) {
    return случаи.map((с) => с.patientId);
  }

  // Имена свёрнуты в Map, поэтому одинаковые имена в списке недопустимы —
  // при них выживает последняя строка, и правка первой проходит незамеченной.
  // Уникальность держит роут (PUT /api/organization), здесь она предполагается
  const описаниеБыло = new Map(
    было.services.map((у) => [ключ(у.name), (у.description ?? "").trim()])
  );
  const описаниеСтало = new Map(
    стало.services.map((у) => [ключ(у.name), (у.description ?? "").trim()])
  );
  const жалобаБыла = new Map(было.diagnoses.map((д) => [ключ(д.name), ключ(д.complaint)]));
  const жалобаСтала = new Map(стало.diagnoses.map((д) => [ключ(д.name), ключ(д.complaint)]));

  return случаи
    .filter((случай) => {
      // Происхождение неизвестно — случай собран до появления этих полей.
      // Считаем затронутым: оставить его на удалённом диагнозе молча хуже,
      // чем пересобрать лишнего
      if (!случай.diagnosisName || !случай.serviceName) return true;

      const диагноз = ключ(случай.diagnosisName);
      const стала = жалобаСтала.get(диагноз);
      // Диагноз убрали из списка — случай остался без опоры
      if (стала === undefined) return true;

      // Жалобу переписали: от неё генератор и отталкивался, значит человек
      // теперь приходит с другим. Сравниваем со старой, а не с пустотой:
      // диагноз мог появиться в списке уже после сборки случая, и тогда
      // сравнивать не с чем — трогать нечего
      const была = жалобаБыла.get(диагноз);
      if (была !== undefined && была !== стала) return true;

      const услуга = ключ(случай.serviceName);
      const описание = описаниеСтало.get(услуга);
      // Услугу убрали — менеджеру больше нечего продавать этому человеку
      if (описание === undefined) return true;
      // Описание переписали: слот «помогает» у случая вырос из прежнего
      // «что входит». Сравниваем со старым по той же причине, что и жалобу
      const былоОписание = описаниеБыло.get(услуга);
      if (былоОписание !== undefined && былоОписание !== описание) return true;

      return false;
    })
    .map((случай) => случай.patientId);
}
