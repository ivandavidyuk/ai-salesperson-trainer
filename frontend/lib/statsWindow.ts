// Какие разговоры попадают в статистику менеджера.
//
// Одно место на всех, кто её считает: главную менеджера и витрину отдела
// у руководителя. Разъедься эти два фильтра — и обнулённая статистика
// пропала бы в одном экране, но осталась в другом, а понять, какой из них
// врёт, было бы не по чему.

/**
 * Условие выборки завершённых разговоров одного менеджера.
 *
 * @param statsResetAt отметка обнуления. Руководитель может обнулить
 * статистику менеджера — первые разговоры уходят на освоение интерфейса
 * и портят картину. Данные при этом не удаляются: считаем от этой даты,
 * поэтому «вернуть» — это обнулить поле, и ошибка нажатия обратима.
 *
 * Строгое `gt`, а не `gte`: обнуление в тот же миг, когда закончился
 * разговор, не должно оставлять его наполовину внутри.
 *
 * Разговор без единой реплики — не разговор. Такие сессии остаются, когда
 * не поднялся микрофон и человек закрыл окно через десять секунд: у Ивана
 * их набралось пять из пятидесяти шести, и каждая тянула вниз среднюю
 * длину и сидела в знаменателе процента сделок как незакрытая. Данные
 * не удаляем — только не считаем.
 */
export function завершённые(userId: string, statsResetAt: Date | null) {
  return {
    userId,
    status: "completed" as const,
    messages: { some: {} },
    ...(statsResetAt ? { startedAt: { gt: statsResetAt } } : {}),
  };
}
