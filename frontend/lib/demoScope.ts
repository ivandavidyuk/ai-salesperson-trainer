import { industryKey, type IndustryKey } from "../scripts/patient-prompt";

/**
 * Кого показываем собственнику: средний, лёгкий и сложный. Три разных
 * человека по полу, возрасту и манере — так слышно, что это не один голос
 * с разными анкетами, а разные люди.
 *
 * Сложным до 14.09 был Станислав Геннадьевич, и вся тройка оказывалась
 * старше пятидесяти: молодого пациента собственник в демо не слышал вовсе.
 * Иван заменил его на Юлию Андреевну, 34, — волевую, вымотанную, ценящую
 * своё время. Уровень сложности у тройки при этом остался тем же, и на три
 * разговора по-прежнему приходится ровно три пациента.
 *
 * Ключ — имя: seed-patients ищет пациента именно по нему, id случайные.
 *
 * Тройка своя у каждой отрасли (18.09): первым стоит тот, в ком собственник
 * узнает своего клиента. У клиник это Тамара Михайловна; у офиса продаж —
 * Дарья Олеговна: семья с ребёнком и семейной ипотекой — 86 % сделок
 * с новостройками (docs/Каркас недвижимости.md, п. 7, решение 17.09).
 */
const ДЕМО_КЛИЕНТЫ_ПО_ОТРАСЛИ: Record<IndustryKey, string[]> = {
  медицина: ["Тамара Михайловна", "Джамшид Толибович", "Юлия Андреевна"],
  недвижимость: ["Дарья Олеговна", "Тамара Михайловна", "Юлия Андреевна"],
};

/** Кто открыт в демо на разговоры у организации этой отрасли */
export function демоКлиенты(industry: string): string[] {
  return ДЕМО_КЛИЕНТЫ_ПО_ОТРАСЛИ[industryKey(industry)];
}

/** Только полный разговор: этапные тренировки собственнику не открываем */
export const ДЕМО_ТИП = "full";

