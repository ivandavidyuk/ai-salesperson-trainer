/** Описание упражнения словами отрасли */
export function описаниеУпражнения(
  id: string,
  описание: string,
  ключ: IndustryKey
): string {
  return ОПИСАНИЯ_УПРАЖНЕНИЙ[ключ]?.[id] ?? словомОтрасли(описание, ключ);
}

/**
 * Совет или мотивация дня, написанные про медицину, — «часть медицинской
 * команды», «план лечения». Заменой слова их не спасти, поэтому
 * немедицинской организации такие тексты не показываются вовсе
 */
export function медицинскийТекст(текст: string): boolean {
  return /пациент|клиник|врач|лечени|терапи|диагноз|заключени|медицин|здоровь|рецепт/i.test(текст);
}
