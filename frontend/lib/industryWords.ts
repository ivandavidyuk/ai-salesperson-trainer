// у офиса продаж.
//
// Один словарь на все экраны, а не условия в каждом компоненте: так видно
// разом, как звучит продукт для отрасли, и новая отрасль — это новая колонка
// здесь, а не поиск по двадцати файлам. У клиник каждая строка — дословно та,
// что стояла в разметке до 18.09: их интерфейс не меняется ни на букву.
//
// Модуль чистый — без React и Prisma: его читают и роуты API, и компоненты.
// Разборщик отрасли — крошечный модуль scripts/industry-key.ts, подключён
// относительным путём: так словарь открывается и из скриптов под ts-node,
// и в браузерный бандл не едет текст промптов.

import { industryKey, type IndustryKey } from "../scripts/industry-key";

export type { IndustryKey };

/**
 * Отрасль организации в cookie — латиницей: значение cookie не должно
 * зависеть от кодировки. Нужна корневому layout, чтобы первая же отрисовка
 * страницы шла словами своей отрасли, а не мигала «Пациентами» до ответа API
 */
export const ОТРАСЛЬ_COOKIE = "podhod_industry";

const СЛАГИ: Record<IndustryKey, string> = {
  медицина: "medicine",
  недвижимость: "realty",
};

export function слагОтрасли(ключ: IndustryKey): string {
  return СЛАГИ[ключ];
}

/** Ключ из cookie; всё незнакомое — медицина, как и у разборщика отрасли */
export function ключИзСлага(слаг: string | null | undefined): IndustryKey {
  return слаг === СЛАГИ.недвижимость ? "недвижимость" : "медицина";
}

