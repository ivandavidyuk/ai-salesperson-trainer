// Пороги оценок разговора. Вынесены отдельно, чтобы одно и то же число
// не означало разное в разных местах интерфейса: бейдж в списке разговоров
// и полосы этапов в разборе красятся по одной шкале.

/** Ниже этого значения оценка считается слабой и красится в янтарный. */
export const SCORE_WARN_BELOW = 6.2;

/** От этого значения оценка считается сильной (зелёный бейдж). */
export const SCORE_GOOD_FROM = 8;

/** Ниже этого значения оценка тревожная — красная. */
export const SCORE_BAD_BELOW = 4;

/**
 * Ступень оценки — общая для бейджей, цифр и полос.
 *
 * Появилась вместе со страницей статистики отдела: там у оценки есть красная
 * ступень, которой раньше не было, и без общего помощника одно и то же число
 * красилось бы на разных экранах по-разному.
 */
/** Чем закончился разговор — совпадает с enum DealOutcome в схеме БД. */
export type DealOutcome = "paid" | "refused" | "not_asked";

/**
 * Закрылась ли сделка. В интерфейсе исход сведён к одному факту.
 *
 * `refused` и `not_asked` **намеренно не различаются на экране** — оба
 * читаются как «Сделка не закрыта». В базе они по-прежнему разные, и разница
 * важна для механизма; менеджеру её несут оценка этапа «Закрытие сделки»
 * и точка роста, а не сама плашка.
 *
 * Решение обсуждалось: сначала исход показывался тремя состояниями, потом
 * двумя фактами («предложение» + «ответ»). Обе версии дробили внимание там,
 * где нужен один ответ — получилось или нет. Если различие снова понадобится
 * с одного взгляда, оно вернётся подписью под фразой, а не третьим видом
 * плашки.
 */
export function isDealClosed(outcome: DealOutcome): boolean {
  return outcome === "paid";
}

/** Что написано на плашке исхода: фраза и оттиск справа. */
export const OUTCOME_LABELS: Record<
  DealOutcome,
  { title: string; stamp: string }
> = {
  paid: { title: "Сделка закрыта", stamp: "ОПЛАЧЕНО" },
  refused: { title: "Сделка не закрыта", stamp: "НЕ ОПЛАЧЕНО" },
  not_asked: { title: "Сделка не закрыта", stamp: "НЕ ОПЛАЧЕНО" },
};

/**
 * Порог, с которого показываем процент закрытых сделок, а не «1 из 3».
 *
 * На двух-трёх разговорах процент врёт: один закрытый из двух даёт 50%,
 * и это ничего не значит. Правило общее для главной и статистики отдела —
 * иначе один и тот же менеджер выглядел бы на них по-разному.
 */
export const DEALS_RATE_MIN_CONVERSATIONS = 5;

/**
 * Как показать долю закрытых сделок.
 *
 * Знаменатель — ВСЕ завершённые разговоры, а не только разобранные:
 * незакрытая сделка не должна прятаться за «разбор пока не пришёл».
 */
export function formatDealsRate(
  paid: number,
  total: number
): { label: string; hint: string | null } {
  if (total === 0) return { label: "—", hint: null };
  if (total < DEALS_RATE_MIN_CONVERSATIONS) {
    return {
      label: `${paid} из ${total}`,
      hint: "мало данных · процент покажем с пяти разговоров",
    };
  }
  return { label: `${Math.round((paid / total) * 100)}%`, hint: null };
}

export type ScoreTone = "gold" | "good" | "brand" | "warn" | "bad";

export function scoreTone(score: number): ScoreTone {
  if (score >= 10) return "gold";
  if (score >= SCORE_GOOD_FROM) return "good";
  if (score >= SCORE_WARN_BELOW) return "brand";
  if (score >= SCORE_BAD_BELOW) return "warn";
  return "bad";
}

