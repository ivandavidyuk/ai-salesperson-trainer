// Услуга, подобранная под диагноз пациента, — то, что менеджеру предстоит
// продать. Приходит вместе с результатом диагностики: по WebSocket на экране
// звонка и в ответе API расшифровки.
//
// null — «услуга не подобрана». Так бывает в двух случаях, и для менеджера
// они одно и то же: у случая нет услуги вовсе (диагноз без лечащей услуги
// в прайсе, как было с пресбиопией) либо услуга из случая уже удалена из
// прайса. Продать то, чего нет в прайсе, нельзя, а имя без цены читалось бы
// как подсказка.

export interface CaseService {
  /** Название дословно из прайса клиники */
  name: string;
  /** Цена строкой, как в прайсе: «от 60 000 ₽ за глаз», «по договорённости» */
  price: string;
  /**
   * Описание из прайса — что входит. У курсов это состав: «Капельницы — 5,
   * аутоплазмотерапия — 3 процедуры». Без него менеджер видел «Курс при
   * грыже» и не знал, что продаёт (Jamaica, 22.10). Пустая строка — нет
   */
  description: string;
}

/**
 * Состав списком, если описание — перечень «что — сколько» через запятую,
 * как у курсов: «Капельницы — 5, лазерная терапия — 7 сеансов». Иначе
 * null, и описание показывается как есть: «Операция 20 минут, капельная
 * анестезия, хрусталик…» запятыми не делится на пункты
 */
export function составСписком(description: string): string[] | null {
  const части = description.split(/,\s+/).map((часть) => часть.trim()).filter(Boolean);
  if (части.length < 2 || !части.every((часть) => /\s—\s*\d/.test(часть))) return null;
  return части.map((часть) => часть.charAt(0).toUpperCase() + часть.slice(1));
}

/** Фраза для состояния «не подобрана» — одна на оба экрана */
export const SERVICE_NOT_MATCHED = "В прайсе клиники нет услуги под этот диагноз.";
