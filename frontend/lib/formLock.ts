// Карточка клиники, закрытая для правки руководителем.
//
// Зачем. Клинике, которую мы настроили сами (Jamaica, 14.10: прайс и курсы
// под её назначения, вычитанные случаи), правка прайса из кабинета
// запустила бы платную пересборку и заменила вычитанных пациентов
// сгенерированными. Видеть прайс и диагнозы руководитель может, менять —
// через нас.
//
// Замок стоит на сервере, а не только в форме: кнопку можно не показать,
// но запрос к API от этого не исчезает. Проверяют его те же два входа,
// что и демо-замок: сохранение формы и пересборка.

import { prisma } from "@/lib/db";

export const КАРТОЧКА_ЗАКРЫТА =
  "Карточка настроена вместе с нами и закрыта для правки. " +
  "Чтобы что-то поменять, напишите нам.";

/** Закрыта ли карточка организации для правки руководителем */
export async function карточкаЗакрыта(organizationId: string): Promise<boolean> {
  const org = await prisma.organization.findUnique({
    where: { id: organizationId },
    select: { formLocked: true },
  });
  return Boolean(org?.formLocked);
}
