// Насколько человек освоился с тренажёром — по этому подсказки решают,
// показываться ли.
//
// Признак серверный и по пользователю, а не по устройству: менеджеры
// Jamaica занимаются с разных телефонов по очереди, и отметка в браузере
// показала бы подсказку опытному и спрятала бы её от новичка.

import { prisma } from "@/lib/db";

export interface Освоение {
  /** Открывал ли хоть раз документ диагностики в каком-нибудь разговоре */
  открывалДокумент: boolean;
}

export async function освоение(userId: string): Promise<Освоение> {
  const сДокументом = await prisma.session.findFirst({
    where: { userId, diagnosticsShownAt: { not: null } },
    select: { id: true },
  });
  return { открывалДокумент: сДокументом !== null };
}

/** Метка у «Результата диагностики» — пока документ ни разу не открывали */
export const подсказкаКДокументу = (о: Освоение) => !о.открывалДокумент;
