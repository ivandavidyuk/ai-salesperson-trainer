// Видимые поля пациента под конкретную клинику.
//
// Личность пациента одна на все клиники, а с чем человек пришёл — зависит
// от отрасли, и это лежит в PatientCase. Долгое время случай писался,
// но НИ ОДИН роут его не читал: анамнез, карточка и возражения везде
// брались напрямую из Patient. Из-за этого вся работа генератора никому
// не показывалась — в проде из 21 пациента анамнез был заполнен у одного,
// написанного руками.
//
// Backend в этом месте давно делает то же самое для промпта роли:
// COALESCE(pc."prompt", p."prompt"). Здесь тот же приём для видимых полей.

/** Что берём из случая. Совпадает с видимыми полями Patient. */
export const ВИДИМЫЕ_ПОЛЯ_СЛУЧАЯ = {
  anamnesis: true,
  description: true,
  objections: true,
} as const;

/**
 * Условие выборки случая под организацию пользователя.
 *
 * У пользователя без организации случаев нет по определению — тогда
 * не запрашиваем ничего, и видимые поля останутся из Patient.
 */
export function случайДляОрганизации(organizationId: string | null | undefined) {
  if (!organizationId) return undefined;
  return {
    where: { organizationId },
    select: ВИДИМЫЕ_ПОЛЯ_СЛУЧАЯ,
    take: 1,
  };
}

interface ВидимыеПоля {
  description?: string | null;
  anamnesis?: string | null;
  objections?: string[];
}

interface СПациентскимСлучаем extends ВидимыеПоля {
  cases?: ВидимыеПоля[];
}

/**
 * Накладывает случай под клинику поверх полей пациента.
 *
 * Пустая строка считается отсутствием: недособранный случай не должен
 * стирать то, что написано руками. Поле `cases` из ответа убирается —
 * наружу отдаём плоского пациента, как и раньше.
 */
export function сНаложеннымСлучаем<T extends СПациентскимСлучаем>(
  patient: T
): Omit<T, "cases"> {
  const { cases, ...остальное } = patient;
  const случай = cases?.[0];
  if (!случай) return остальное;

  // Перекрываем ТОЛЬКО то, что роут и правда запрашивал. Иначе помощник
  // дописал бы в ответ поле, которого там быть не должно: возражения
  // менеджеру не отдаются вовсе, и появиться они не имеют права
  const результат = { ...остальное } as ВидимыеПоля;
  if ("anamnesis" in остальное && случай.anamnesis) {
    результат.anamnesis = случай.anamnesis;
  }
  if ("description" in остальное && случай.description) {
    результат.description = случай.description;
  }
  if ("objections" in остальное && случай.objections?.length) {
    результат.objections = случай.objections;
  }
  return результат as Omit<T, "cases">;
}
