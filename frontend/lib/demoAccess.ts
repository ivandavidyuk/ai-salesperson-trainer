// Демо-доступ. Режима два, и они не заменяют друг друга.
//
// **Сутки** — пара аккаунтов (РОП и менеджер), выданная после демо-звонка.
// Часы жизни тикают не с выдачи, а с ПЕРВОГО разговора: выданная в пятницу
// вечером пара не сгорает к понедельнику, пока её не трогали.
//
// **Разговоры** — один аккаунт собственнику, который на созвоне ещё не был.
// Ему нужно услышать, что клиент живой, и увидеть разбор, а не осваивать
// тренажёр: три завершённых разговора, три клиента, только полный разговор.
// Остальных клиентов и типы тренировки из списков не убираем — они видны
// заблокированными, и это работает на воронку: собственник видит, что
// открывается на полном доступе.
//
// После истечения любого из режимов новые разговоры закрыты, но вход
// и разборы живут ещё неделю: второй созвон опирается на просмотр разборов,
// и он случается через день-два.
//
// Потолок расхода здесь не считается — это делает обычный месячный лимит
// часов (lib/hours.ts): демо-организации он ставится в 3 часа при выдаче.

import { prisma } from "@/lib/db";
import { ЕСТЬ_РЕПЛИКА_МЕНЕДЖЕРА } from "@/lib/statsWindow";

// Что именно открыто в демо — в lib/demoScope.ts: те константы нужны
// и скрипту выдачи, который Prisma-модули импортировать не может

/** Сколько живёт суточное демо после первого разговора */
const СУТКИ_МС = 24 * 60 * 60 * 1000;
/** Сколько после истечения доступны вход и разборы */
const ХВОСТ_МС = 7 * СУТКИ_МС;

export interface DemoStatus {
  organizationId: string;
  /** Чем меряется доступ */
  режим: "сутки" | "разговоры";
  /**
   * Суточное демо: когда истекает; null — разговор ещё не начинали.
   * Демо на разговоры: когда исчерпано; null — разговоры ещё остались.
   */
  expiresAt: Date | null;
  /** Сколько разговоров осталось. null у суточного демо */
  осталось: number | null;
  /** Доступ выбран: новые разговоры не начинаются */
  разговорыЗакрыты: boolean;
  /** Вышла и неделя разборов: вход закрыт целиком */
  входЗакрыт: boolean;
}

/**
 * Статус демо-доступа пользователя. null — обычный пользователь,
 * никаких демо-ограничений.
 */
export async function демоСтатус(
  userId: string,
  now: Date = new Date()
): Promise<DemoStatus | null> {
  const user = await prisma.user.findUnique({
    where: { id: userId },
    select: {
      organization: {
        select: {
          id: true,
          isDemo: true,
          demoExpiresAt: true,
          demoTalksLimit: true,
        },
      },
    },
  });
  const org = user?.organization;
  if (!org?.isDemo) return null;

  const хвостВышел = (момент: Date | null) =>
    момент !== null && now.getTime() > момент.getTime() + ХВОСТ_МС;

  if (org.demoTalksLimit === null) {
    const истекает = org.demoExpiresAt;
    return {
      organizationId: org.id,
      режим: "сутки",
      expiresAt: истекает,
      осталось: null,
      разговорыЗакрыты:
        истекает !== null && now.getTime() > истекает.getTime(),
      входЗакрыт: хвостВышел(истекает),
    };
  }

  const проведено = await prisma.session.count({
    where: {
      status: "completed",
      // Брошенная на первой секунде сессия попытку не съедает — то же
      // условие, которым пустые разговоры убраны из статистики. Реплики
      // пациента мало: в части упражнений он здоровается первым
      ...ЕСТЬ_РЕПЛИКА_МЕНЕДЖЕРА,
      user: { organizationId: org.id },
    },
  });
  const осталось = Math.max(0, org.demoTalksLimit - проведено);
  const закрыты = осталось === 0;

  // Момент исчерпания засекаем лениво, при первом же чтении статуса после
  // последнего разговора. В самом завершении разговора это сделать негде:
  // он закрывается тремя путями — кнопкой «Завершить», обрывом связи
  // и сторожем на бэкенде, — а чтение статуса общее для всех трёх
  let исчерпано = org.demoExpiresAt;
  if (закрыты && исчерпано === null) {
    await prisma.organization.updateMany({
      where: { id: org.id, isDemo: true, demoExpiresAt: null },
      data: { demoExpiresAt: now },
    });
    исчерпано = now;
  }

  return {
    organizationId: org.id,
    режим: "разговоры",
    expiresAt: исчерпано,
    осталось,
    разговорыЗакрыты: закрыты,
    входЗакрыт: хвостВышел(исчерпано),
  };
}

/**
 * Демо ли эта организация — без чтения пользователя.
 *
 * Нужна там, где решение зависит от организации, а не от того, вышли ли
 * сутки: пересборка случаев демо-клинике закрыта всегда, и в первый час
 * доступа тоже.
 */
export async function этоДемо(organizationId: string): Promise<boolean> {
  const org = await prisma.organization.findUnique({
    where: { id: organizationId },
    select: { isDemo: true },
  });
  return Boolean(org?.isDemo);
}

/**
 * Демо ли это на разговоры — то есть надо ли гасить лишних клиентов и типы
 * тренировки. Отдельно от `демоСтатус`, потому что спискам не нужен счёт
 * разговоров: им хватает признака режима.
 */
export async function демоНаРазговоры(
  organizationId: string | null
): Promise<boolean> {
  if (!organizationId) return false;
  const org = await prisma.organization.findUnique({
    where: { id: organizationId },
    select: { isDemo: true, demoTalksLimit: true },
  });
  return Boolean(org?.isDemo && org.demoTalksLimit !== null);
}

