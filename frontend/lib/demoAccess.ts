/**
 * Засекает первый разговор суточного демо: с этого момента сутки тикают.
 *
 * Идемпотентно и безопасно к гонке двух аккаунтов пары: условие
 * `demoExpiresAt: null` пропускает только первый вызов, второй — no-op.
 * Обычную организацию не трогает по условию `isDemo: true`, демо
 * на разговоры — по `demoTalksLimit: null`: там это поле значит момент
 * исчерпания, и заполнять его на старте нельзя.
 */
export async function засечьПервыйРазговор(
  organizationId: string,
  now: Date = new Date()
): Promise<void> {
  await prisma.organization.updateMany({
    where: {
      id: organizationId,
      isDemo: true,
      demoTalksLimit: null,
      demoExpiresAt: null,
    },
    data: { demoExpiresAt: new Date(now.getTime() + СУТКИ_МС) },
  });
}
