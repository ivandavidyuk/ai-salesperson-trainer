// Проверка сверки «кого задела правка клиники». Запуск: npm run check:staleness
//
// Решает эта логика вещь дорогую и необратимую: кого пересобрать за деньги
// и у кого при этом стереть вычитанный врачом случай вместе с документом
// диагностики. Ошибка в обе стороны плоха по-разному. Пересобрали лишнего —
// потеряли вычитку и заплатили; не пересобрали нужного — пациент остался
// с диагнозом, которого в клинике больше нет, и это никак не видно.
//
// Тестового раннера во фронте нет (тесты живут в backend/tests), поэтому
// проверка сделана скриптом — как check:prompts, и стоит в CI рядом с ним.

import {
  затронутыеСлучаи,
  type ПроисхождениеСлучая,
  type СнимокКлиники,
} from "../lib/caseStaleness";

const КЛИНИКА: СнимокКлиники = {
  city: "Москва",
  industry: "офтальмология",
  services: [
    { name: "Замена хрусталика с имплантацией ИОЛ" },
    { name: "Лазерная коррекция зрения" },
    { name: "Подбор очков и контактных линз" },
  ],
  diagnoses: [
    { name: "Возрастная катаракта", complaint: "стало мутно, будто через плёнку" },
    { name: "Миопия", complaint: "вдаль всё расплывается" },
    { name: "Пресбиопия", complaint: "мелкий шрифт приходится отодвигать" },
  ],
};

const СЛУЧАИ: ПроисхождениеСлучая[] = [
  { patientId: "катаракта", diagnosisName: "Возрастная катаракта", serviceName: "Замена хрусталика с имплантацией ИОЛ" },
  { patientId: "миопия", diagnosisName: "Миопия", serviceName: "Лазерная коррекция зрения" },
  { patientId: "пресбиопия", diagnosisName: "Пресбиопия", serviceName: "Подбор очков и контактных линз" },
];

/** Копия клиники с правкой — чтобы случаи не мутировали между проверками */
function правка(изменения: Partial<СнимокКлиники>): СнимокКлиники {
  return {
    city: КЛИНИКА.city,
    industry: КЛИНИКА.industry,
    services: КЛИНИКА.services.map((у) => ({ ...у })),
    diagnoses: КЛИНИКА.diagnoses.map((д) => ({ ...д })),
    ...изменения,
  };
}

interface Проверка {
  что: string;
  стало: СнимокКлиники;
  случаи?: ПроисхождениеСлучая[];
  ждём: string[];
}

const ПРОВЕРКИ: Проверка[] = [
  {
    что: "ничего не менялось",
    стало: правка({}),
    ждём: [],
  },
  {
    что: "цена услуги (самая частая правка) — не задевает никого",
    стало: правка({
      services: [
        { name: "Замена хрусталика с имплантацией ИОЛ" },
        { name: "Лазерная коррекция зрения" },
        { name: "Подбор очков и контактных линз" },
      ],
    }),
    ждём: [],
  },
  {
    что: "добавили услугу — прежние случаи целы",
    стало: правка({
      services: [...КЛИНИКА.services, { name: "Лечение глаукомы" }],
    }),
    ждём: [],
  },
  {
    что: "добавили диагноз — прежние случаи целы",
    стало: правка({
      diagnoses: [...КЛИНИКА.diagnoses, { name: "Астигматизм", complaint: "двоится" }],
    }),
    ждём: [],
  },
  {
    что: "удалили услугу — затронут только тот, кто её продавал",
    стало: правка({
      services: КЛИНИКА.services.filter((у) => у.name !== "Лазерная коррекция зрения"),
    }),
    ждём: ["миопия"],
  },
  {
    что: "удалили диагноз — затронут только его носитель",
    стало: правка({
      diagnoses: КЛИНИКА.diagnoses.filter((д) => д.name !== "Пресбиопия"),
    }),
    ждём: ["пресбиопия"],
  },
  {
    что: "переписали жалобу диагноза — затронут его носитель",
    стало: правка({
      diagnoses: КЛИНИКА.diagnoses.map((д) =>
        д.name === "Миопия" ? { ...д, complaint: "к вечеру глаза устают" } : д
      ),
    }),
    ждём: ["миопия"],
  },
  {
    что: "сменилась отрасль — затронуты все",
    стало: правка({ industry: "стоматология" }),
    ждём: ["катаракта", "миопия", "пресбиопия"],
  },
  {
    что: "сменился город — затронуты все",
    стало: правка({ city: "Санкт-Петербург" }),
    ждём: ["катаракта", "миопия", "пресбиопия"],
  },
  {
    что: "лишний пробел и регистр в названии — не правка",
    стало: правка({
      services: [
        { name: "  замена хрусталика С ИМПЛАНТАЦИЕЙ ИОЛ " },
        { name: "Лазерная коррекция зрения" },
        { name: "Подбор очков и контактных линз" },
      ],
    }),
    ждём: [],
  },
  {
    что: "случай без происхождения — затронут любой правкой",
    стало: правка({}),
    случаи: [
      { patientId: "старый", diagnosisName: null, serviceName: null },
      ...СЛУЧАИ,
    ],
    ждём: ["старый"],
  },
  {
    что: "диагноз добавлен после сборки случая — жалоба сравнению не подлежит",
    стало: правка({}),
    случаи: [
      // Диагноза «Кератоконус» не было в прежнем списке и нет в новом:
      // случай на нём стоять не может, значит затронут по «диагноз исчез»
      { patientId: "чужой", diagnosisName: "Кератоконус", serviceName: "Лазерная коррекция зрения" },
    ],
    ждём: ["чужой"],
  },
];

function main(): void {
  const беды: string[] = [];

  for (const проверка of ПРОВЕРКИ) {
    const получилось = затронутыеСлучаи(КЛИНИКА, проверка.стало, проверка.случаи ?? СЛУЧАИ)
      .slice()
      .sort();
    const ждём = проверка.ждём.slice().sort();
    const сошлось = JSON.stringify(получилось) === JSON.stringify(ждём);
    console.log(
      `  ${сошлось ? "✓" : "✗"} ${проверка.что.padEnd(58)} ` +
        `${получилось.length ? получилось.join(", ") : "никого"}`
    );
    if (!сошлось) {
      беды.push(`${проверка.что}: ждали [${ждём.join(", ")}], получили [${получилось.join(", ")}]`);
    }
  }

  if (беды.length > 0) {
    console.error(`\n${беды.length} расхождений:`);
    for (const беда of беды) console.error(`  — ${беда}`);
    process.exit(1);
  }
  console.log(`\nВсё сходится: ${ПРОВЕРКИ.length} проверок.`);
}

main();
