// Пресетные случаи в markdown — под чтение человеком, а не машиной.
//
//   npm run dump:presets:md -- --куда "C:\путь\к\папке"
//
// Зачем отдельно от dump:presets. Тот отдаёт JSON критику: там только то,
// что критик читает, и в один ряд. Здесь наоборот — файл на отрасль,
// пациенты по порядку, у каждого сначала основание выбора (четыре
// измерения), потом что увидит менеджер, потом что знает сам пациент.
//
// Формат повторяет backend/scripts/generate_for_review.py: Дима читал
// анамнезы в нём, и менять привычную раскладку под ту же работу незачем.

import { existsSync, readFileSync, writeFileSync } from "fs";
import { join } from "path";

import { PATIENT_PORTRAITS } from "../lib/patientAvatars";
import { PROFILES } from "./patients";
import { ПРЕСЕТЫ } from "./presets";
import { клиническая, type Preset } from "./presets/types";

function аргумент(имя: string): string | null {
  const i = process.argv.indexOf(`--${имя}`);
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : null;
}

/** Возраст из личности — в заголовке он нужнее, чем в карточке */
function возраст(имя: string): string {
  const профиль = PROFILES.find((p) => p.name === имя);
  const найдено = профиль?.personality.identity.match(
    /,\s*(\d{1,3})\s*(год|года|лет)/,
  );
  return найдено ? `${найдено[1]} ${найдено[2]}` : "";
}

const УРОВНИ: Record<string, string> = {
  easy: "лёгкий",
  mid: "средний",
  hard: "сложный",
};

/**
 * Реплики грамотного менеджера из сценария симулятора: эксперту по отрасли
 * важно видеть не только клиента, но и то, чем мы считаем хорошую работу
 * с ним, — с этим он и будет спорить. Сценарий лежит рядом с симулятором,
 * имя файла — от слага портрета; комментарии (строки с #) опускаем
 */
function репликиМенеджера(имя: string): string[] {
  const слаг = PATIENT_PORTRAITS[имя];
  if (!слаг) return [];
  const путь = join(
    __dirname, "..", "..", "backend", "scripts", "dialogues", `realty-${слаг}.txt`,
  );
  if (!existsSync(путь)) return [];
  return readFileSync(путь, "utf8")
    .split(/\r?\n\s*\r?\n/)
    .map((абзац) =>
      абзац
        .split(/\r?\n/)
        .filter((строка) => !строка.startsWith("#"))
        .join(" ")
        .trim(),
    )
    .filter(Boolean);
}

/** Офис продаж: читает не врач, а человек из продаж недвижимости */
function отчётОфиса(пресет: Preset): string {
  const { clinic, cases } = пресет;
  const куски: string[] = [
    `# Покупатели для тренажёра: ${clinic.industryLabel}`,
    "",
    `Покупателей ${cases.length}. Это клиенты, с которыми менеджер отдела продаж ` +
      "разговаривает голосом в тренажёре. Характеры людей проверены на клиниках " +
      "и не обсуждаются — проверяем всё, что про недвижимость: с чем человек " +
      "пришёл, какие у него деньги, чего он боится и как его ведёт грамотный " +
      "менеджер.",
    "",
    "## Что просим проверить",
    "",
    "1. **Повод.** Приходят ли такие люди в офис продаж с таким запросом — или",
    "   это придумано. Типичен ли возраст и состав семьи.",
    "2. **Деньги.** Сходятся ли цифры: цена, взнос, ставка, платёж, срок.",
    "   Действуют ли названные программы и условия так, как написано, — семейная",
    "   ипотека, рассрочка от застройщика, программа с закреплённой ставкой,",
    "   скидка за полную оплату.",
    "3. **Порядок сделки.** Бронь, договор, эскроу или аккредитив, регистрация,",
    "   ключи, дистанционная сделка, зачёт своей квартиры — так ли это делается",
    "   на практике и в такие ли сроки.",
    "4. **Страхи и возражения.** Те ли это слова, которые вы слышите от таких",
    "   покупателей. Чего не хватает, что звучит фальшиво.",
    "5. **Работа менеджера.** Согласны ли вы, что именно так такого клиента",
    "   и надо вести, — или хороший менеджер сделал бы иначе.",
    "6. **Прайс.** Правдоподобны ли цены и условия для Петербурга.",
    "",
    "Пишите замечания прямо по тексту, любым способом: нам важнее «так не",
    "бывает», чем аккуратность оформления.",
    "",
    "## Прайс и условия офиса продаж",
    "",
    ...clinic.services.map((у) => `- **${у.name}** — ${у.price}. ${у.description}`),
    "",
    "---",
    "",
  ];

  for (const c of cases) {
    if (клиническая(c.picture)) continue;
    const к = c.picture;
    const профиль = PROFILES.find((p) => p.name === c.patientName);
    const уровень = профиль ? (УРОВНИ[String(профиль.difficulty)] ?? "") : "";
    const реплики = репликиМенеджера(c.patientName);
    куски.push(
      `## ${c.patientName}, ${возраст(c.patientName)}${уровень ? ` · ${уровень}` : ""}`,
      "",
      `**С чем пришёл:** ${к.reason}`,
      "",
      `**Кто так покупает:** ${к.onset}`,
      "",
      `**Насколько это обычно:** ${к.common} — ${к.typicalFor}`,
      "",
      `**На какой он стадии:** ${к.stage}`,
      "",
      `**Чего хочет:** ${к.request}`,
      "",
      `**Что его подтолкнуло:** ${к.noticedWhen}`,
      "",
      `**Что ему подходит:** ${c.service}. ${к.fit}`,
      "",
      `**Карточка:** ${c.description}`,
      "",
      "**Заявка (её видит менеджер до разговора):**",
      "",
      `> ${c.anamnesis.split("\n").join("\n> ")}`,
      "",
      "**Зачем пришёл (это знает сам покупатель):**",
      "",
      `> ${c.case.situation}`,
      "",
      "**Чего боится именно в этой покупке:**",
      "",
      ...(c.case.fears ?? []).map((с) => `- ${с}`),
      "",
      "**Что должно прозвучать, чтобы он согласился:**",
      "",
      ...c.case.conditions.map((у) => `- ${у}`),
      "",
      "**Возражения, которых ждать:**",
      "",
      ...c.objections.map((в) => `- ${в}`),
      "",
      ...(реплики.length
        ? [
            "**Как его ведёт грамотный менеджер (реплики из нашего проверочного сценария):**",
            "",
            ...реплики.map((р, i) => `${i + 1}. ${р}`),
            "",
          ]
        : []),
      "---",
      "",
    );
  }
  return куски.join("\n");
}

function отчёт(пресет: Preset): string {
  if (пресет.clinic.отрасль !== "медицина") return отчётОфиса(пресет);
  const { clinic, cases } = пресет;
  const куски: string[] = [
    `# Случаи пациентов: ${clinic.industryLabel}`,
    "",
    `Пациентов ${cases.length}. Личности пациентов писал Дима, они не менялись — ` +
      `всё медицинское написано заново, его и проверяем.`,
    "",
    "## Что проверяем",
    "",
    "1. **Окно начала.** Может ли это состояние ВПЕРВЫЕ появиться в таком",
    "   возрасте — или оно начинается только раньше.",
    "2. **Частота.** Типичный это случай для возраста или исключение,",
    "   выданное за правило.",
    "3. **Стадия.** Названа стадия — принадлежат ли ей жалобы, или это",
    "   симптомы более поздней.",
    "4. **Условие проявления.** Заметил бы человек это при своей жизни",
    "   и своих привычках.",
    "5. **Лечение.** Лечится ли это той услугой, которую предлагают.",
    "",
    "Отдельно: не читается ли анамнез как вывод о продаже вместо находки",
    "осмотра, и не знает ли пациент заранее, что ему предложат.",
    "",
    "## Прайс клиники",
    "",
    ...clinic.services.map(
      (у) => `- **${у.name}** — ${у.price}. ${у.description}`,
    ),
    "",
    "## Диагнозы клиники",
    "",
    ...clinic.diagnoses.map(
      (д) => `- **${д.name}** (с чем приходят: ${д.complaint}) → лечим: ${д.treatedBy}`,
    ),
    "",
    "---",
    "",
  ];

  for (const c of cases) {
    // Вычитка врачом — для клиник; запрос покупателя читается иначе
    if (!клиническая(c.picture)) continue;
    const к = c.picture;
    куски.push(
      `## ${c.patientName}, ${возраст(c.patientName)}`,
      "",
      `**Диагноз:** ${к.diagnosis}`,
      "",
      `**Начинается:** ${к.onset}`,
      "",
      `**Обычное для возраста:** ${к.common} — ${к.typicalFor}`,
      "",
      `**Стадия:** ${к.stage}`,
      "",
      `**Жалобы:** ${к.complaints}`,
      "",
      `**Замечает при:** ${к.noticedWhen}`,
      "",
      `**Осмотр:** ${к.objective}`,
      "",
      `**Что с этим делают:** ${к.treatment}`,
      "",
      `**Предлагаем:** ${c.service}`,
      "",
      `**Карточка:** ${c.description}`,
      "",
      "**Анамнез (его видит менеджер до разговора):**",
      "",
      `> ${c.anamnesis.split("\n").join("\n> ")}`,
      "",
      // Документ печатается СРАЗУ за анамнезом: он от анамнеза и пишется,
      // и вычитывать их надо парой. Врач, читающий документ в отрыве,
      // не поймает главного — противоречия с историей болезни
      ...(c.diagnostics
        ? [
            "**Результат диагностики (менеджер получает по кнопке в разговоре):**",
            "",
            `> ${c.diagnostics.split("\n").join("\n> ")}`,
            "",
          ]
        : []),
      "**Зачем пришёл (это знает сам пациент):**",
      "",
      `> ${c.case.situation}`,
      "",
      "**Возражения, которых ждать:**",
      "",
      ...c.objections.map((в) => `- ${в}`),
      "",
      "---",
      "",
    );
  }
  return куски.join("\n");
}

const куда = аргумент("куда") ?? process.cwd();
for (const пресет of ПРЕСЕТЫ) {
  const путь = join(куда, `Случаи — ${пресет.clinic.industry}.md`);
  writeFileSync(путь, отчёт(пресет), "utf8");
  console.log(`${путь} · пациентов ${пресет.cases.length}`);
}
