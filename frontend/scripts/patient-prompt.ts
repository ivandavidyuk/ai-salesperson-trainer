/**
 * Отрасль и повод обращения. Подменяется целиком, личность при этом та же.
 */
export interface PatientCase {
  // Зачем пришла: повод обращения и что знает о своей проблеме
  situation: string;
  // Пока разговор о чём — пациент спокоен и отвечает охотно
  calmWhile: string;
  // Примеры речи в лексике этой отрасли. Иллюстрируют правила манеры
  // из личности, поэтому и живут отдельно от них
  mannerExamples: string;
  // Обязательные условия про саму услугу: чем снимается страх за безопасность,
  // что входит в стоимость. Идут до условий от характера
  conditions: string[];
  // Накопительные условия про услугу
  helps: string[];
  // Ситуативные страхи: чем рискует именно здесь, голосом персонажа
  // («звучит не страхом, а допросом: кто отвечает»). Форма страха у человека
  // одна, предмет подставляет отрасль. Идут после страхов характера.
  // Необязательно: случаи, собранные до появления слота, живут без него,
  // а пересборка берёт их из пресета той же отрасли
  fears?: string[];
  // Сколько денег с собой прямо сейчас — наличные и карта, с причиной.
  // Дописывается к бюджету личности одним абзацем
  moneyToday?: string;
  // Слова, принадлежащие этому случаю. Не идут в промпт: по ним проверялка
  // убеждается, что случай не протёк в личность. Заполняется вместе со
  // случаем — в том числе генератором, когда он появится
  vocabulary: string[];
}

export interface PatientRole {
  personality: PatientPersonality;
  case: PatientCase;
}

/**
 * Склеивает роль пациента из слоёв в том порядке, в котором её читает модель.
 *
 * Переносы строк сборщик НЕ расставляет: текст в слотах уже сверстан, и любая
 * переверстка изменила бы промпт, по которому персонаж уже говорит.
 *
 * Зато приводит их к LF. На Windows рабочая копия лежит в CRLF (core.autocrlf),
 * и шаблонные строки несут \r\n, а в базу промпт попадает с LF — сид
 * запускается в контейнере. Без нормализации сид, запущенный с Windows,
 * перезаписал бы промпты всем пациентам, отличаясь ровно на число строк.
 */
export function buildRolePrompt(
  role: PatientRole,
  rules: IndustryRules = МЕДИЦИНА,
): string {
  const { personality, case: patientCase } = role;
  const bullets = (items: string[]) => items.map((t) => `- ${t}`).join("\n");

  // Условия случая идут перед условиями характера: сначала «сняли страх
  // за саму услугу», потом «прошли сцену с согласующим». Нумерация начинается
  // со второго — первый номер занят условием про оплату, и автор пациента
  // им не распоряжается
  const conditions = [...patientCase.conditions, ...personality.conditions]
    .map((text, i) => `${i + 3}. ${text}`)
    .join("\n");

  // Блок финансов необязателен, и пустой не выводится вовсе: иначе добавление
  // слота переписало бы промпты всем, у кого его нет, — включая эталонный
  // «Сколько с собой» из случая дописывается к бюджету личности одним
  // абзацем — так текст клиник, где эта фраза раньше стояла в личности,
  // не меняется ни на символ
  const бюджет = personality.budget
    ? [[personality.budget, patientCase.moneyToday].filter(Boolean).join(" ")]
    : [];
  const деньги = [...(personality.finances ?? []), ...бюджет];
  const finances = деньги.length
    ? [`ОТНОШЕНИЕ К ДЕНЬГАМ:\n${bullets(деньги)}`]
    : [];

  return [
    personality.identity,
    `РЕЧЕВАЯ МАНЕРА:\n${personality.manner}\n- Примеры:\n${patientCase.mannerExamples}`,
    `ЗАЧЕМ ПРИШЛА:\n${patientCase.situation}`,
    `ПОВЕДЕНИЕ ПО СИТУАЦИИ:\n${patientCase.calmWhile}`,
    // «Не озвучивай прямо» модель прочла как «не поднимай тему»: за четыре
    // разговора 10.08 ни один пациент не спросил ни про гарантии, ни про
    // восстановление. А страх, который ни разу не прозвучал, менеджеру нечем
    // снимать — и условие засчитывается само собой
    `СТРАХИ (звучат твоими словами, но не словом «боюсь»):\n${bullets(
      personality.caseFearsFirst
        ? [...(patientCase.fears ?? []), ...personality.fears]
        : [...personality.fears, ...(patientCase.fears ?? [])],
    )}`,
    ...finances,
    // Прежние заголовки «КОГДА ТЕПЛЕТЬ» и «КОГДА ЗАКРЫВАТЬСЯ» читались как
    // рецепт и пересказывались вслух: «скажешь чётко и дашь скидку —
    // я согласен». Это ощущение, а не инструкция собеседнику
    `ОТ ЧЕГО ТЕПЛЕЕШЬ (чувствуешь, не объявляешь):\n${bullets(personality.warmsUp)}`,
    `ОТ ЧЕГО ЗАКРЫВАЕШЬСЯ (чувствуешь, не объявляешь):\n${bullets(personality.closesUp)}`,
    objectionsTiming(rules),
    TURN_SIZE,
    moneyReality(rules),
    `${paymentCondition(rules)}\n${conditions}`,
    `${HELPS_HEADER}\n${bullets([...personality.helps, ...patientCase.helps])}`,
    `КАК ТЫ ПРИНИМАЕШЬ РЕШЕНИЕ:\n${personality.decision}`,
    PROHIBITIONS,
  ]
    .join("\n\n")
    .replace(/\r\n/g, "\n");
}

/**
 * Текст личности без промпта целиком — для проверки, что случай не протёк.
 *
 * Собирается из тех же слотов, что уходят в промпт, чтобы проверка смотрела
 * на то же, что читает модель, а не на отдельно поддерживаемый список.
 */
export function personalityText(personality: PatientPersonality): string {
  return [
    personality.identity,
    personality.manner,
    ...personality.fears,
    ...(personality.finances ?? []),
    personality.budget ?? "",
    ...personality.warmsUp,
    ...personality.closesUp,
    ...personality.conditions,
    ...personality.helps,
    personality.decision,
  ].join("\n");
}
