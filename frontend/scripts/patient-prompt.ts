// Сборка роли пациента из слоёв. Используется сидом пациентов.
//
// Зачем слои, а не один текст на пациента: пациентов будет около ста, и без
// разделения каждый следующий пишется копированием предыдущего. Тогда правила,
// от которых зависит работа механизма сделки, оказываются переписаны сто раз
// в ста слегка разных версиях, и проверить это глазами уже нельзя.
//
// Здесь живёт слой механизма — 860 символов, одинаковых у всех пациентов.
// Автор пациента их не пишет и не может изменить: сборщик подставляет их сам.
// Расширить правило — значит поправить константу здесь, и оно применится ко
// всем пациентам сразу.
//
// Слоты PatientRole — то, что пишется под каждого пациента. Заголовки разделов
// выдаёт сборщик: сто пациентов не должны перепечатывать «РЕЧЕВАЯ МАНЕРА:»,
// а модель ждёт от них одну и ту же структуру.

// --- Слой механизма ---------------------------------------------------------

// Возражения появляются только после коммерческого предложения. Это правило
// механизма, а не черта характера: пациент, возражающий с первой реплики,
// не даёт менеджеру дойти до выявления потребности, и тренировка вырождается
// в отбивание заготовок.
const OBJECTIONS_TIMING = `ВОЗРАЖЕНИЯ:
До коммерческого предложения возражений нет вовсе. Они появляются, только
когда менеджер называет цену, предлагает записаться на операцию или говорит
о лечении, — и звучат твоими словами, а не заготовками.`;

// Первое обязательное условие — всегда прямое предложение оплатить, и номер
// у него всегда первый. Без предложения пациенту нечего принимать, и «сделка
// не закрыта» означало бы не отказ, а то, что закрытия никто не пробовал:
// это разные ошибки менеджера с разным лечением.
const PAYMENT_CONDITION = `ЧТО ДОЛЖНО ПРОИЗОЙТИ, ЧТОБЫ ТЫ СОГЛАСИЛАСЬ:

Обязательное — без любого из этого ты отказываешь, как бы хорошо ни шёл
разговор в остальном:
1. Менеджер прямо предложил оплатить операцию. Намёк, «вы подумайте»
   и «приходите, когда решитесь» не считаются: тебе нечего принимать.`;

// Накопительные условия отдельным механизмом не считаются: они уже растворены
// в оценках этапов, а те проходят через порог допуска. Считать их второй раз
// значило бы наказывать дважды за одно и то же.
const HELPS_HEADER = `Хорошо, но не обязательно — от этого зависит, насколько тепло ты говоришь:`;

// Блок запретов всегда идёт последним, и вклиниться после него автор пациента
// не может. Каждый запрет закрывает свой способ сломать тренировку: уступчивость
// модели, подсказку менеджеру и согласие на то, чего не предлагали.
const PROHIBITIONS = `ЧЕГО НЕ ДЕЛАТЬ:
- Не соглашайся от настойчивости. Повторный вопрос без новых аргументов —
  это отказ. Тебя убеждают факты и снятые страхи, а не количество попыток.
- Не подсказывай менеджеру, что ему сказать, чтобы ты согласилась.
- Не соглашайся, пока тебе прямо не предложили оплатить.`;

// Для проверялки: она убеждается, что все блоки дошли до каждого пациента
// дословно. Порядок — как в собранном промпте.
export const MECHANIC_BLOCKS = [
  OBJECTIONS_TIMING,
  PAYMENT_CONDITION,
  HELPS_HEADER,
  PROHIBITIONS,
];

// --- Слоты пациента ---------------------------------------------------------

export interface PatientRole {
  // Кто ты: имя, возраст, биография, быт, характер
  identity: string;
  // Речевая манера: соразмерность ответа вопросу, примеры, запреты
  manner: string;
  // Зачем пришла: повод обращения и что знает о своей проблеме
  situation: string;
  // Пока разговор о чём — ты спокойна и отвечаешь охотно
  calmWhile: string;
  // Страхи: проявляются поведением, вслух не называются
  fears: string[];
  // Реакция на манеру менеджера
  warmsUp: string[];
  closesUp: string[];
  // Обязательные условия согласия БЕЗ правила про прямое предложение оплатить:
  // его подставляет сборщик первым номером
  mustHappen: string[];
  // Накопительные условия — от них зависит, насколько тепло идёт разговор
  helps: string;
  // Механика принятия решения: кто согласующий и как проходит сцена с ним
  decision: string;
}

/**
 * Склеивает роль пациента из слоёв в том порядке, в котором её читает модель.
 *
 * Переносы строк сборщик НЕ расставляет: текст в слотах уже сверстан, и любая
 * переверстка изменила бы промпт, по которому персонаж уже говорит.
 *
 * Зато приводит их к LF. На Windows рабочая копия лежит в CRLF (core.autocrlf),
 * и шаблонные строки ниже несут \r\n, а в базу промпт до сих пор попадал с LF —
 * сид запускался в контейнере. Без нормализации сид, запущенный с Windows,
 * перезаписал бы промпты всем пациентам, отличаясь ровно на число строк.
 */
export function buildRolePrompt(role: PatientRole): string {
  const bullets = (items: string[]) => items.map((t) => `- ${t}`).join("\n");

  // Нумерация начинается со второго: первый номер занят условием про оплату,
  // и автор пациента им не распоряжается
  const conditions = role.mustHappen
    .map((text, i) => `${i + 2}. ${text}`)
    .join("\n");

  return [
    role.identity,
    `РЕЧЕВАЯ МАНЕРА:\n${role.manner}`,
    `ЗАЧЕМ ПРИШЛА:\n${role.situation}`,
    `ПОВЕДЕНИЕ ПО СИТУАЦИИ:\n${role.calmWhile}`,
    `СТРАХИ (проявляй через поведение, не озвучивай прямо):\n${bullets(role.fears)}`,
    `КОГДА ТЕПЛЕТЬ:\n${bullets(role.warmsUp)}`,
    `КОГДА ЗАКРЫВАТЬСЯ:\n${bullets(role.closesUp)}`,
    OBJECTIONS_TIMING,
    `${PAYMENT_CONDITION}\n${conditions}`,
    `${HELPS_HEADER}\n${role.helps}`,
    `КАК ТЫ ПРИНИМАЕШЬ РЕШЕНИЕ:\n${role.decision}`,
    PROHIBITIONS,
  ]
    .join("\n\n")
    .replace(/\r\n/g, "\n");
}
