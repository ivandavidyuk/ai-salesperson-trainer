// Сборка роли пациента из слоёв. Используется сидом пациентов.
//
// Слоёв три, и делятся они по авторству, а не по месту в промпте:
//
//   механизм  — константы ниже, одинаковы у всех. Охраняют работу тренажёра;
//               автор пациента их не пишет и изменить не может.
//   личность  — характер, манера, быт, страхи, механика согласующего.
//               Не меняется при смене отрасли: Тамара Михайловна остаётся
//               собой и в офтальмологии, и в стоматологии.
//   случай    — отрасль: зачем пришла, чем снимаются её страхи, примеры речи
//               на языке этой отрасли. Со временем будет собираться
//               автоматически по данным клиники, которые заполнит РОП.
//
// Из этого следует главное требование к личности: в ней не должно быть НИ ОДНОГО
// отраслевого слова. Иначе подмена случая даст пациента, который рассуждает
// про катаракту, придя лечить зуб. Проверяется подстановкой чужого случая —
// см. check-prompts.ts.
//
// Сборщик перемешивает слои: страхи стоят между случаем и правилами механизма.
// Это нормально — слой отвечает на вопрос «кто это писал», а не «где это лежит».

// --- Слой механизма ---------------------------------------------------------

// Возражения появляются только после коммерческого предложения. Это правило
// механизма, а не черта характера: пациент, возражающий с первой реплики,
// не даёт менеджеру дойти до выявления потребности, и тренировка вырождается
// в отбивание заготовок.
const OBJECTIONS_TIMING = `ВОЗРАЖЕНИЯ:
До коммерческого предложения возражений нет вовсе. Они появляются, только
когда менеджер называет цену, предлагает записаться или говорит о лечении, —
и звучат твоими словами, а не заготовками.`;

// Первое обязательное условие — всегда прямое предложение оплатить, и номер
// у него всегда первый. Без предложения пациенту нечего принимать, и «сделка
// не закрыта» означало бы не отказ, а то, что закрытия никто не пробовал:
// это разные ошибки менеджера с разным лечением.
const PAYMENT_CONDITION = `ЧТО ДОЛЖНО ПРОИЗОЙТИ, ЧТОБЫ ТЫ СОГЛАСИЛАСЬ:

Обязательное — без любого из этого ты отказываешь, как бы хорошо ни шёл
разговор в остальном:
1. Менеджер прямо предложил оплатить лечение. Намёк, «вы подумайте»
   и «приходите, когда решитесь» не считаются: тебе нечего принимать.`;

// Накопительные условия отдельным механизмом не считаются: они уже растворены
// в оценках этапов, а те проходят через порог допуска. Считать их второй раз
// значило бы наказывать дважды за одно и то же.
const HELPS_HEADER = `Хорошо, но не обязательно — от этого зависит, насколько тепло ты говоришь:`;

// Блок запретов всегда идёт последним, и вклиниться после него автор пациента
// не может. Каждый запрет закрывает свой способ сломать тренировку: уступчивость
// модели, подсказку менеджеру и согласие на то, чего не предлагали.
//
// Первый запрет сужен до оплаты после живого разговора 30.07.2026. В прежней
// формулировке он относился к любому повторному вопросу — и сорвал сцену
// с согласующим: менеджер дважды предложил позвонить мужу, роль сочла это
// настойчивостью без новых аргументов и отказала оба раза. Сделка не закрылась,
// хотя менеджер сделал именно то, что промпт называет проходящим ходом.
const PROHIBITIONS = `ЧЕГО НЕ ДЕЛАТЬ:
- Не соглашайся оплатить от настойчивости. Повторное предложение без новых
  аргументов — это отказ. Тебя убеждают факты и снятые страхи, а не количество
  попыток. К промежуточным шагам — например, позвонить согласующему — это
  не относится: там достаточно снять названную тобой помеху.
- Не подсказывай менеджеру, что ему сказать, чтобы ты согласилась.
- Не соглашайся, пока тебе прямо не предложили оплатить.
- Не описывай своих действий и не пиши ремарок в скобках: тебя только слышно.
  Ремарку собеседник не услышит вовсе — её вырезают перед озвучкой, и вместо
  твоего хода он получит тишину. Всё, что делаешь, проговаривай словами.
- Твоё имя — не имя собеседника. Не обращайся к нему тем именем, которым
  он называет тебя.`;

// Для проверялки: она убеждается, что все блоки дошли до каждого пациента
// дословно. Порядок — как в собранном промпте.
export const MECHANIC_BLOCKS = [
  OBJECTIONS_TIMING,
  PAYMENT_CONDITION,
  HELPS_HEADER,
  PROHIBITIONS,
];

// --- Слой личности ----------------------------------------------------------

/**
 * Кто этот человек. Переживает смену отрасли без правок.
 *
 * Быт остаётся здесь: вязание, чтение, внуки, возраст годятся любому случаю.
 * Случай говорит лишь, что именно из этого страдает, — так сцепка характера
 * с проблемой сохраняется, а характер не становится пресным.
 */
export interface PatientPersonality {
  // Имя, возраст, биография, быт, характер
  identity: string;
  // Правила речи: соразмерность ответа вопросу, темп, запреты.
  // Примеры живут в случае — они обязаны говорить на языке отрасли
  manner: string;
  // Страхи: проявляются поведением, вслух не называются. Здесь форма страха
  // («в моём возрасте это опасно»), а чем именно рискуют — в случае
  fears: string[];
  // Отношение к деньгам: рассрочка, кредит, наличные, переплата. Отдельно
  // от быта, потому что это не краска характера, а рычаг закрытия: человеку,
  // считающему переплату, и человеку с наличными в портфеле нужны разные
  // условия. По этому блоку генератор пишет условие про деньги.
  //
  // Необязательное: пациент без прописанных финансовых привычек — нормальный
  // пациент, и пустой блок в промпт не выводится
  finances?: string[];
  // Реакция на манеру менеджера
  warmsUp: string[];
  closesUp: string[];
  // Обязательные условия, вытекающие из характера, — например пройденная
  // сцена с согласующим. Условия про саму услугу лежат в случае
  conditions: string[];
  // Накопительные условия от характера: что значит «услышали именно меня»
  helps: string[];
  // Механика принятия решения: кто согласующий и как проходит сцена с ним
  decision: string;
}

// --- Слой случая ------------------------------------------------------------

/**
 * Отрасль и повод обращения. Подменяется целиком, личность при этом та же.
 */
export interface PatientCase {
  // Зачем пришла: повод обращения и что знает о своей проблеме
  situation: string;
  // Пока разговор о чём — пациент спокоен и отвечает охотно
  calmWhile: string;
  // Примеры речи в лексике этой отрасли. Иллюстрируют правила манеры
  // из личности, поэтому и живут отдельно от них
  mannerExamples: string;
  // Обязательные условия про саму услугу: чем снимается страх за безопасность,
  // что входит в стоимость. Идут до условий от характера
  conditions: string[];
  // Накопительные условия про услугу
  helps: string[];
  // Слова, принадлежащие этому случаю. Не идут в промпт: по ним проверялка
  // убеждается, что случай не протёк в личность. Заполняется вместе со
  // случаем — в том числе генератором, когда он появится
  vocabulary: string[];
}

export interface PatientRole {
  personality: PatientPersonality;
  case: PatientCase;
}

/**
 * Склеивает роль пациента из слоёв в том порядке, в котором её читает модель.
 *
 * Переносы строк сборщик НЕ расставляет: текст в слотах уже сверстан, и любая
 * переверстка изменила бы промпт, по которому персонаж уже говорит.
 *
 * Зато приводит их к LF. На Windows рабочая копия лежит в CRLF (core.autocrlf),
 * и шаблонные строки несут \r\n, а в базу промпт попадает с LF — сид
 * запускается в контейнере. Без нормализации сид, запущенный с Windows,
 * перезаписал бы промпты всем пациентам, отличаясь ровно на число строк.
 */
export function buildRolePrompt(role: PatientRole): string {
  const { personality, case: patientCase } = role;
  const bullets = (items: string[]) => items.map((t) => `- ${t}`).join("\n");

  // Условия случая идут перед условиями характера: сначала «сняли страх
  // за саму услугу», потом «прошли сцену с согласующим». Нумерация начинается
  // со второго — первый номер занят условием про оплату, и автор пациента
  // им не распоряжается
  const conditions = [...patientCase.conditions, ...personality.conditions]
    .map((text, i) => `${i + 2}. ${text}`)
    .join("\n");

  // Блок финансов необязателен, и пустой не выводится вовсе: иначе добавление
  // слота переписало бы промпты всем, у кого его нет, — включая эталонный
  const finances = personality.finances?.length
    ? [`ОТНОШЕНИЕ К ДЕНЬГАМ:\n${bullets(personality.finances)}`]
    : [];

  return [
    personality.identity,
    `РЕЧЕВАЯ МАНЕРА:\n${personality.manner}\n- Примеры:\n${patientCase.mannerExamples}`,
    `ЗАЧЕМ ПРИШЛА:\n${patientCase.situation}`,
    `ПОВЕДЕНИЕ ПО СИТУАЦИИ:\n${patientCase.calmWhile}`,
    `СТРАХИ (проявляй через поведение, не озвучивай прямо):\n${bullets(personality.fears)}`,
    ...finances,
    `КОГДА ТЕПЛЕТЬ:\n${bullets(personality.warmsUp)}`,
    `КОГДА ЗАКРЫВАТЬСЯ:\n${bullets(personality.closesUp)}`,
    OBJECTIONS_TIMING,
    `${PAYMENT_CONDITION}\n${conditions}`,
    `${HELPS_HEADER}\n${bullets([...personality.helps, ...patientCase.helps])}`,
    `КАК ТЫ ПРИНИМАЕШЬ РЕШЕНИЕ:\n${personality.decision}`,
    PROHIBITIONS,
  ]
    .join("\n\n")
    .replace(/\r\n/g, "\n");
}

/**
 * Текст личности без промпта целиком — для проверки, что случай не протёк.
 *
 * Собирается из тех же слотов, что уходят в промпт, чтобы проверка смотрела
 * на то же, что читает модель, а не на отдельно поддерживаемый список.
 */
export function personalityText(personality: PatientPersonality): string {
  return [
    personality.identity,
    personality.manner,
    ...personality.fears,
    ...(personality.finances ?? []),
    ...personality.warmsUp,
    ...personality.closesUp,
    ...personality.conditions,
    ...personality.helps,
    personality.decision,
  ].join("\n");
}
