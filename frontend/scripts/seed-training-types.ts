// Типы тренировки для мастера настройки.
// Запуск: npm run seed:training
//
// Три текстовых поля у типа, и они уходят в разные места:
//   prompt   — в системный промпт РОЛИ: как пациент ведёт себя в упражнении;
//   rubric   — ОЦЕНЩИКУ: что мерить в этом упражнении;
//   doneWhen — ОЦЕНЩИКУ: чем определяется, что этап отработан.
//
// Рубрика и критерий роли не показываются намеренно. Знай она, по каким
// признакам судят её собеседника, она начала бы подыгрывать — это тот же
// запрет «не подсказывай менеджеру», на котором у нас отсеялись модели
// при отборе 31.07.
//
// Поле description — единственное место, где менеджер узнаёт, что от него
// требуется: отдельных экранов под критерии этапа нет и не планируется.
// Поэтому там не «о чём этап», а «что сделать».
//
// Промпты живут здесь, а не в БД: источник правды — репозиторий, изменения
// видны в истории git. Поэтому скрипт ПЕРЕЗАПИСЫВАЕТ их при каждом запуске —
// правки, сделанные напрямую в базе, будут потеряны.
//
// Про слаги. «s1…s4» — легаси-нумерация, и она больше не совпадает с порядком:
// prevention встал между s3 и s4. Это осознанно, чинить не нужно. id —
// первичный ключ, на него ссылаются Session.trainingTypeId и
// Assignment.trainingTypeId, включая демо-разговоры на проде; переименование
// стоило бы миграции живых данных, а пользователь id вообще не видит —
// на экране title и position.
//
// Тексты согласованы с Димой 03.08.2026 по его голосовым.

