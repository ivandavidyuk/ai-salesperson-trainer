// Пациент как он лежит в репозитории: личность и досье для РОПа.
//
// По файлу на пациента: двадцать одна личность в seed-patients.ts нечитаема,
// а искать нужного в одном полотне на три тысячи строк невозможно.

import type { PatientDifficulty } from "@prisma/client";
import type { PatientPersonality, IndustryKey } from "../patient-prompt";

export interface PatientProfile {
  /** Имя на экране: «Имя Отчество», как у Тамары. Фамилия живёт в identity */
  name: string;
  /**
   * В каких отраслях участвует персонаж. Нет поля — во всех: личность
   * отраслево-чистая (этап 0), и случай ей пишется под любую. Поле нужно
   * в двух случаях: библиотечный персонаж в отрасль не идёт (покупка втайне
   * от мужа в офисе продаж невозможна — ипотека и ДДУ требуют согласия
   * супруга) или персонаж написан под одну отрасль («мама 30» с семейной
   * ипотекой). От состава зависят список клиентов организации, цели
   * пересборки у клиник и полнота пресета (`составОтрасли` в index.ts).
   */
  industries?: IndustryKey[];
  /**
   * Сложность — это «трудно довести до сделки», а НЕ «неприятен
   * в разговоре». Менеджер берёт уровень, чтобы калибровать вызов
   * закрытия; грубость сама по себе его не усложняет.
   *
   * На механизм не влияет ничем: в промпт не попадает, модель про уровень
   * не знает. Это фильтр в списке, чип в карточке и счётчик достижения
   * «закрыл сложного». Поэтому трудным пациента делает только то,
   * что написано в его личности и случае.
   *
   * Считается по препятствиям к сделке, которые видны в промпте. Каждое
   * отраслево-нейтральное, каждое стоит одно очко:
   * — согласующий по шагам: настоящая сцена с третьим лицом, которую
   *   менеджер обязан провести (ложное «спрошу у брата» не считается);
   * — оплата требует особого решения: без рассрочки от клиники, без банка,
   *   без следов, частями — сделки нет;
   * — скрытый сюжет: чтобы закрыть, надо распознать, о чём пациент молчит;
   * — наказание за невнятность: мямлит, оправдывается, тянет — дожимает
   *   или уходит (за слабость, не за сладость и не за спешку);
   * — невыполнимое условие: замкнутый круг или уход без возврата.
   * Ноль очков — easy, одно — mid, два и больше — hard.
   *
   * Откалибровано живым тестом 21 персонажа 01–02.09: со старыми ярлыками
   * закрываемость шла 100 / 43 / 64 процента по easy / mid / hard, то есть
   * mid и hard были перевёрнуты. С этими — 80 / 67 / 43, монотонно.
   * Ложное возражение сложности не добавляет: его достаточно не принять
   * всерьёз, и вживую на этом никто не споткнулся.
   *
   * До 25.08 уровни стояли по впечатлению от характера; 25.08 переставлены
   * по четырём осям, 03.09 — по этим препятствиям (восемь ярлыков).
   *
   * Ярлык живёт в таблице `Patient` и попадает туда только через
   * `npm run seed:patients`. Пересборка промптов при старте контейнера
   * его не трогает — после правки сид надо прогнать руками.
   */
  difficulty: PatientDifficulty;
  personality: PatientPersonality;
  // Случая здесь нет намеренно: отрасль и повод обращения живут в пресетах
  // (`scripts/presets/<отрасль>/`) и в PatientCase организации — по случаю
  // на клинику. Видимые отраслевые поля — карточка, анамнез, возражения —
  // приходят оттуда же. До 16.09 в файле лежал ещё и «глобальный»
  // офтальмологический случай из первой генерации, третий и никем
  // не вычитанный набор; его убрали, когда у каждой организации на проде
  // оказался свой пресетный случай, и запасной путь перестал быть нужен.

  // Досье для руководителя. Менеджеру API эти поля не отдаёт: «как выиграть
  // клиента» — это ответ на задачу, которую он тренирует
  character: string;
  decisionMaker: string;
  approach: string;
  /**
   * Голос синтеза, свой у каждого пациента.
   *
   * До 24.08 их было два на всех: один мужской и один женский, из-за чего
   * два пациента подряд звучали как один человек. Теперь у каждого свой,
   * подобранный под возраст и манеру речи.
   *
   * Выбирали НЕ по задержке: замер одиннадцати русских мужских голосов дал
   * медианы 138–147 мс, разброс девять миллисекунд. Голос в этой модели —
   * эмбеддинг поверх общей сети, на скорость он не влияет, и выбирать
   * по секундомеру нечего.
   *
   * Известный компромисс: русских голосов с меткой «пожилой» в библиотеке
   * ElevenLabs нет вообще — те два, что есть, немецкий и англоязычный.
   * Поэтому пятеро пациентов 71–83 лет говорят средневозрастными голосами
   * и звучат моложе своих лет. Вытянуто фактурой: хрипотца, сухость,
   * неспешность.
   *
   * Не задан — берётся общий из `ELEVENLABS_VOICE_ID`.
   */
  voice?: string;
}
