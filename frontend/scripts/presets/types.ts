// Отраслевой пресет: готовые случаи пациентов для клиники этой отрасли.
//
// Зачем. Случай под клинику собирает платный пайплайн из трёх вызовов модели
// (клиническая картина → подбор услуги → проза), и на 21 пациента это около
// 300 ₽ за клинику. Демо-доступ выдаётся часто и раздавать его по такой цене
// нельзя, а боевому клиенту вычитанный случай лучше свежесгенерированного:
// пресет читали люди, генерацию — нет.
//
// Поэтому случаи написаны заранее и лежат в репозитории — как личности
// и механизм. Сид `seed:presets` наливает их в организацию `isPreset`,
// а `create-demo` копирует оттуда демо-клинике той же отрасли.
//
// ЧЕМ ЭТО НЕ ЯВЛЯЕТСЯ: подменой пайплайна. Тексты написаны в том же порядке
// и по тем же контрактам, что у генератора (backend/services/clinical_picture.py
// и case_generator.py) — сначала диагноз без знания услуг, потом услуга под
// диагноз, потом проза. Клиент, которому пресет не подойдёт, пересоберёт
// случаи под свой прайс существующей кнопкой в кабинете руководителя.

import type { PatientCase } from "../patient-prompt";

/**
 * Клиническая картина — то, что в проде отдаёт `clinical_picture`.
 *
 * В базу не идёт: генератор её тоже не сохраняет (в `caseData` живут только
 * шесть слотов случая). Здесь она нужна двум читателям — критику, который
 * судит «чей брак, картины или прозы», и человеку на вычитке: без неё
 * замечание «так не бывает» не с чем сопоставить, непонятно, ошиблись
 * в возрасте, в стадии или в условии проявления.
 *
 * Поля — те же десять и в том же смысле, что `_PICTURE_FIELDS`
 * в clinical_picture.py. Четыре из них несут дисциплину, из-за которой
 * весь пайплайн и переписан: окно начала (onsetFrom/onset), частота
 * в возрасте (common/typicalFor), стадия с её симптомами (stage/complaints)
 * и условие проявления (noticedWhen).
 */
export interface ClinicalPicture {
  /** Название ДОСЛОВНО из списка диагнозов клиники, без стадии внутри */
  diagnosis: string;
  /** С какого возраста состояние может начаться. Число: сверяется арифметикой */
  onsetFrom: number;
  /** То же словами: когда возникает впервые и у кого */
  onset: string;
  /** Обычное ли это для такого возраста. Ровно «да» или «нет» */
  common: "да" | "нет";
  /** Пояснение к common: на какой возраст приходится основная масса случаев */
  typicalFor: string;
  /** Стадия, как принято делить в отрасли. «Стадий не выделяют» — законный ответ */
  stage: string;
  /** На что жалуется этот человек своими словами, про свою жизнь. 1–2 предложения */
  complaints: string;
  /** При каких условиях он это замечает */
  noticedWhen: string;
  /** Что видит специалист на осмотре: находки и измерения. Без выводов о продаже */
  objective: string;
  /** Что с этим делают — вмешательство или тактика, как это зовут в отрасли */
  treatment: string;
}

/**
 * Запрос покупателя — то, что в офисе продаж застройщика стоит на месте
 * клинической картины. Те же четыре измерения дисциплины (CLAUDE.md: «чиним
 * измерения, а не факты»): окно повода, обычность для возраста и семьи,
 * стадия поиска, условие проявления. Диагноза здесь нет: повод — событие
 * в жизни, а не состояние из списка, и таблицы поводов у организации
 * не ведётся — подбор квартиры делает менеджер, это его работа.
 * Решения — docs/Каркас недвижимости.md (17.09).
 */
export interface BuyerPicture {
  /** Повод одной строкой: «квартира внучке-студентке», «расширение: второй ребёнок» */
  reason: string;
  /** С какого возраста такой повод бывает. Число: сверяется с возрастом личности */
  reasonFrom: number;
  /** То же словами: когда такой повод возникает и у кого */
  onset: string;
  /** Обычен ли повод для этого возраста и семьи. Ровно «да» или «нет» */
  common: "да" | "нет";
  /** Пояснение к common: у кого такой повод — основная масса */
  typicalFor: string;
  /** Стадия поиска: только начал, смотрел полгода, с одобрением банка, с деньгами от продажи */
  stage: string;
  /** Чего хочет этот человек своими словами, про свою жизнь. 1–2 предложения */
  request: string;
  /** При каких условиях повод проявился — что подтолкнуло прийти именно сейчас */
  noticedWhen: string;
  /** Что менеджер видит в заявке: кто будет жить, чем платит, срок заселения, что смотрел. Без мотивов */
  application: string;
  /** Что подходит под запрос: тип квартиры, очередь, срок сдачи, платёж */
  fit: string;
}

/** Картина клиники узнаётся по диагнозу; у офиса продаж на его месте повод */
export function клиническая(picture: ClinicalPicture | BuyerPicture): picture is ClinicalPicture {
  return "diagnosis" in picture;
}

/**
 * Случай одного пациента в одной отрасли.
 *
 * `case` — те самые шесть слотов, что уедут в `PatientCase.caseData`
 * и станут промптом через `buildRolePrompt`. Остальное — видимые поля
 * карточки и служебная картина.
 */
export interface PresetCase {
  /** Имя как в `PatientProfile.name` — по нему сид находит пациента */
  patientName: string;
  /** Услуга, подобранная ПОД диагноз или под запрос. Название дословно из clinic.ts */
  service: string;
  /** Клиническая картина у клиники, запрос покупателя у офиса продаж */
  picture: ClinicalPicture | BuyerPicture;
  case: PatientCase;
  /** Строка карточки: «62 года · диагностика зрения». Возраст и повод, не услуга */
  description: string;
  /**
   * Что менеджер читает перед разговором. У клиники — выписка из карты,
   * связный абзац, заканчивается строкой «Диагноз: …». У офиса продаж —
   * заявка: откуда пришёл, что смотрел, кто будет жить, чем платит,
   * без мотивов. Поле в базе одно на обе отрасли
   */
  anamnesis: string;
  /**
   * Готовый результат диагностики — то, что менеджер увидит по кнопке.
   * Стоит вплотную к анамнезу НАМЕРЕННО: документ пишется от анамнеза,
   * и правящий одно обязан видеть второе. Пусто — работает генератор.
   * У офиса продаж не бывает: кнопки там нет (решение 17.09)
   */
  diagnostics?: string;
  /** Ровно три: «прямая речь» — пояснение со строчной, какой страх за ней */
  objections: string[];
}

/** Услуга прайса. Цена строкой — как в модели `Service` */
export interface PresetService {
  name: string;
  price: string;
  description: string;
}

/** Диагноз клиники. `complaint` — отправная точка жалобы, а не готовый текст */
export interface PresetDiagnosis {
  name: string;
  complaint: string;
  /**
   * Услуга, которая ЛЕЧИТ это состояние, — результат второго шага пайплайна
   * (`clinical_picture.match_services`), выполненного один раз на отрасль.
   *
   * В проде подбор идёт отдельным вызовом на каждого пациента, но отвечает
   * он на вопрос о диагнозе, а не о человеке: при закрытом списке услуг
   * ответ для одного диагноза один и тот же у всех двадцати одного. Важен
   * не счётчик вызовов, а направление — услуга подобрана ПОД диагноз,
   * а не диагноз подогнан под услугу.
   *
   * Диагностический приём лечением не считается: услуга, после которой
   * становится известен только диагноз, оставляет человека там же, где он был.
   */
  treatedBy: string;
}

/** Клиника отрасли: то, что в проде заполняет руководитель в своём кабинете */
export interface PresetClinic {
  /**
   * Отрасль одним словом в нижнем регистре — ровно то, что оператор передаст
   * в `create-demo --industry`. Поиск пресета идёт точным равенством.
   */
  industry: string;
  /**
   * Клиника продаёт лечение под диагноз, офис продаж — квартиру под
   * запрос. От этого зависят форма случая (картина или запрос), проверки
   * и то, что менеджер читает перед разговором
   */
  kind: "клиника" | "офис продаж";
  /**
   * Набор ещё пишется: сид наливает то, что есть, проверка полноты
   * выключена, а пациент без случая в такой организации не открывается
   * («ещё не подготовлен»). Снять, когда случаев 21
   */
  inProgress?: boolean;
  /** Название организации-пресета в базе */
  orgName: string;
  /**
   * Отрасль словами для промпта генератора — поле `industry` организации
   * видит только модель, и ей нужна фраза, а не ключ.
   */
  industryLabel: string;
  services: PresetService[];
  diagnoses: PresetDiagnosis[];
}

/** Отрасль целиком: клиника и случаи всех пациентов */
export interface Preset {
  clinic: PresetClinic;
  cases: PresetCase[];
}
