//
// В ОТЛИЧИЕ ОТ СТОМАТОЛОГИИ И ОФТАЛЬМОЛОГИИ пресет собран не по
// универсальности, а под живую клинику: диагнозы и процедуры — её список,
// цены — её прайс. Отрасль та же, медицина, а деньги устроены иначе:
