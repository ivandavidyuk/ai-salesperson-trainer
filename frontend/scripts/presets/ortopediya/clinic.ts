//   спина  — бесплатное ММТ невролога (мануальное мышечное тестирование)
//            и УЗИ спины.
//
// ПРАЙС ДВУХ ВИДОВ. Процедуры — как в прайсе клиники, цена за одну. Курсы —
// комбинированные назначения: врач клиники обычно назначает не одну
// процедуру, а сочетание. Услуга случая одна, поэтому назначение записано
// курсом с итоговой ценой, а процедуры остаются в прайсе: из них менеджер
// собирает вариант подешевле, когда пациент упрётся в потолок.
//
// СОСТАВ КУРСОВ — ЧЕРНОВИК, врачи клиники его правят на вычитке. Цены курсов
// сложены из цен процедур; у капельниц цена в прайсе вилкой, поэтому курс
// с ними — «от».
//
// «Грыжи, протрузии» клиники разведены на два диагноза с разными курсами:
// иначе у десяти пациентов по спине была бы одна услуга и одна цена.

