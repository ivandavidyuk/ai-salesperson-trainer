// Проверка формы пресетных случаев — теми же правилами, какими прод-генератор
// проверяет ответ модели.
//
// Зачем повторять проверку на TypeScript, если она есть на Python. Случаи
// в пресетах написаны руками и мимо генератора, то есть мимо `validate_case`:
// ни одно его правило к ним не применялось. А правила эти — не вкусовщина,
// каждое куплено браком в проде: сорок шесть примеров манеры вместо двух,
// «Пресебиопия» в анамнезе, условие, написанное инструкцией менеджеру.
// Рукописный случай ошибается ровно там же, где ошибалась модель.
//
// ИСТОЧНИК ПРАВДЫ — backend/services/case_generator.py (`validate_case`,
// REQUIRED_FIELDS, _GENERIC_VOCABULARY, _HEDGES, _INSTRUCTION_VOICE,
// _WRONG_PERSON) и clinical_picture.py (`годится_по_возрасту`, `_чем_плоха`).
// Правила продублированы намеренно: тянуть Python в проверку фронта нечем,
// а без проверки пресет уехал бы в прод непроверенным вовсе. Разъедутся —
// прод останется прав, а здесь надо будет догнать.

import { MECHANIC_BLOCKS, type PatientPersonality } from "../patient-prompt";
import type { ClinicalPicture, PresetCase, PresetClinic } from "./types";

/** Ровно два примера манеры: в замере модель однажды выдала сорок шесть */
const ПРИМЕРОВ_МАНЕРЫ = 2;
/** Меньше пяти отраслевых слов — проверка протечек слепнет */
const МИНИМУМ_СЛОВАРЯ = 5;
/** Корень в две буквы ловит что попало: «дн» совпадало с «дней», «дно», «однажды» */
const МИНИМУМ_КОРНЯ = 3;

/**
 * Слова, звучащие в любой клинике и в любой продаже. В словаре случая им
 * не место: по нему ищут отраслевые протечки, а «врач» и «решени» есть
 * в личностях законно.
 *
 * Список дословно из `_GENERIC_VOCABULARY` case_generator.py.
 */
const ОБЩИЕ_СЛОВА = new Set([
  "врач", "решени", "стоимост", "приём", "прием", "осмотр", "риск",
  "цен", "довер", "лечени", "процедур", "клиник", "пациент", "здоровь",
  "деньг", "оплат", "рассрочк", "консультац", "специалист",
]);

/** Границы документа диагностики. Дословно из `_MIN_LEN`/`_MAX_LEN` */
const ДОКУМЕНТ_МИН = 120;
const ДОКУМЕНТ_МАКС = 1600;
/** Разделов в документе — меньше трёх это огрызок, а не заключение */
const ДОКУМЕНТ_РАЗДЕЛОВ = 3;
/** Вывод о продаже вместо находки. Дословно из `_SALES_CONCLUSIONS` */
const ВЫВОДЫ_О_ПРОДАЖЕ = [
  "требуется ", "показана ", "показано ", "рекомендована ", "рекомендовано ",
  "рекомендуется ", "необходима ", "необходимо ",
];

/** Медицинская карта не гадает. Дословно из `_HEDGES` */
const ГАДАНИЯ = [
  "предположительн", "возможно", "вероятно", "скорее всего", "по-видимому",
  "неизвестн", "не установлен", "уточнить у",
];

/** Условие, написанное инструкцией менеджеру. Дословно из `_INSTRUCTION_VOICE` */
const ГОЛОС_ИНСТРУКЦИИ = ["нужно ", "необходимо ", "следует ", "менеджер должен"];

/**
 * Сбитое лицо: промпт обращается к пациенту на «ты».
 *
 * Дословно из `_WRONG_PERSON`. Ловушка: сама инструкция генератора приводит
 * в пример «что в моём возрасте резать глаз опасно» — и этот пример её же
 * валидатор бракует. Правильно только «в твоём возрасте».
 */
const ЧУЖОЕ_ЛИЦО =
  /(?<![А-Яа-яЁёA-Za-z])(моём|моем|моего|моей|моя|мою|мои|мне|меня|ей|ему)(?![А-Яа-яЁёA-Za-z])/i;

/** Блоки механизма одним текстом — с ними сверяется словарь случая */
const МЕХАНИЗМ_ТЕКСТОМ = MECHANIC_BLOCKS.join("\n").toLowerCase();

/** Ищет корень с начала слова — как `containsStem` в check-prompts.ts */
export function содержитКорень(текст: string, корень: string): boolean {
  const экранированный = корень.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return new RegExp(`(?<![A-Za-zА-Яа-яЁё])${экранированный}`, "i").test(текст);
}

/** Одна ли это строка с точностью до регистра и знаков. Как `_same_line` */
function однаСтрока(левая: string, правая: string): boolean {
  const чистка = (t: string) => t.toLowerCase().replace(/[ .,;:—«»"'()-]/g, "");
  return чистка(левая) === чистка(правая);
}

/** Возраст из первой строки личности: «Ты — Тамара Михайловна Соколова, 62 года» */
export function возрастИзЛичности(personality: PatientPersonality): number | null {
  const найдено = personality.identity.match(/,\s*(\d{1,3})\s*(?:год|года|лет)/);
  return найдено ? Number(найдено[1]) : null;
}

/**
 * Проверяет один пресетный случай. Возвращает список проблем — пустой, если
 * всё сошлось.
 *
 * @param личность нужна, чтобы поймать словарь, протёкший из личности,
 * и «помогает», дословно повторяющее её же строки.
 */
export function проверитьСлучай(
  пресет: PresetCase,
  личность: PatientPersonality,
  клиника: PresetClinic,
): string[] {
  const беды: string[] = [];
  const { case: случай, picture: картина } = пресет;

  // --- Клиническая картина ---------------------------------------------------

  const диагнозы = new Map(
    клиника.diagnoses.map((д) => [д.name.trim().toLowerCase(), д]),
  );
  const диагноз = диагнозы.get(картина.diagnosis.trim().toLowerCase());
  if (!диагноз) {
    беды.push(`диагноза «${картина.diagnosis}» нет в списке клиники`);
  }

  const возраст = возрастИзЛичности(личность);
  if (возраст === null) {
    беды.push("не удалось прочитать возраст из личности");
  } else if (возраст < картина.onsetFrom) {
    // Та самая арифметика, из-за которой переписан пайплайн: «миопия,
    // впервые возникшая в 48 лет» проходила, пока окно читали словами
    беды.push(
      `начинается с ${картина.onsetFrom}, а человеку ${возраст} — картина невозможна`,
    );
  }

  if (картина.common !== "да" && картина.common !== "нет") {
    беды.push(`common: «${картина.common}» вместо «да» или «нет»`);
  }

  const картинаСлитно = Object.values(картина).join(" ").toLowerCase();
  const гадание = ГАДАНИЯ.find((г) => картинаСлитно.includes(г));
  if (гадание) беды.push(`картина гадает: «${гадание}»`);

  for (const поле of ["diagnosis", "objective"] as const) {
    if (картина[поле].toLowerCase().includes(" или ")) {
      беды.push(`«или» в поле картины ${поле} — не выбрано одно`);
    }
  }

  // --- Услуга ----------------------------------------------------------------

  const услуга = клиника.services.find((у) => у.name === пресет.service);
  if (!услуга) {
    беды.push(`услуги «${пресет.service}» нет в прайсе клиники`);
  } else if (диагноз && диагноз.treatedBy !== пресет.service) {
    беды.push(
      `услуга «${пресет.service}» не лечит «${картина.diagnosis}» — ` +
        `по таблице отрасли лечит «${диагноз.treatedBy}»`,
    );
  }

  // --- Слоты случая ----------------------------------------------------------

  const примеры = случай.mannerExamples.split("\n").filter((с) => с.trim());
  if (примеры.length !== ПРИМЕРОВ_МАНЕРЫ) {
    беды.push(`примеров манеры ${примеры.length}, а нужно ${ПРИМЕРОВ_МАНЕРЫ}`);
  }
  for (const пример of примеры) {
    if (!пример.startsWith("  ")) {
      беды.push(`пример манеры без двух ведущих пробелов: «${пример.slice(0, 40)}…»`);
    }
    if (!пример.includes("→")) {
      беды.push(`пример манеры без стрелки: «${пример.trim().slice(0, 40)}…»`);
    }
  }

  if (случай.conditions.length !== 2) {
    беды.push(`условий случая ${случай.conditions.length} вместо 2`);
  }
  if (случай.helps.length < 1 || случай.helps.length > 2) {
    беды.push(`«помогает» ${случай.helps.length} строк, ожидалось 1–2`);
  }
  if (пресет.objections.length !== 3) {
    беды.push(`возражений ${пресет.objections.length} вместо 3`);
  }

  for (const условие of случай.conditions) {
    const голос = ГОЛОС_ИНСТРУКЦИИ.find((г) => условие.toLowerCase().includes(г));
    if (голос) беды.push(`условие написано инструкцией менеджеру: «${голос.trim()}»`);
    // Услуга в условии превращает пациента в человека с готовым решением:
    // ему остаётся только уговорить себя, продавать нечего
    for (const у of клиника.services) {
      if (условие.toLowerCase().includes(у.name.toLowerCase())) {
        беды.push(`в условии названа услуга «${у.name}» — пациент её знать не может`);
      }
    }
  }

  for (const строка of [...случай.conditions, ...случай.helps]) {
    const лицо = строка.match(ЧУЖОЕ_ЛИЦО);
    if (лицо) беды.push(`сбито лицо, нужно «ты»: «${лицо[1]}»`);
  }

  for (const строкаЛичности of личность.helps) {
    const эхо = случай.helps.find((h) => однаСтрока(h, строкаЛичности));
    if (эхо) беды.push(`«помогает» повторяет личность: «${эхо}»`);
  }

  for (const помощь of случай.helps) {
    if (помощь !== помощь.trimStart()) беды.push(`«помогает» с пробелом в начале`);
    if (помощь.endsWith(".")) беды.push(`«помогает» с точкой в конце: «${помощь}»`);
    if (/^[А-ЯЁ]/.test(помощь)) беды.push(`«помогает» с заглавной: «${помощь}»`);
  }

  // --- Словарь ---------------------------------------------------------------

  const личностьТекстом = [
    личность.identity,
    личность.manner,
    ...личность.fears,
    ...(личность.finances ?? []),
    ...(личность.budget ? [личность.budget] : []),
    ...личность.warmsUp,
    ...личность.closesUp,
    ...личность.conditions,
    ...личность.helps,
    личность.decision,
  ]
    .join("\n")
    .toLowerCase();

  // Корень, совпадающий со словом из блоков механизма, бесполезен: механизм
  // одинаков у всех пациентов всех отраслей, и такой корень «находится»
  // в любом промпте. Поймано на «холодн» из стоматологического словаря —
  // оно совпало с «холоднее» в правиле про переспрос, и проверка протечек
  // начала ругаться на здоровый офтальмологический случай
  const вМеханизме = случай.vocabulary.filter((слово) =>
    содержитКорень(МЕХАНИЗМ_ТЕКСТОМ, слово.trim().toLowerCase()),
  );
  if (вМеханизме.length) {
    беды.push(
      `словарь совпадает со словами механизма (они есть у всех): ` +
        вМеханизме.join(", "),
    );
  }

  const годныеСлова = случай.vocabulary.filter((слово) => {
    const корень = слово.trim().toLowerCase();
    return кореньГоден(корень) && !содержитКорень(личностьТекстом, корень);
  });
  if (годныеСлова.length < МИНИМУМ_СЛОВАРЯ) {
    беды.push(
      `словарь из ${годныеСлова.length} отраслевых слов после чистки — ` +
        `проверка ослепнет (нужно ≥${МИНИМУМ_СЛОВАРЯ})`,
    );
  }

  // --- Анамнез и карточка ----------------------------------------------------

  const анамнез = пресет.anamnesis.toLowerCase();
  const гаданиеВАнамнезе = ГАДАНИЯ.find((г) => анамнез.includes(г));
  if (гаданиеВАнамнезе) беды.push(`анамнез гадает: «${гаданиеВАнамнезе}»`);

  if (!анамнез.includes(картина.diagnosis.trim().toLowerCase())) {
    беды.push(`анамнез не повторяет диагноз дословно: «${картина.diagnosis}»`);
  }
  if (!пресет.anamnesis.trimEnd().endsWith(картина.diagnosis.trim())) {
    беды.push("анамнез не заканчивается строкой «Диагноз: …»");
  }
  if (/^Пациент(ка)? (предъявляет|обратил|обратилась)/i.test(пресет.anamnesis)) {
    беды.push("анамнез начинается пересказом повода — эта строка видна всегда");
  }
  // Вывод о продаже вместо находки осмотра — то, на чём врачи забраковали
  // первую сборку целиком
  for (const оборот of ["требуется ", "показана ", "показано ", "рекомендована ", "необходима "]) {
    if (анамнез.includes(оборот)) {
      беды.push(`в анамнезе вывод о продаже: «${оборот.trim()}»`);
    }
  }

  if (!/^\d{1,3} (год|года|лет) · .+/.test(пресет.description)) {
    беды.push(`карточка не в форме «62 года · повод»: «${пресет.description}»`);
  }
  if (возраст !== null && !пресет.description.startsWith(`${возраст} `)) {
    беды.push(`в карточке не тот возраст: «${пресет.description}», а человеку ${возраст}`);
  }
  for (const у of клиника.services) {
    if (пресет.description.toLowerCase().includes(у.name.toLowerCase())) {
      беды.push(`в карточке название услуги «${у.name}» вместо повода`);
    }
  }

  for (const возражение of пресет.objections) {
    if (!/^«[^»]+»\s—\s[а-яё]/.test(возражение)) {
      беды.push(
        `возражение не в форме «реплика» — пояснение со строчной: «${возражение.slice(0, 45)}…»`,
      );
    }
  }

  // --- Результат диагностики -------------------------------------------------
  //
  // Сгенерированный документ проходит `чем_плох` в backend/services/diagnostics.py.
  // Написанный руками не проходил НИЧЕГО — а именно он теперь основной путь.
  // Проверки здесь повторяют питоновские; источник правды — там, при расхождении
  // менять оба.
  if (пресет.diagnostics !== undefined) {
    const документ = пресет.diagnostics;
    const строчный = документ.toLowerCase();

    if (документ.trim().length < ДОКУМЕНТ_МИН) {
      беды.push(`документ диагностики короче ${ДОКУМЕНТ_МИН} знаков`);
    }
    if (документ.trim().length > ДОКУМЕНТ_МАКС) {
      беды.push(
        `документ диагностики длиннее ${ДОКУМЕНТ_МАКС} знаков — читать между репликами нечем`,
      );
    }

    // Имя в шапке: документ, вставленный не тому пациенту, выглядит
    // безупречно и врёт молча
    const имя = пресет.patientName.split(" ")[0].toLowerCase();
    if (имя && !строчный.includes(имя)) {
      беды.push("в шапке документа диагностики нет имени пациента");
    }

    const гаданиеВДокументе = ГАДАНИЯ.find((г) => строчный.includes(г));
    if (гаданиеВДокументе) {
      беды.push(`документ диагностики гадает: «${гаданиеВДокументе}»`);
    }
    for (const оборот of ВЫВОДЫ_О_ПРОДАЖЕ) {
      if (строчный.includes(оборот)) {
        беды.push(`в документе диагностики вывод о продаже: «${оборот.trim()}»`);
      }
    }

    // Норм в настоящем заключении не пишут — их знает читатель. Форма
    // одобрена экспертом именно без них
    // Граница слова \b после кириллицы в JS не работает: \w там только
    // латиница, и проверка молча не срабатывала. В питоновском близнеце
    // \b корректен — это то самое место, где два языка расходятся
    // при одинаково выглядящем коде
    const норма = /[(\-–—]\s*норма(?![а-яё])/i.exec(документ);
    if (норма) {
      беды.push(`в документе диагностики норма рядом со значением: «${норма[0].trim()}»`);
    }
    for (const след of ["объект исследования", "способ исследования"]) {
      if (строчный.includes(след)) {
        беды.push(`в документе диагностики прежний бланк: «${след}»`);
      }
    }

    const разделов = (документ.match(/^\s*\*\*[^*]+\*\*/gm) || []).length;
    if (разделов < ДОКУМЕНТ_РАЗДЕЛОВ) {
      беды.push(
        `в документе диагностики ${разделов} разделов, нужно хотя бы ${ДОКУМЕНТ_РАЗДЕЛОВ}`,
      );
    }

    // Самое ценное: документ, называющий услугу, отдаёт менеджеру готовый
    // ответ. Тренировка в том и состоит, чтобы он вывел услугу сам
    const услуга = клиника.services.find((у) =>
      строчный.includes(у.name.toLowerCase()),
    );
    if (услуга) {
      беды.push(`документ диагностики называет услугу: «${услуга.name}»`);
    }
  }

  return беды;
}

/** Корень годится в словарь: не общий, не огрызок */
function кореньГоден(корень: string): boolean {
  return корень.length >= МИНИМУМ_КОРНЯ && !ОБЩИЕ_СЛОВА.has(корень);
}

/**
 * Проверки, которые видны только на всём наборе отрасли: покрытие пациентов
 * и разнообразие.
 */
export function проверитьНабор(
  случаи: PresetCase[],
  клиника: PresetClinic,
  ожидаемыеИмена: string[],
): string[] {
  const беды: string[] = [];

  const покрыты = new Set(случаи.map((с) => с.patientName));
  const непокрытые = ожидаемыеИмена.filter((имя) => !покрыты.has(имя));
  if (непокрытые.length) {
    // Частичный пресет опаснее отсутствующего: непокрытый пациент молча
    // упадёт на глобальный офтальмологический промпт, и стоматологическая
    // клиника получит человека с катарактой
    беды.push(`${клиника.industry}: без случая остались ${непокрытые.join(", ")}`);
  }
  const лишние = [...покрыты].filter((имя) => !ожидаемыеИмена.includes(имя));
  if (лишние.length) {
    беды.push(`${клиника.industry}: случаи для несуществующих пациентов — ${лишние.join(", ")}`);
  }

  // Одинаковая жалоба при одинаковом диагнозе — то, что врач замечает,
  // прочитав подряд два десятка карточек
  const поДиагнозу = new Map<string, string[]>();
  for (const с of случаи) {
    const ключ = с.picture.diagnosis.toLowerCase();
    поДиагнозу.set(ключ, [...(поДиагнозу.get(ключ) ?? []), с.picture.complaints]);
  }
  for (const [диагноз, жалобы] of поДиагнозу) {
    const уникальные = new Set(жалобы.map((ж) => ж.trim().toLowerCase()));
    if (уникальные.size !== жалобы.length) {
      беды.push(`${клиника.industry}: у диагноза «${диагноз}» повторяются жалобы дословно`);
    }
  }

  // Диагнозы клиники, не доставшиеся никому: список отрасли собран из самых
  // частых состояний, и пустующий диагноз значит, что он лишний в списке
  const выданные = new Set(случаи.map((с) => с.picture.diagnosis.toLowerCase()));
  const пустые = клиника.diagnoses.filter((д) => !выданные.has(д.name.toLowerCase()));
  if (пустые.length) {
    беды.push(
      `${клиника.industry}: диагнозы без единого пациента — ` +
        пустые.map((д) => д.name).join(", "),
    );
  }

  const описания = случаи.map((с) => с.description.trim().toLowerCase());
  if (new Set(описания).size !== описания.length) {
    беды.push(`${клиника.industry}: повторяются строки карточек`);
  }

  return беды;
}
