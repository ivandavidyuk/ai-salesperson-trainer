// Выгрузка личностей пациентов в JSON — для генератора случаев на backend.
//
// Личности живут в TypeScript (frontend/scripts/patients/), а генератор
// написан на Python и работает в контейнере на DE. В бою эту пропасть
// перешагивает Next.js: rebuildCases читает PROFILES и шлёт личность
// в запросе. Но для разовой сборки на вычитку поднимать всю цепочку
// с формой РОПа незачем — и вредно: она пишет в боевые данные, а второй
// прогон по другой отрасли затрёт первый.
//
// Поэтому выгружаем личности как есть и отдаём скрипту напрямую.
//
//   npm run --silent dump:personalities > личности.json
//
// Флаг --silent обязателен: без него npm печатает в stdout свою шапку
// с именем задачи, и JSON перестаёт разбираться.
//
// Дальше файл кладётся в контейнер и скармливается generate_for_review.py.

import { PROFILES } from "./patients";

const выгрузка = PROFILES.map((профиль) => ({
  name: профиль.name,
  personality: профиль.personality,
}));

// В stdout, а не в файл: путь выбирает вызывающий, а мешать ему нечем —
// сообщений скрипт не печатает
process.stdout.write(JSON.stringify(выгрузка, null, 2));
