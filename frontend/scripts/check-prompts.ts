function checkNoClinicWords(): void {
  const роли = Object.entries(ЭТАЛОННЫЕ_РОЛИ);
  for (const [name, role] of роли) {
    const text = personalityText(role.personality);
    const найдено = clinicWordsIn(name, text);
    if (найдено.length > 0) {
      fail(`${name}: в личности клинические слова — ${найдено.join(", ")}`);
    }
    const допуск = ДОПУСКИ_БИОГРАФИИ[name];
    if (!допуск) continue;
    const лишние = допуск.stems.filter((stem) => !containsStem(text, stem));
    if (лишние.length > 0) {
      fail(`${name}: допуск на «${лишние.join(", ")}» больше не нужен — убрать`);
    }
  }
  console.log(
    `Личность без клиники: ${роли.length} из ${роли.length}, ` +
      `допусков биографии ${Object.keys(ДОПУСКИ_БИОГРАФИИ).length}`,
  );
}

function checkIndustryResolver(): void {
  const ожидания: Array<[string, IndustryRules, string]> = [
    ["офтальмология", МЕДИЦИНА, "медицина"],
    ["стоматология: терапия и имплантация", МЕДИЦИНА, "медицина"],
    ["", МЕДИЦИНА, "медицина"],
    ["Недвижимость: офис продаж застройщика", НЕДВИЖИМОСТЬ, "недвижимость"],
    ["застройщик", НЕДВИЖИМОСТЬ, "недвижимость"],
  ];
  for (const [industry, rules, имя] of ожидания) {
    if (industryRules(industry) !== rules) {
      fail(`разборщик отрасли: «${industry}» должен давать ${имя}`);
    }
  }
  console.log(`Разборщик отрасли: ${ожидания.length} названий разобраны верно`);
}

function checkRealtyProbe(): void {
  const роли = Object.entries(ЭТАЛОННЫЕ_РОЛИ);
  let символов = 0;
  for (const [name, role] of роли) {
    const роль: PatientRole = { personality: role.personality, case: REALTY_CASE };
    const prompt = buildRolePrompt(роль, НЕДВИЖИМОСТЬ);
    const остались = clinicWordsIn(name, prompt);
    if (остались.length > 0) {
      fail(`проба недвижимости: у ${name} остались клинические слова — ${остались.join(", ")}`);
    }
    символов += prompt.length;
  }
  console.log(
    `Проба недвижимости: ${роли.length} личностей собраны с офисом продаж ` +
      `(${символов} символов), клиники не осталось`,
  );
}

