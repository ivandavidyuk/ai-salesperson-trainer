// Проверка промптов пациентов. Запуск: npm run check:prompts
//
// Промпт — не код, его нельзя проверить типами, а ошибка в нём проявляется
// только в живом разговоре и не всегда сразу. Поэтому проверяется машинно:
//
// 1. Собранный промпт Тамары совпадает с эталоном. Ловит любое изменение
//    текста — в том числе правку самого слоя механизма, которую проверка №2
//    по построению увидеть не может: она сверяет промпт с той же константой,
//    которая изменилась.
// 2. Слой механизма дошёл до каждой роли. Ловит другое: роль, до которой блок
//    не доехал — сборщик перестал его выдавать или пациента собрали в обход.
// 3. Личность не протекла отраслью — главная проверка разделения. Слова
//    случая не должны встречаться в слоте личности, иначе подмена случая даст
//    пациента, который рассуждает про катаракту, придя лечить зуб.
// 4. Подстановка чужого случая: та же личность собирается со стоматологическим
//    случаем, и промпт остаётся целым. Проверяет шов на сборке, а не на слово.
// 5. Два структурных инварианта: условие про оплату идёт первым номером,
//    блок запретов — последним.
// 6. Отраслевые пресеты: каждый пациент собирается с пресетным случаем своей
//    отрасли, и к нему применяются все проверки выше плюс контракты формы
//    из прод-генератора (см. presets/validate.ts). Пресеты написаны руками,
//    то есть мимо validate_case, — без этого раздела они уехали бы в прод
//    непроверенными вовсе.
//
// Проверки нарочно проверялись на отказ: без блока запретов падают первая
// и вторая, при вставке чего-либо после запретов — пятая.

