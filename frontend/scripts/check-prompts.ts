// 7. Личность без клиники. Проверка №3 ищет в личности слова конкретного
// случая («катаракт», «зуб»), а слова любой клиники — врач, приём, лечение —
// пропускает: до 16.09 граница слоёв проходила по «любой клинике», и замер
// нашёл такие слова у 21 личности из 21. Для других отраслей граница —
// «любая покупка». С 17.09 личности чистые все: ситуативные страхи и «деньги
// сегодня» — в случае, отраслевые слова в характере переписаны нейтрально.
// Остаётся биография: хирург остаётся хирургом в любой отрасли — на это
// допуск по имени, корню и причине, и допуск должен быть нужен.
const КЛИНИЧЕСКИЕ_СЛОВА = [
  "клиник", "врач", "лечен", "лечит", "приём", "прием", "осмотр", "пациент",
  "здоровь", "процедур", "вмешательств", "операц", "диагно", "снимок", "снимк",
  "медицин", "анестез", "наркоз", "палат",
];
const ДОПУСКИ_БИОГРАФИИ: Record<string, { stems: string[]; why: string }> = {
  "Борис Семёнович": {
    stems: ["медицин"],
    why: "профессор-хирург: «в медицинских кругах», «историю медицины»",
  },
  "Галина Петровна": {
    stems: ["здоровь"],
    why: "«смотришь передачи про здоровье» — быт пенсионерки",
  },
  "Григорий Игоревич": {
    stems: ["медицин", "клиник", "диагно"],
    why: "журналист-расследователь: «статьи про бизнес и медицину», «в клиниках города знают»; диагноз — его тайна",
  },
};

function clinicWordsIn(name: string, text: string): string[] {
  const allowed = ДОПУСКИ_БИОГРАФИИ[name]?.stems ?? [];
  return КЛИНИЧЕСКИЕ_СЛОВА.filter((stem) => !allowed.includes(stem) && containsStem(text, stem));
}

