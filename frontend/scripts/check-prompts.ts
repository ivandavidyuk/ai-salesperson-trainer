// Эталон Тамары. История: 4451 / ba3d2d9c… — снят с прода 30.07.2026;
// 4452 / c0f86b17… — после разреза личность ↔ случай; этот — после того, как
// сцена с согласующим стала двухшаговой, а запрет про настойчивость сузился
// до оплаты (живой разговор 30.07 показал, что прежняя формулировка сцену
// срывала).
//
// Сверяемся с хешем, а не с копией текста: копия в репозитории разошлась бы
// с базой незаметно, а хеш совпадает только с тем, что персонаж реально
// говорит. Намеренная правка промпта — значит обновить эти два числа тем же
// коммитом, и это видно в диффе.
// Обновлён 31.07.2026 (вторая правка за день): в запрете на ремарки исправлено
// обоснование. Оно обещало, что ремарку «произнесут вслух как есть», хотя
// strip_for_speech её вырезает — то есть собеседник получает тишину. Повод:
// первый полный прогон, где Станислав одиннадцать ходов из одиннадцати ответил
// одними ремарками в скобках. Прирост ровно 98 символов — только этот блок.
//
// Обновлён 10.08.2026 — самая крупная правка механизма с момента разреза
// слоёв. Повод: врач провёл живые разговоры с четырьмя пациентами и дал два
// десятка замечаний, которые разошлись по пяти корням, и все пять оказались
// не в личностях, а здесь.
//
// Что изменилось: условия согласия описаны состоянием, а не действиями
// менеджера (их зачитывали вслух); вопросы и сомнения отвязаны от возражений
// и разрешены с начала; сказано, что снимает сомнение, а что нет; появились
// блоки про размер хода и про деньги в моменте; страхи обязаны звучать;
// «когда теплеть» стало «от чего теплеешь». Прирост 2025 символов.
//
// Правка того же дня, вторая: у «переспроси, если не ответили» не было
// потолка, и модель обобщила его до «переспрашивай каждый ход». В прогоне
// Галина задала один вопрос восемь раз подряд, Виталий четыре. Теперь
// переспрос ровно один, а дальше пациент делает вывод о собеседнике —
// шаг вместо запрета шага.
//
// Третья правка того же дня: запрет на ремарки назывался только «в скобках»,
// и модель обошла его звёздочками — `*кивает*`, `*делает паузу*`. Вырезаются
// перед озвучкой оба вида, а запрещён был один. Теперь запрещено действие
// как таковое, любым способом записи. Заодно сказано, что короткий ход —
// это нормально: ремарки полезли там, где реплики стали короткими и модель
// добирала длину описанием действий.
//
// Обновлён 24.08.2026 — по второму разбору Димы, десять пациентов. Жалоба та
// же, что в августе: пациент проговаривает вслух, как к нему найти подход,
// и складывается, едва менеджер это повторит. Но чинить пришлось не там,
// где в прошлый раз: шесть запретов «не подсказывай» уже стояли в механизме
// с 10.08 и не удержали. Замер по расшифровкам 22.08 показал почему.
//
// Корень был не в запретах, а в том, что рецепт согласия выдавали сами:
// генератор случая обязан был называть продаваемую услугу в условиях
// (20 случаев из 21), а у пятерых она стояла прямо в «зачем пришёл» —
// «пришёл по поводу лазерной коррекции методом Relex SMILE». Пациент
// являлся с готовым продуктом, продавать было нечего. Правка ушла
// в case_generator.py.
//
// Что изменилось здесь: появилось второе обязательное условие — понимать,
// что у тебя и почему предложено именно это; повторение собственных слов
// пациента объяснением не считается. Появился слот бюджета: потолок суммы
// и сколько денег с собой сейчас — привычки в деньгах его не заменяли,
// и 10.08 два пациента отдали 727 и 272 тысячи наличными на диагностике.
// Условия личностей переписаны из «сделай X — и я соглашусь» в состояние,
// закавыченные реплики с триггером на повтор убраны: замер поймал
// «только тихо, пожалуйста» в четырёх ходах подряд. Прирост 1766 символов.
//
// 03.09: в «ДЕНЬГИ В МОМЕНТЕ» добавлено правило об оплаченном приёме — второй раз
// за него пациент не платит и просьбу оплатить называет ошибкой собеседника.
// Прежде это держалось только на тексте случая. Прирост 308 символов.
//
// Прежние эталоны, если понадобится сверка: 10047 / 6afc2124… (до правила
// об оплаченном приёме), 8281 / ed000765… (до условий-состояний),
// 8090 / e8040b9c… (до правки 10.08),
// 7816 / 4a86c5e1… (до потолка на переспрос),
// 5791 / bf6868fe… (до правки поведения),
// 5693 / 2d78b460… (до перезаморозки случаев),
// 5600 / 756826c9… (до запрета на чужое имя),
// 5245 / 43357e28… (до блока «отношение к деньгам»).
