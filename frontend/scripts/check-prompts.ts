// Проверка промптов пациентов. Запуск: npm run check:prompts
//
// Промпт — не код, его нельзя проверить типами, а ошибка в нём проявляется
// только в живом разговоре и не всегда сразу. Поэтому проверяется машинно:
//
// 1. Собранный промпт Тамары совпадает с эталоном. Ловит любое изменение
//    текста — в том числе правку самого слоя механизма, которую проверка №2
//    по построению увидеть не может: она сверяет промпт с той же константой,
//    которая изменилась.
// 2. Слой механизма дошёл до каждой роли. Ловит другое: роль, до которой блок
//    не доехал — сборщик перестал его выдавать или пациента собрали в обход.
// 3. Личность не протекла отраслью — главная проверка разделения. Слова
//    случая не должны встречаться в слоте личности, иначе подмена случая даст
//    пациента, который рассуждает про катаракту, придя лечить зуб.
// 4. Подстановка чужого случая: та же личность собирается со стоматологическим
//    случаем, и промпт остаётся целым. Проверяет шов на сборке, а не на слово.
// 5. Два структурных инварианта: условие про оплату идёт первым номером,
//    блок запретов — последним.
//
// Проверки нарочно проверялись на отказ: без блока запретов падают первая
// и вторая, при вставке чего-либо после запретов — пятая.

import { createHash } from "crypto";
import { writeFileSync } from "fs";
import { tmpdir } from "os";
import { join } from "path";

import { LAYERED_ROLES, PATIENTS } from "./seed-patients";
import {
  MECHANIC_BLOCKS,
  buildRolePrompt,
  personalityText,
  type PatientCase,
  type PatientRole,
} from "./patient-prompt";

// Эталон Тамары. История: 4451 / ba3d2d9c… — снят с прода 30.07.2026;
// 4452 / c0f86b17… — после разреза личность ↔ случай; этот — после того, как
// сцена с согласующим стала двухшаговой, а запрет про настойчивость сузился
// до оплаты (живой разговор 30.07 показал, что прежняя формулировка сцену
// срывала).
//
// Сверяемся с хешем, а не с копией текста: копия в репозитории разошлась бы
// с базой незаметно, а хеш совпадает только с тем, что персонаж реально
// говорит. Намеренная правка промпта — значит обновить эти два числа тем же
// коммитом, и это видно в диффе.
const TAMARA_BASELINE = {
  length: 5245,
  md5: "43357e28335045750c0ed36233baf1b9",
};

const md5 = (text: string) => createHash("md5").update(text, "utf8").digest("hex");

// Чужой случай для подстановки: стоматология вместо офтальмологии. Личность
// при подстановке не меняется — в этом и смысл разделения.
const DENTAL_CASE: PatientCase = {
  situation: `Ноет зуб снизу справа, недели три уже. Сначала только на холодное отзывался, теперь ноет и сам, особенно к вечеру. Жевать на эту сторону не получается — всё перекладываешь на левую. Год назад врач говорил, что пломба там глубокая и её пора менять, но ты отложила. За осмотр уже заплатила — пришла его пройти.`,
  calmWhile: `Пока разговор про осмотр, снимок или вопросы о здоровье — ты спокойна, отвечаешь охотно, можешь сама что-то уточнить. Ты пришла сюда сама и настроена доброжелательно.`,
  mannerExamples: `  Менеджер: «Давно болит?» → «Недели три. Сначала только на холодное.»
  Менеджер: «Расскажите, что вас беспокоит?» → «Ноет справа снизу, к вечеру сильнее. Жевать на эту сторону совсем не могу, всё на левую перекладываю. Год назад говорили пломбу менять, а я отложила.»`,
  conditions: [
    `Снят страх за безопасность в твоём возрасте — конкретикой: как проходит,
   сколько длится, чем обезболивают, что 62 года для этого лечения обычный
   возраст. «Не волнуйтесь, всё будет хорошо» не снимает ничего.`,
    `Снят страх отдать большие деньги и пожалеть — объяснили, что входит
   в стоимость, чем отличаются материалы, есть ли рассрочка. Просто назвать
   сумму — не снять страх, а создать его.`,
  ],
  helps: [
    `связал лечение с твоей жизнью, а не с номером зуба`,
    `объяснил, почему делать сейчас, а не «когда совсем разболится»`,
  ],
  vocabulary: ["зуб", "пломб", "жевать", "снимок"],
};

// Пробная роль: нужна, чтобы проверка «один раз написали — всем применилось»
// опиралась не на единственного пациента. Содержимое нарочно другое.
const PROBE_ROLE: PatientRole = {
  personality: {
    identity: "Ты — пробный пациент, 40 лет.",
    manner: "- Отвечай коротко",
    fears: ["Боится, что будет больно"],
    warmsUp: ["Если объясняют спокойно → теплеешь"],
    closesUp: ["Если торопят → замолкаешь"],
    conditions: ["Пройдена сцена с женой."],
    helps: ["дал выговориться"],
    decision: "Решаешь вместе с женой, она не против.",
  },
  case: {
    situation: "Пришёл провериться.",
    calmWhile: "Пока говорят про осмотр — спокоен.",
    mannerExamples: "  Менеджер: «Давно беспокоит?» → «С месяц.»",
    conditions: ["Снят страх боли."],
    helps: ["объяснил, почему сейчас"],
    vocabulary: [],
  },
};

const problems: string[] = [];
const fail = (text: string) => problems.push(text);

function checkMechanicLayer(label: string, prompt: string): void {
  // Сборщик обязан отдавать LF независимо от того, как лежит рабочая копия:
  // иначе сид с Windows записал бы в базу другой текст, чем сид в контейнере
  if (prompt.includes("\r")) {
    fail(`${label}: в собранном промпте остался CRLF — сборщик не нормализовал`);
  }

  MECHANIC_BLOCKS.forEach((block, index) => {
    if (!prompt.includes(block)) {
      const head = block.split("\n")[0];
      fail(`${label}: блок механизма №${index + 1} отсутствует или изменён — «${head}»`);
    }
  });

  // Условие про оплату занимает первый номер, свои условия пациента идут с 2
  if (!prompt.includes("1. Менеджер прямо предложил оплатить")) {
    fail(`${label}: условие про прямое предложение оплатить не первым номером`);
  }
  if (!/\n2\. /.test(prompt)) {
    fail(`${label}: нет условия под номером 2 — нумерация пациента сбита`);
  }

  // Запреты последними: вклиниться после них нельзя
  if (!prompt.endsWith(MECHANIC_BLOCKS[MECHANIC_BLOCKS.length - 1])) {
    fail(`${label}: блок запретов не в конце промпта`);
  }
}

/**
 * Слова случая не должны встречаться в личности.
 *
 * Проверяем именно текст личности, а не собранный промпт: слова вроде
 * «анестезия» принадлежат случаю, но чужой случай вправе их употреблять,
 * и поиск по всему промпту дал бы ложную тревогу.
 */
function checkNoCaseLeak(label: string, role: PatientRole): void {
  const text = personalityText(role.personality);
  for (const stem of role.case.vocabulary) {
    if (containsStem(text, stem)) {
      fail(`${label}: слово случая «${stem}» протекло в личность`);
    }
  }
}

/**
 * Ищет корень слова с начала слова, а не где попало внутри.
 *
 * Подстрочный поиск давал ложные тревоги: корень «очк» находится в середине
 * «рассрочки», и подстановка стоматологического случая — где рассрочка тоже
 * упоминается — сообщала о протечке офтальмологии. Поэтому перед корнем
 * обязана стоять не-буква.
 */
function containsStem(text: string, stem: string): boolean {
  const escaped = stem.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return new RegExp(`(?<![A-Za-zА-Яа-яЁё])${escaped}`, "i").test(text);
}

function main(): void {
  console.log("=== Проверка промптов ===\n");

  // 1. Тамара совпадает с эталоном
  const tamara = buildRolePrompt(LAYERED_ROLES["Тамара Михайловна"]);
  const actual = { length: tamara.length, md5: md5(tamara) };
  const same =
    actual.length === TAMARA_BASELINE.length && actual.md5 === TAMARA_BASELINE.md5;

  console.log(`Тамара Михайловна: ${actual.length} символов, md5 ${actual.md5}`);
  if (same) {
    console.log("  совпадает с эталоном\n");
  } else {
    console.log(
      `  ЭТАЛОН: ${TAMARA_BASELINE.length} символов, md5 ${TAMARA_BASELINE.md5}\n`,
    );
    fail(
      "промпт Тамары разошёлся с эталоном. Если правка намеренная — обновите " +
        "TAMARA_BASELINE тем же коммитом; если нет, сборщик изменил текст",
    );
    // Во временную папку, а не в репозиторий: иначе каждый неудачный прогон
    // оставлял бы неотслеживаемый файл в рабочей копии
    const dump = join(tmpdir(), "tamara-assembled.txt");
    writeFileSync(dump, tamara, "utf8");
    console.log(`  собранный промпт записан в ${dump}\n`);
  }

  // 2-3. Слой механизма и непротекание отрасли — у всех на слоях и у пробной
  for (const [name, role] of Object.entries(LAYERED_ROLES)) {
    checkMechanicLayer(name, buildRolePrompt(role));
    checkNoCaseLeak(name, role);
  }
  checkMechanicLayer("пробный пациент", buildRolePrompt(PROBE_ROLE));

  const layered = Object.keys(LAYERED_ROLES).length;
  console.log(
    `Слой механизма: ${MECHANIC_BLOCKS.length} блоков проверено ` +
      `у ${layered + 1} ролей (${layered} настоящих + пробная)`,
  );

  const words = Object.values(LAYERED_ROLES).reduce(
    (sum, role) => sum + role.case.vocabulary.length,
    0,
  );
  console.log(`Личность без отрасли: ${words} слов случая проверено`);

  // 4. Подстановка чужого случая: личность та же, случай стоматологический
  const swapped: PatientRole = {
    personality: LAYERED_ROLES["Тамара Михайловна"].personality,
    case: DENTAL_CASE,
  };
  const swappedPrompt = buildRolePrompt(swapped);
  checkMechanicLayer("Тамара со стоматологическим случаем", swappedPrompt);
  checkNoCaseLeak("Тамара со стоматологическим случаем", swapped);
  // И наоборот: офтальмологических слов в подменённом промпте быть не должно
  // вовсе — ни в личности, ни в блоках случая
  const leaked = LAYERED_ROLES["Тамара Михайловна"].case.vocabulary.filter((stem) =>
    containsStem(swappedPrompt, stem),
  );
  if (leaked.length > 0) {
    fail(
      `подстановка: в промпте со чужим случаем остались слова прежнего — ` +
        leaked.join(", "),
    );
  }
  console.log(
    `Подстановка случая: ${swappedPrompt.length} символов, ` +
      `офтальмологии не осталось`,
  );

  // 5. Сколько ещё на заглушках — чтобы не забылось молча
  const stubs = PATIENTS.filter((p) => !(p.name in LAYERED_ROLES));
  console.log(`\nНа слоях: ${layered} из ${PATIENTS.length} пациентов`);
  if (stubs.length > 0) {
    console.log(`Заглушки: ${stubs.map((p) => p.name).join(", ")}`);
  }

  if (problems.length > 0) {
    console.error(`\n${problems.length} проблем:`);
    for (const problem of problems) console.error(`  — ${problem}`);
    process.exit(1);
  }
  console.log("\nВсё сходится.");
}

main();
