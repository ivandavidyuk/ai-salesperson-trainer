const problems: string[] = [];
const fail = (text: string) => problems.push(text);

function checkMechanicLayer(label: string, prompt: string, blocks: string[] = MECHANIC_BLOCKS): void {
  // Сборщик обязан отдавать LF независимо от того, как лежит рабочая копия:
  // иначе сид с Windows записал бы в базу другой текст, чем сид в контейнере
  if (prompt.includes("\r")) {
    fail(`${label}: в собранном промпте остался CRLF — сборщик не нормализовал`);
  }

  blocks.forEach((block, index) => {
    if (!prompt.includes(block)) {
      const head = block.split("\n")[0];
      fail(`${label}: блок механизма №${index + 1} отсутствует или изменён — «${head}»`);
    }
  });

  // Условие про оплату занимает первый номер, свои условия пациента идут с 2
  if (!prompt.includes("1. Менеджер прямо предложил оплатить")) {
    fail(`${label}: условие про прямое предложение оплатить не первым номером`);
  }
  if (!/\n2\. /.test(prompt)) {
    fail(`${label}: нет условия под номером 2 — нумерация пациента сбита`);
  }

  // Запреты последними: вклиниться после них нельзя
  if (!prompt.endsWith(MECHANIC_BLOCKS[MECHANIC_BLOCKS.length - 1])) {
    fail(`${label}: блок запретов не в конце промпта`);
  }
}

/**
 * Слова случая не должны встречаться в личности.
 *
 * Проверяем именно текст личности, а не собранный промпт: слова вроде
 * «анестезия» принадлежат случаю, но чужой случай вправе их употреблять,
 * и поиск по всему промпту дал бы ложную тревогу.
 */
function checkNoCaseLeak(label: string, role: PatientRole): void {
  const text = personalityText(role.personality);
  for (const stem of role.case.vocabulary) {
    if (containsStem(text, stem)) {
      fail(`${label}: слово случая «${stem}» протекло в личность`);
    }
  }
}

/**
 * Ищет корень слова с начала слова, а не где попало внутри.
 *
 * Подстрочный поиск давал ложные тревоги: корень «очк» находится в середине
 * «рассрочки», и подстановка стоматологического случая — где рассрочка тоже
 * упоминается — сообщала о протечке офтальмологии. Поэтому перед корнем
 * обязана стоять не-буква.
 */
function containsStem(text: string, stem: string): boolean {
  const escaped = stem.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return new RegExp(`(?<![A-Za-zА-Яа-яЁё])${escaped}`, "i").test(text);
}

/**
 * Отраслевые пресеты: собранный промпт, форма слотов и чистота отрасли.
 *
 * Каждый случай проходит те же проверки, что эталонные роли, плюс две.
 * Первая — контракты генератора (`presets/validate.ts`): пресеты написаны
 * руками, мимо `validate_case`, а обязаны выглядеть ровно так, как выглядит
 * его выход.
 *
 * Вторая — кросс-отраслевая чистота. У одного пациента теперь несколько
 * случаев в разных отраслях, и промпт стоматологического не смеет нести
 * ни одного офтальмологического слова: это ровно та проверка подстановки,
 * что стоит у Тамары, только на настоящих данных, а не на образце.
 */
function checkPresets(): void {
  const личности = new Map(PROFILES.map((p) => [p.name, p.personality]));
  const именаПациентов = PROFILES.map((p) => p.name);

  // Словари всех отраслей по пациенту — по ним ищется протечка чужой отрасли
  const словариПоПациенту = new Map<string, Map<string, string[]>>();
  for (const пресет of ПРЕСЕТЫ) {
    for (const случай of пресет.cases) {
      const поОтраслям = словариПоПациенту.get(случай.patientName) ?? new Map();
      поОтраслям.set(пресет.clinic.industry, случай.case.vocabulary);
      словариПоПациенту.set(случай.patientName, поОтраслям);
    }
  }

  let проверено = 0;
  for (const пресет of ПРЕСЕТЫ) {
    const отрасль = пресет.clinic.industry;

    for (const беда of проверитьНабор(пресет.cases, пресет.clinic, именаПациентов)) {
      fail(беда);
    }

    for (const случай of пресет.cases) {
      const личность = личности.get(случай.patientName);
      if (!личность) {
        fail(`пресет ${отрасль}: нет личности для «${случай.patientName}»`);
        continue;
      }
      const метка = `${случай.patientName} · ${отрасль}`;
      const роль: PatientRole = { personality: личность, case: случай.case };
      const правила = industryRules(отрасль);
      const prompt = buildRolePrompt(роль, правила);

      checkMechanicLayer(метка, prompt, mechanicBlocks(правила));
      checkNoCaseLeak(метка, роль);
      for (const беда of проверитьСлучай(случай, личность, пресет.clinic)) {
        fail(`${метка}: ${беда}`);
      }

      // Слова другой отрасли в этом промпте — брак: пациент, пришедший
      // лечить зуб, не должен рассуждать про хрусталик
      for (const [чужая, словарь] of словариПоПациенту.get(случай.patientName) ?? []) {
        if (чужая === отрасль) continue;
        const протекло = словарь.filter((stem) => containsStem(prompt, stem));
        if (протекло.length > 0) {
          fail(`${метка}: слова отрасли «${чужая}» в промпте — ${протекло.join(", ")}`);
        }
      }
      проверено++;
    }
  }

  const отрасли = ПРЕСЕТЫ.map((п) => п.clinic.industry).join(", ");
  console.log(
    `\nПресеты: ${проверено} случаев в ${ПРЕСЕТЫ.length} отраслях (${отрасли})`,
  );
}

