// Ключ отрасли организации.
//
// С 18.09 отрасль хранится отдельным полем `Organization.industryKey`,
// а не угадывается по свободному тексту: «Новостройки» угадывание отдавало
// медицине, а в продукте за отраслью идут правила промпта, слова оценщика
// и закрытые функции. Ключ ставится при заведении организации — из пресета
// (create-client, create-demo, seed:presets); клиника, заведённая формой
// руководителя, — медицина. Свободный текст `industry` остаётся: по нему
// генерация клиник пишет случаи («стоматология — терапия и имплантация»).
//
// Отдельным модулем, а не внутри patient-prompt.ts: ключ нужен и экранам
// (слова интерфейса — lib/industryWords.ts), а модуль промптов тянул бы
// в браузер весь текст механизма.

/** Отрасли продукта. Медицина — база: её тексты эталонные, остальные — поверх */
export const ОТРАСЛИ = ["медицина", "недвижимость"] as const;

/** Ключ отрасли: по нему выбираются правила, состав персонажей и пресет */
export type IndustryKey = (typeof ОТРАСЛИ)[number];

/**
 * Отрасли, у которых нет клинических функций (диагностика, генерация
 * случаев). Таблицы только для них — отчёт эксперту, проба промпта —
 * типизируются этим типом: добавленная отрасль не соберётся, пока
 * в каждой такой таблице нет её строки
 */
export type НемедицинскаяОтрасль = Exclude<IndustryKey, "медицина">;

/**
 * Ключ из базы. Незнакомое значение — медицина: так же вела себя
 * организация до отраслей, и так безопасно для каждой клиники
 */
export function ключОтрасли(value: string | null | undefined): IndustryKey {
  return (ОТРАСЛИ as readonly string[]).includes(value ?? "")
    ? (value as IndustryKey)
    : "медицина";
}
