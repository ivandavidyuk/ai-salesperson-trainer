async function main() {
  console.log("=== Пациенты ===\n");

  for (const item of PATIENTS) {
    // В схеме у пациента нет уникального поля — ищем по имени
    const existing = await prisma.patient.findFirst({ where: { name: item.name } });
    if (existing) {
      await prisma.patient.update({ where: { id: existing.id }, data: item });
    } else {
      await prisma.patient.create({ data: item });
    }
    const mark = item.isActive ? "доступен" : "скоро";
    const size = `${item.prompt.length} символов промпта`;
    console.log(`${existing ? "обновлён" : "создан "}  ${item.name} · ${mark} · ${size}`);
  }

  console.log(`\nВсего пациентов: ${PATIENTS.length}`);
  console.log("Промпты перезаписаны значениями из этого файла.");
}

// Сид запускается только при прямом вызове: проверялка промптов импортирует
// из этого файла PATIENTS и LAYERED_ROLES, и заливать при этом базу не должна
if (require.main === module) {
  main()
    .catch((error) => {
      console.error("\nНепредвиденная ошибка:", error);
      process.exit(1);
    })
    .finally(async () => {
      await prisma.$disconnect();
    });
}
