// Документ врача: разбор строк бланка по макету «Экран звонка».
//
// В самом тексте заголовки разделов обёрнуты в звёздочки: так их требует
// промпт генератора, и по ним же код считает разделы и ловит пустые
// (`backend/services/diagnostics.py`). Убрать звёздочки из документов нельзя —
// они несущие; поэтому их разбирает показ. До этого документ выводился как
// есть, и менеджер читал сырые `**` и на звонке, и в расшифровке.
//
// Дизайн различает заголовок и значение не жирностью, а цветом, отступом
// и воздухом: заголовок раздела темнее и с просветом сверху, значения под
// ним — со сдвигом вправо и обычным цветом. Полужирная только первая строка.

/** Строка вида `**Заголовок:** остаток` — заголовок и всё, что за ним */
const ЗАГОЛОВОК = /^\*\*(.+?)\*\*\s*(.*)$/;

interface DiagnosticsDocumentProps {
  text: string;
  /** Размер, цвет и прокрутку задаёт вызывающий экран — они у них разные */
  className?: string;
}

export default function DiagnosticsDocument({
  text,
  className = "",
}: DiagnosticsDocumentProps) {
  // Пустые строки не переносим: воздух между разделами даёт отступ заголовка,
  // иначе после разбора остались бы двойные просветы
  const строки = text
    .split("\n")
    .map((строка) => строка.trim())
    .filter(Boolean);
  // Значения сдвигаются вправо только под заголовком. Документ без заголовков
  // (генератор сломался, старая запись) читается тогда как простой текст,
  // а не как список без начала
  const первыйЗаголовок = строки.findIndex((строка) => ЗАГОЛОВОК.test(строка));

  return (
    <div className={className}>
      {строки.map((строка, индекс) => {
        const разбор = ЗАГОЛОВОК.exec(строка);

        if (!разбор) {
          const подЗаголовком = первыйЗаголовок >= 0 && индекс > первыйЗаголовок;
          return (
            <div key={индекс} className={подЗаголовком ? "pl-3.5" : undefined}>
              {строка}
            </div>
          );
        }

        const [, заголовок, остаток] = разбор;

        // Первая строка — шапка документа: «Первичный осмотр» и кто пациент.
        // Она читается целиком, поэтому выделена вся, а не одно название
        if (индекс === 0) {
          return (
            <div key={индекс} className="mb-2 font-semibold text-ink">
              {остаток ? `${заголовок} · ${остаток}` : заголовок}
            </div>
          );
        }

        return (
          <div key={индекс} className="mt-1.5 text-ink">
            {заголовок}
            {/* Значение в одной строке с заголовком («Ведущий глаз: OD») —
                обычным цветом, как и значения под заголовком */}
            {остаток && <span className="font-normal text-ink-label"> {остаток}</span>}
          </div>
        );
      })}
    </div>
  );
}
