"""Учёт израсходованных токенов — по требованию, без влияния на бой.

Повод: 04.08 смета прогона разошлась с реальным счётом, и выяснить, на что
именно ушли деньги, было нечем. Оценка «столько-то символов в промпте» врёт
дважды — она не видит ни выхода, ни токенов размышления, а у Claude
размышление тарифицируется как выход и бывает больше самого ответа.

Устроено на contextvars: пока никто не открыл учёт, счётчика нет и функции
ничего не делают. Голосовой пайплайн из-за этого не меняется вовсе — ему
учёт не нужен, а лишняя работа на ходу разговора не нужна тем более.

    with учёт() as счёт:
        ...вызовы моделей...
    print(счёт.как_словарь())
"""

from contextlib import contextmanager
from contextvars import ContextVar
from dataclasses import dataclass, field
from typing import Iterator, Optional

# Активный счётчик текущей задачи. None — учёт не ведётся
_текущий: ContextVar[Optional["Счёт"]] = ContextVar("счёт_токенов", default=None)


@dataclass
class ПоМодели:
    вызовов: int = 0
    вход: int = 0
    выход: int = 0
    # Токены размышления. Провайдер кладёт их внутрь выхода, но считает
    # отдельным полем — и именно они оказались тем, чего не было в смете
    размышление: int = 0


@dataclass
class Счёт:
    модели: dict[str, ПоМодели] = field(default_factory=dict)

    def добавить(
        self,
        модель: str,
        вход: int,
        выход: int,
        размышление: int = 0,
    ) -> None:
        запись = self.модели.setdefault(модель, ПоМодели())
        запись.вызовов += 1
        запись.вход += вход
        запись.выход += выход
        запись.размышление += размышление

    @property
    def всего_токенов(self) -> int:
        return sum(м.вход + м.выход for м in self.модели.values())

    def как_словарь(self) -> dict:
        return {
            "всего_токенов": self.всего_токенов,
            "по_моделям": {
                имя: {
                    "вызовов": м.вызовов,
                    "вход": м.вход,
                    "выход": м.выход,
                    "размышление": м.размышление,
                }
                for имя, м in sorted(self.модели.items())
            },
        }


@contextmanager
def учёт() -> Iterator[Счёт]:
    """Открывает учёт на время блока. Вложенные блоки считают независимо."""
    счёт = Счёт()
    токен = _текущий.set(счёт)
    try:
        yield счёт
    finally:
        _текущий.reset(токен)


def записать(модель: str, usage: Optional[dict]) -> None:
    """Кладёт usage из ответа провайдера в открытый счёт.

    Молчит, если учёт не открыт или провайдер usage не прислал: пропущенный
    учёт не повод ронять разговор.
    """
    счёт = _текущий.get()
    if счёт is None or not usage:
        return
    подробности = usage.get("completion_tokens_details") or {}
    счёт.добавить(
        модель,
        вход=int(usage.get("prompt_tokens") or 0),
        выход=int(usage.get("completion_tokens") or 0),
        размышление=int(подробности.get("reasoning_tokens") or 0),
    )
