"""Генератор случая: с чем пациент пришёл в конкретную клинику.

Личность пациента написана вручную и одна на все клиники: характер, манера,
быт, страхи, механика согласующего. Случай — повод обращения, анамнез, чем
снимаются страхи — зависит от отрасли, и его собирает эта модель по данным,
которые заполнил руководитель.

Генератор не «дополняет» случай, а пишет его целиком: в аватарах, которые
пишет автор пациентов, медицинского содержания нет вовсе. Отсюда и главный
риск: ошибка здесь — не корявая фраза, а несуществующая болезнь, которую
менеджер услышит как факт. Вычитки человеком нет (сто пациентов никто читать
не станет), поэтому качество держится на инструкции ниже и на проверках
в validate_case.

Отдаёт слоты, а не готовый текст. Собирает промпт frontend существующей
функцией buildRolePrompt — второй реализации сборщика на Python не появляется,
значит нечему разъезжаться.
"""

import logging
import re
from typing import Optional

from core.config import get_settings
from services.llm_json import ask_json

logger = logging.getLogger(__name__)

# Два вида сбоя лечатся по-разному, и путать их нельзя.
#
# Провайдер отказал (429, пустой ответ) — повторять надо С ПАУЗОЙ, иначе
# три запроса подряд упрутся в тот же лимит. Это умеет ask_json, ему
# и передаём число попыток.
#
# Ответ пришёл, но не годится по форме — повторять можно сразу: провайдер
# жив, дело в модели.
_PROVIDER_ATTEMPTS = 3
_SHAPE_ATTEMPTS = 2

# Ровно два примера манеры: в замере одна модель выдала сорок шесть, и это
# прошло бы проверку «поле на месте». Считаем, а не только проверяем наличие
_MANNER_EXAMPLES = 2
_MIN_VOCABULARY = 5

# Слова, которые звучат в любой клинике и в любой продаже. В словаре случая
# им не место: по нему ищут отраслевые протечки в личность, а «врач»
# и «решени» в личности Тамары есть законно — она про мужа и про то, что
# крупные решения принимаются вместе. Оставь их в словаре, и проверка начнёт
# ругаться на верный текст, а настоящую протечку не заметят среди шума.
_GENERIC_VOCABULARY = frozenset(
    {
        "врач", "решени", "стоимост", "приём", "прием", "осмотр", "риск",
        "цен", "довер", "лечени", "процедур", "клиник", "пациент", "здоровь",
        "деньг", "оплат", "рассрочк", "консультац", "специалист",
    }
)

# Медицинская карта не гадает. Модель охотно пишет «отсутствие зуба
# (предположительно, одного или нескольких)» — менеджер читает анамнез
# как данность, и такая осторожность превращается в брак.
_HEDGES = ("предположительн", "возможно", "вероятно", "скорее всего", "по-видимому")

# Признак того, что условие написано как инструкция менеджеру, а не как
# состояние пациента: «Чтобы снять страх…, нужно рассказать…». Такой текст
# кладёт в промпт пациента готовый ответ, который менеджер должен добыть сам.
_INSTRUCTION_VOICE = ("нужно ", "необходимо ", "следует ", "менеджер должен")

# Промпт обращается к пациенту на «ты», и списки — тоже. Модель срывается
# то в первое лицо («страх за безопасность в моём возрасте»), то в третье
# («позволит ей общаться с внуками»); в собранном промпте это заметно.
# Ловим только однозначные местоимения: «её» пропускаем намеренно — оно
# может законно указывать на другого человека, например на жену.
#
# Обязательно по границам слова, а не подстрокой: «ей» сидит внутри «твоей»,
# и без границ проверка забракует ровно тот текст, которого добивается
_WRONG_PERSON = re.compile(
    r"(?<![А-Яа-яЁёA-Za-z])"
    r"(моём|моем|моего|моей|моя|мою|мои|мне|меня|ей|ему)"
    r"(?![А-Яа-яЁёA-Za-z])",
    re.IGNORECASE,
)

REQUIRED_FIELDS = (
    "situation",
    "calmWhile",
    "mannerExamples",
    "caseConditions",
    "caseHelps",
    "vocabulary",
    "anamnesis",
    "description",
    "objections",
)

INSTRUCTIONS = """Ты собираешь «случай» для тренажёра по продажам: пациента,
которого играет ИИ, а менеджер клиники учится с ним разговаривать.

Личность пациента уже написана и МЕНЯТЬСЯ НЕ ДОЛЖНА. Твоя работа — придумать,
с чем именно этот человек пришёл в эту клинику, и написать недостающие части.

ГЛАВНОЕ ПРАВИЛО: не противоречь личности. Проверь себя по трём пунктам.
1. Если в блоке «как принимает решение» есть согласующий (муж, жена, сын),
   случай не вправе делать пациента одиноким или решающим единолично.
   Это ломает не правдоподобие, а механизм сделки.
2. Возраст, занятость, быт, характер — берутся из личности как есть.
   Не придумывай пациенту работу, если он на пенсии.
3. Страхи в личности заданы формой («боится, что в его возрасте это опасно»).
   Случай наполняет их содержанием, но не заменяет другими.

ВТОРОЕ ПРАВИЛО: не выдумывай услуг и цен. Бери только то, что есть в списке
клиники. Если чего-то нет — не упоминай вовсе.

Пиши на «ты», обращаясь к пациенту, как написана личность. Это касается
и списков: «в твоём возрасте», «твою проблему с жеванием», «позволит тебе
общаться с внуками». Не «в моём возрасте» и не «позволит ей» — пациент
читает этот текст как обращённый к себе, и сбитое лицо в нём заметно.

Ремарок в скобках и описаний действий не пиши — пациента только слышно.

Верни JSON с полями:

"situation" — зачем пришёл. Повод обращения, что человек знает о своей
  проблеме, что уже предпринимал, почему тянул. 3-5 предложений. Здесь же
  указать, что за приём уже заплачено — он пришёл его пройти.

"calmWhile" — пока разговор о чём пациент спокоен и отвечает охотно.
  1-2 предложения.

"mannerExamples" — массив РОВНО ИЗ ДВУХ строк. Примеры ответов на языке этой
  отрасли, показывающие соразмерность: на закрытый вопрос коротко,
  на открытый развёрнуто. Формат строки, с двумя пробелами в начале:
  "  Менеджер: «вопрос» → «ответ»"

  Ответы не должны спорить с "situation": человек, который пришёл с жалобой,
  не отвечает «нет, ничего не беспокоит».

"caseConditions" — массив РОВНО ИЗ ДВУХ строк: при каком условии пациент
  соглашается. Первая — про страх за безопасность процедуры, вторая — про
  страх отдать деньги и пожалеть.

  Вторую пиши по блоку «отношение к деньгам» из личности, если он есть.
  Человеку, который считает переплату, нужен график платежей; тому, кто
  привык к наличным, — скидка за оплату сразу; тому, кто боится слова
  «кредит», — рассрочка от клиники без банка. Общее «расскажите про
  рассрочку» не годится ни одному из них.

  Пиши УСЛОВИЕ, А НЕ ИНСТРУКЦИЮ МЕНЕДЖЕРУ. Это текст в промпте пациента:
  он описывает, когда пациент перестаёт бояться, а не подсказывает готовый
  ответ. Начинай со снятого страха («Снят страх…»), перечисляй, какой
  конкретикой он снимается, и заканчивай тем, что НЕ засчитывается.
  Каждая строка — 2-3 предложения.

  Образец формы (отрасль будет другая, копируй строй, а не содержание):
    "Снят страх за безопасность в твоём возрасте — конкретикой: как проходит,
     сколько длится, какая анестезия, что 62 года для этой операции обычный
     возраст. «Не волнуйтесь, всё будет хорошо» не снимает ничего."

  Так писать НЕЛЬЗЯ — это инструкция менеджеру и готовый ответ:
    "Чтобы снять страх за безопасность, нужно подробно рассказать, что
     процедура стандартная и давно отработанная."

"caseHelps" — массив из 1-2 строк: что помогает, но не обязательно.
  Глагол в прошедшем времени, со строчной буквы, без точки в конце.

  НЕ ПОВТОРЯЙ то, что уже перечислено в личности в блоке про «помогает»:
  эти строки встанут в один список, и повтор будет виден дословно. Личность
  говорит про обращение с человеком вообще; твои строки — про само лечение:
  связать его с жизнью этого человека, объяснить, почему делать сейчас.

  Образец формы:
    "связал лечение с твоей жизнью, а не с диоптриями"
    "объяснил, почему делать сейчас, а не «когда совсем плохо станет»"

"vocabulary" — массив из 8-12 корней слов, с начала слова и без окончаний:
  например для офтальмологии "очк", "диоптри", "катаракт", "хрусталик".
  По этому списку проверяется, что отраслевые слова не протекли в личность.

  Слово годится, только если пациент ДРУГОЙ клиники его бы не сказал.
  Не бери то, что встречается в любой клинике и в любой продаже: "врач",
  "решени", "стоимост", "приём", "осмотр", "риск", "цен", "довер".
  На таких словах проверка начнёт ругаться на законную личность
  и перестанет ловить настоящие протечки.

"anamnesis" — то, что менеджер видит ДО разговора. Только медицинские факты:
  что болит, сколько длится, что говорил врач раньше. Ни мнений пациента,
  ни его мотивов, ни того, с кем он советуется — это он должен раскопать
  в разговоре сам.

  Пиши определённо. Это медицинская карта: «предположительно», «возможно»,
  «вероятно», «скорее всего» в ней недопустимы. Не знаешь точно — придумай
  и напиши как факт, менеджер читает это как данность.

"description" — одна короткая строка для карточки: возраст и повод.
  Например "62 года · диагностика зрения".

"objections" — массив из трёх строк. Возражения, которых менеджеру ждать:
  прямая речь пациента в «ёлочках», затем тире и короткое пояснение
  со строчной буквы, какой страх за ней. Возражения вытекают из страхов
  личности, а не из общих соображений.

  Говорит их сам пациент — не обращайся в них к пациенту по имени.

  Образец формы:
    "«А в моём возрасте это не опасно?» — страх за безопасность операции"
    "«Мне надо с мужем посоветоваться» — одна такое не решает"

Только JSON, без markdown-обёртки."""


def build_messages(personality: dict, clinic: dict) -> list[dict]:
    """Собирает запрос: инструкция отдельно, данные клиники и личность — отдельно."""
    services = "\n".join(
        f"- {s.get('name', '')} — {s.get('price', '')}."
        + (f" {s['description']}" if s.get("description") else "")
        for s in clinic.get("services", [])
    )
    personality_text = "\n\n".join(
        f"{key}: {value if not isinstance(value, list) else chr(10).join(value)}"
        for key, value in personality.items()
    )
    return [
        {"role": "system", "content": INSTRUCTIONS},
        {
            "role": "user",
            "content": (
                f"КЛИНИКА: {clinic.get('name', '')}\n"
                f"ОТРАСЛЬ: {clinic.get('industry', '')}\n\n"
                f"УСЛУГИ И ЦЕНЫ:\n{services or '— не указаны'}\n\n"
                f"ЛИЧНОСТЬ ПАЦИЕНТА (не менять):\n{personality_text}"
            ),
        },
    ]


def _same_line(left: str, right: str) -> bool:
    """Одна ли это строка с точностью до регистра и знаков препинания."""
    strip = str.maketrans("", "", " .,;:—-«»\"'()")
    return left.lower().translate(strip) == right.lower().translate(strip)


def validate_case(case: dict, personality: Optional[dict] = None) -> Optional[str]:
    """Проверяет форму ответа. Возвращает причину отказа либо None.

    Проверяем не только наличие полей, но и количество элементов: в замере
    модель однажды вернула сорок шесть примеров манеры вместо двух, и это
    не отказ, а тихий мусор — он прошёл бы проверку «поле на месте» и уехал
    в промпт, который услышит менеджер.
    """
    missing = [field for field in REQUIRED_FIELDS if not case.get(field)]
    if missing:
        return f"нет полей: {', '.join(missing)}"

    examples = case["mannerExamples"]
    if isinstance(examples, str):
        # Часть моделей отдаёт строкой с переносами — это допустимо
        examples = [line for line in examples.split("\n") if line.strip()]
        case["mannerExamples"] = examples
    if len(examples) != _MANNER_EXAMPLES:
        return f"примеров манеры {len(examples)}, а нужно {_MANNER_EXAMPLES}"

    for field, expected in (("caseConditions", 2), ("objections", 3)):
        if len(case[field]) != expected:
            return f"{field}: {len(case[field])} вместо {expected}"

    if not 1 <= len(case["caseHelps"]) <= 3:
        return f"caseHelps: {len(case['caseHelps'])}, ожидалось 1-3"

    # Общие слова вычищаем, а не отвергаем весь ответ: остальной случай может
    # быть хорош, а список — единственное, что в нём подпорчено
    vocabulary = [
        word for word in case["vocabulary"] if word.strip().lower() not in _GENERIC_VOCABULARY
    ]
    dropped = len(case["vocabulary"]) - len(vocabulary)
    if dropped:
        logger.info("Из словаря случая убрано общих слов: %d", dropped)
    case["vocabulary"] = vocabulary
    if len(vocabulary) < _MIN_VOCABULARY:
        return f"словарь из {len(vocabulary)} отраслевых слов — проверка ослепнет"

    anamnesis = case["anamnesis"].lower()
    hedge = next((h for h in _HEDGES if h in anamnesis), None)
    if hedge:
        return f"анамнез гадает: «{hedge}»"

    for condition in case["caseConditions"]:
        lowered = condition.lower()
        voice = next((v for v in _INSTRUCTION_VOICE if v in lowered), None)
        if voice:
            return f"условие написано инструкцией менеджеру: «{voice.strip()}»"

    # Списки «помогает» из личности и из случая склеиваются в один, поэтому
    # переписанная строка личности видна в промпте дословным повтором.
    # Инструкции против этого не хватило: модель охотно копирует то, что
    # видит на входе
    for helps in (personality or {}).get("helps", []):
        echo = next((h for h in case["caseHelps"] if _same_line(h, helps)), None)
        if echo:
            return f"«помогает» повторяет личность: «{echo}»"

    for line in [*case["caseConditions"], *case["caseHelps"]]:
        person = _WRONG_PERSON.search(line)
        if person:
            return f"сбито лицо, нужно «ты»: «{person.group(1)}»"

    return None


async def generate_case(personality: dict, clinic: dict) -> Optional[dict]:
    """Случай под клинику. Возвращает слоты либо None, если не получилось.

    Никогда не бросает: сбой на одном пациенте не должен ронять сборку
    остальных.
    """
    settings = get_settings()
    messages = build_messages(personality, clinic)

    for attempt in range(1, _SHAPE_ATTEMPTS + 1):
        case = await ask_json(
            messages,
            model=settings.case_model,
            purpose="случай",
            attempts=_PROVIDER_ATTEMPTS,
            temperature=0.7,  # текст должен быть живым, а не воспроизводимым
            # С включённым размышлением бюджет уходит на мысли, и JSON
            # обрывается на середине строки. У оценщика та же причина
            # и тот же потолок
            max_tokens=8000,
        )
        if case is None:
            # Провайдер не ответил и после всех повторов с паузами —
            # повторять ещё раз тем же способом бессмысленно
            return None

        problem = validate_case(case, personality)
        if problem is None:
            return case
        logger.warning(
            "Генератор случая, попытка %d: ответ не годится — %s", attempt, problem
        )

    logger.error(
        "Генератор случая: %d ответа подряд не прошли проверку формы", _SHAPE_ATTEMPTS
    )
    return None
