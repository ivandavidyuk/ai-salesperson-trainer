"""Разбор реплик: очистка для синтеза и механические проверки текста.

Общий дом для чистых функций над репликами. Раньше они жили в двух местах:
`strip_for_speech` в `main.py`, а разбор совпадений — в `qa/checks.py`.
Второе особенно неудобно: `qa` — инструмент проверки промптов, и когда
эти же функции понадобились выдаче достижений, производственный код
пришлось бы тянуть из инструмента.

Здесь только чистые функции: ни базы, ни сети, ни настроек.
"""

import re

# Разметка и ремарки, которые модель вставляет вопреки запрету в промпте.
# Замер 31.07.2026 на четырёх моделях: чистой нет ни одной. Gemini пишет
# скобочные ремарки («(Прищуривается, внимательно слушает.)»), gpt-5.4-nano —
# Markdown с жирным и списками, qwen — и то, и другое сразу: «*(Молча беру
# у вас папку, достаёт лупу)*».
#
# Запрет в промпте оставляем — он работает, просто не всегда. А это страховка
# на выходе: до синтеза ремарка доходить не должна ни от какой модели, иначе
# TTS произнесёт её вслух как реплику пациента.
_MARKDOWN_CHARS = str.maketrans("", "", "*_`#")

# Слова от четырёх букв: короткие служебные совпадают у всех подряд
_СЛОВО = re.compile(r"[А-Яа-яЁё]{4,}")

_ПРЕДЛОЖЕНИЕ = re.compile(r"[^.!?]+[.!?]?")


def strip_for_speech(text: str) -> str:
    """Убирает из реплики всё, что нельзя произнести вслух.

    Работает по готовому предложению, а не по дельтам стрима: дельта режется
    где попало, и «**» приезжает половинками.

    Скобки чистятся и незакрытые тоже: предложение отрезается по точке, и
    ремарка из двух предложений разрывается пополам — «(Молча беру папку.»
    в одном, «Достаёт лупу.)» в другом. Обе половины одинаково не нужны.
    """
    # Парные скобки целиком
    text = re.sub(r"\([^()]*\)", " ", text)
    # Хвост незакрытой скобки и начало неоткрытой — остатки разорванной ремарки
    text = re.sub(r"\([^()]*$", " ", text)
    text = re.sub(r"^[^()]*\)", " ", text)
    text = text.translate(_MARKDOWN_CHARS)
    # Нумерация списка в начале строки: «1) », «2. » — читается вслух нелепо
    text = re.sub(r"(?m)^\s*\d+[.)]\s+", "", text)
    return re.sub(r"\s+", " ", text).strip()


def значимые_слова(текст: str) -> set[str]:
    """Слова от четырёх букв: короткие служебные совпадают у всех подряд."""
    return {слово.lower() for слово in _СЛОВО.findall(текст)}


def слова_подряд(текст: str) -> list[str]:
    """Значимые слова в порядке следования — для поиска дословных кусков."""
    return [с.lower() for с in _СЛОВО.findall(текст)]


def вопросы(реплика: str) -> list[str]:
    """Вопросительные предложения реплики — то, на что ждут ответа."""
    очищенная = strip_for_speech(реплика)
    return [
        кусок.strip()
        for кусок in _ПРЕДЛОЖЕНИЕ.findall(очищенная)
        if "?" in кусок and len(кусок.strip()) > 10
    ]


def найти_присказку(реплики: list[str], минимум: int = 3) -> tuple[str, int]:
    """Тройка слов, кочующая из реплики в реплику. Пусто — присказки нет.

    @param минимум в скольких репликах тройка должна встретиться. Проверка
    промптов считает присказкой три хода, достижению «Попка-дурак» нужно
    пять — поэтому порог параметр, а не константа модуля.
    """
    где: dict[tuple[str, str, str], set[int]] = {}
    for номер, реплика in enumerate(реплики, 1):
        слова = слова_подряд(реплика)
        for i in range(len(слова) - 2):
            где.setdefault((слова[i], слова[i + 1], слова[i + 2]), set()).add(номер)
    if not где:
        return "", 0
    тройка, ходы = max(где.items(), key=lambda пара: len(пара[1]))
    if len(ходы) < минимум:
        return "", 0
    return " ".join(тройка), len(ходы)
