"""Критик: вторая модель перечитывает готовый случай и ищет неправдоподобие.

Страховка, а не основная починка. Причину — вывернутую причинность, когда
диагноз подгонялся под услугу, — вылечил порядок вызовов в case_generator.
Критик ставится поверх, чтобы ловить то, что всё равно просачивается.

ПОЧЕМУ ДРУГАЯ МОДЕЛЬ. Картину пишет одна модель, прозу другая; критик обязан
быть из третьего семейства. Модель, проверяющая собственную логику, с собой
соглашается — и проверка превращается в подпись под своей же ошибкой.

ПОЧЕМУ УЗКИЕ ВОПРОСЫ. «Правдоподобно ли это» — вопрос, на который модель
отвечает наугад. «Попадает ли возраст в окно начала» — вопрос с ответом.
Список вопросов взят из четырёх измерений, по которым разошлись все семь
замечаний двух врачей 06-07.08: окно начала, частота в возрасте, стадия
и её симптомы, условие проявления. Ни одно из них не привязано к отрасли.

ЧЕЙ БРАК — ЧАСТЬ ВЕРДИКТА. Без этого пересборка бывает заведомо бесполезной:
если не сходится сам диагноз с возрастом, переписывание прозы не поможет
никогда. Поэтому критик обязан назвать виновника, а вызывающий по нему
решает, что пересобирать.

ОШИБКИ КРИТИКА НЕСИММЕТРИЧНЫ. Ложный отказ дёшев: берём следующую картину
из уже готовых, теряем разнообразие. Ложный пропуск дорог: врач видит
чепуху, и мы там, откуда начали. Поэтому лучше перебдеть — но не ценой
пациента: без случая он не остаётся никогда, худший исход это пометка.
"""

import logging
from typing import Optional

from core.config import get_settings
from services.llm_json import ask_json

logger = logging.getLogger(__name__)

# Отказ провайдера повторяем; отказа по форме здесь нет — разбор мягкий,
# непонятный ответ считаем «годится», чтобы сбой критика не стоил пациента
_PROVIDER_ATTEMPTS = 2

ВИНОВАТА_КАРТИНА = "картина"
ВИНОВАТА_ПРОЗА = "проза"


REVIEW_INSTRUCTIONS = """Ты — практикующий специалист отрасли, о которой пойдёт
речь. Тебе показывают карточку пациента, собранную автоматически, и просят
сказать, бывает ли так на самом деле.

Ты не редактор и не корректор: стиль, длина и красота текста тебя не
интересуют. Тебя интересует одно — не противоречит ли написанное тому,
как эти состояния ведут себя в жизни.

ПРОВЕРЬ ПЯТЬ ВЕЩЕЙ, каждую отдельно.

1. ОКНО НАЧАЛА. Может ли это состояние ВПЕРВЫЕ возникнуть в таком возрасте?
   Есть состояния, которые начинаются только в определённый период жизни
   и у взрослого впервые появиться не могут.

   СУДИ САМ, а не по строке «Начинается» в карточке. Её писала та же
   машина, что и всё остальное, и если она ошиблась — ошиблась именно там.
   Замер 07.08: миопия у сорокавосьмилетнего прошла проверку только потому,
   что в карточке стояло «начинается в любом возрасте», и это приняли
   на веру. Сначала ответь на вопрос из своих знаний, потом сверься
   с карточкой — расхождение и есть брак.

2. ЧАСТОТА. Типичный это случай для такого возраста или редкое исключение,
   выданное за обычное? Исключения бывают, но их не выдают за норму.

3. СТАДИЯ. Названа стадия — принадлежат ли ей описанные жалобы? Яркие
   узнаваемые симптомы обычно принадлежат поздним стадиям; если при ранней
   стадии описана развёрнутая картина, это брак. Проверь и обратное: если
   жалобы означают состояние более запущенное, чем названо, диагноз неверен.

4. УСЛОВИЕ ПРОЯВЛЕНИЯ. Заметил бы этот человек такое при своей жизни,
   работе и привычках? Бывает, что состояние есть, а человек его не
   чувствует, пока не окажется в определённых обстоятельствах.

5. ЛЕЧЕНИЕ. Названная услуга действительно лечит это состояние?

Отдельно: не выдуман ли сам диагноз. Название должно быть настоящим,
а не собранным из подходящих по смыслу слов.

Верни JSON. Поля именно в этом порядке:

"checks" — массив из пяти строк, по одной на проверку выше, коротко:
  что проверил и что увидел. Сначала разбор, потом вывод — не наоборот.

"fault" — кто виноват, если брак есть:
  "картина" — неверен сам выбор: не тот возраст, не та стадия, редкость
    вместо обычного, услуга не лечит, выдуманный диагноз. Переписывание
    текста тут не спасёт, нужна другая картина.
  "проза" — картина верна, а текст ей противоречит: приписаны жалобы,
    которых в картине нет, или вывод о продаже вместо находки осмотра.
  null — если брака нет.

"objection" — ОДНО предложение: что именно не так. Пиши так, чтобы по нему
  можно было исправить. Если брака нет — пустая строка.

"verdict" — "годится" или "брак".

Только JSON, без markdown-обёртки."""


def build_review_messages(personality: dict, picture: dict, case: dict, service: str) -> list[dict]:
    """Запрос критику: кто пациент, что ему поставили и что прочтёт менеджер."""
    # Личность целиком не нужна — критику важен возраст и образ жизни,
    # то есть то, из чего он поймёт, заметил бы человек описанное. Характер,
    # страхи и манера речи к правдоподобию диагноза отношения не имеют
    кто = str(personality.get("identity", ""))
    карточка = (
        f"Диагноз: {picture.get('diagnosis', '')}\n"
        f"Начинается: {picture.get('onset', '')}\n"
        f"Типичность: {picture.get('typicalFor', '')}\n"
        f"Стадия: {picture.get('stage', '')}\n"
        f"Жалобы: {picture.get('complaints', '')}\n"
        f"Замечает при: {picture.get('noticedWhen', '')}\n"
        f"Осмотр: {picture.get('objective', '')}\n"
        f"Предлагаемая услуга: {service}"
    )
    return [
        {"role": "system", "content": REVIEW_INSTRUCTIONS},
        {
            "role": "user",
            "content": (
                f"ЧЕЛОВЕК:\n{кто}\n\n"
                f"ЧТО ЕМУ ПОСТАВИЛИ:\n{карточка}\n\n"
                f"АНАМНЕЗ, КОТОРЫЙ ПРОЧТЁТ МЕНЕДЖЕР:\n{case.get('anamnesis', '')}"
            ),
        },
    ]


def разобрать(ответ: Optional[dict]) -> tuple[bool, Optional[str], str]:
    """Ответ критика → (годится, чей брак, возражение). Чистая функция.

    Непонятный ответ считаем «годится»: критик — страховка, и его сбой
    не должен стоить пациенту случая. Молчаливый пропуск здесь лучше
    молчаливой потери.
    """
    if not isinstance(ответ, dict):
        return True, None, ""

    вердикт = str(ответ.get("verdict") or "").strip().lower()
    возражение = str(ответ.get("objection") or "").strip()
    виновник = str(ответ.get("fault") or "").strip().lower()

    if вердикт != "брак":
        return True, None, ""
    # Брак назван, а виновника нет — считаем виноватой прозу: она дешевле
    # в пересборке, и картина остаётся в запасе на следующую попытку
    if виновник not in (ВИНОВАТА_КАРТИНА, ВИНОВАТА_ПРОЗА):
        виновник = ВИНОВАТА_ПРОЗА
    return False, виновник, возражение or "критик забраковал без пояснения"


async def review(
    personality: dict,
    picture: dict,
    case: dict,
    service: str,
) -> tuple[bool, Optional[str], str]:
    """Перечитывает случай. Возвращает (годится, чей брак, возражение).

    Пока не включён настройкой — молча соглашается, не тратя вызова.
    Непроверенный критик опаснее отсутствующего: он бракует молча,
    и систематическая ошибка выглядит как проверенное качество.
    """
    if not get_settings().critic_enabled:
        return True, None, ""

    ответ = await ask_json(
        build_review_messages(personality, picture, case, service),
        model=get_settings().critic_model,
        purpose="критик случая",
        attempts=_PROVIDER_ATTEMPTS,
        temperature=0.0,  # суждение, а не сочинение
    )
    годится, виновник, возражение = разобрать(ответ)
    if not годится:
        logger.info(
            "Критик забраковал «%s» (виновата %s): %s",
            picture.get("diagnosis", ""),
            виновник,
            возражение,
        )
    return годится, виновник, возражение
