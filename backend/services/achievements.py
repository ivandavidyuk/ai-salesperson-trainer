"""Выдача достижений: за что и когда открывается бейдж.

Двадцать семь бейджей нарисованы и засеяны, но до этого модуля не открывался
ни один — связи проставлял только сид демо-аккаунта.

Ядро здесь — чистая функция `оценить`: ни базы, ни сети, ни настроек.
Так условия можно проверить тестами, не поднимая Postgres, а это единственный
способ не ошибиться в пороге и не заметить.

ЧЕГО МЕХАНИЗМ НЕ ВЫДАЁТ И НЕ БУДЕТ, пока не появятся данные:

- `wolf`, `seller`, `confident-seller` — суммы сделок в системе нет;
- `no-discount` — скидок мы не храним;
- `sold-a-pen` — «сложный продукт» нигде не определён;
- `objection-slayer`, `terminator` — в разборе есть ОЦЕНКА этапа возражений,
  но не число отработанных возражений, а бейджи просят именно счёт;
- `king-of-the-hill` — первое место за месяц: календарное условие, которому
  нужен ежемесячный запуск, а такого механизма в проекте нет.

Список НЕВЫДАВАЕМЫХ закреплён тестом намеренно: без него легко «починить»
их наугад, подставив похожее по смыслу поле, и молча начать врать.
"""

import logging
import re
from dataclasses import dataclass, field

from services.text import вопросы, найти_присказку

logger = logging.getLogger(__name__)

# Достижения, которые механизм не выдаёт (см. шапку модуля)
НЕВЫДАВАЕМЫЕ = frozenset({
    "wolf", "seller", "confident-seller", "no-discount", "sold-a-pen",
    "objection-slayer", "terminator", "king-of-the-hill",
})

# «Быстрая» сделка — по описанию бейджа
_БЫСТРО_СЕК = 25 * 60

# «Мгновенный отказ»: пациент ушёл, не начав разговора
_МГНОВЕННО_СЕК = 3 * 60

# Сколько раз одна тройка слов должна прозвучать, чтобы это была не речь,
# а заклинание. Описание бейджа говорит «5 раз за тренировку»
_ПОПУГАЙ_ПОВТОРОВ = 5

# Мат: корни ищутся В НАЧАЛЕ СЛОВА, а не подстрокой где угодно.
#
# Подстрокой было бы катастрофой ровно в этом продукте: «рубля» содержит
# «бля», а цену в рублях называют в каждом разговоре о продаже. Поймано
# на боевых данных до начисления — шуточный бейдж «Ты псих!» достался бы
# почти всем. Туда же «хлебал» и «погребал» с «ебал» внутри.
_МАТ_НАЧАЛА = (
    "бля", "хуй", "хуё", "хуе", "пизд", "ебал", "ебан", "ёбан",
    "заеб", "наеб", "уеб", "доеб", "въеб", "отъеб",
)

# Сращения, где корень стоит не в начале, а слово однозначное
_МАТ_ЦЕЛИКОМ = ("похуй", "нахуй", "нахуя", "нихуя", "охуе", "ахуе", "похую")

_СЛОВО_РУС = re.compile(r"[а-яё]+")


@dataclass
class Разговор:
    """Один законченный разговор — всё, что о нём знает выдача."""

    duration_sec: int = 0
    outcome: str | None = None          # paid / refused / not_asked
    overall: float | None = None
    needs: float | None = None
    objections: float | None = None
    # Все пять этапных оценок проставлены — значит дошли до закрытия
    все_этапы: bool = False
    patient_id: str | None = None
    patient_hard: bool = False
    started_at_day: str = ""            # YYYY-MM-DD, для «трёх подряд»
    реплики_менеджера: list[str] = field(default_factory=list)
    реплики_пациента: list[str] = field(default_factory=list)


@dataclass
class Сводка:
    """Накопленное по пользователю ДО этого разговора."""

    завершённых: int = 0
    закрытых: int = 0
    закрытых_сложным: int = 0
    закрытых_по_пациентам: dict[str, int] = field(default_factory=dict)
    подряд_без_сделки: int = 0
    разговоров_в_день: dict[str, int] = field(default_factory=dict)


def оценить(сводка: Сводка, разговор: Разговор) -> set[str]:
    """Какие бейджи заработаны ЭТИМ разговором с учётом прошлого.

    Возвращает слаги. Чистая функция: одни и те же входные данные всегда
    дают один и тот же ответ.
    """
    закрыл = разговор.outcome == "paid"

    # Счётчики с учётом текущего разговора
    завершённых = сводка.завершённых + 1
    закрытых = сводка.закрытых + (1 if закрыл else 0)
    у_пациента = сводка.закрытых_по_пациентам.get(разговор.patient_id or "", 0) + (
        1 if закрыл and разговор.patient_id else 0
    )
    сложных = сводка.закрытых_сложным + (1 if закрыл and разговор.patient_hard else 0)
    в_день = сводка.разговоров_в_день.get(разговор.started_at_day, 0) + 1

    заработано: set[str] = set()

    def дать(слаг: str, условие: bool) -> None:
        if условие and слаг not in НЕВЫДАВАЕМЫЕ:
            заработано.add(слаг)

    # --- Счётом по разговорам и сделкам ---
    дать("first-contact", завершённых >= 1)
    дать("closer", закрытых >= 1)
    дать("triple-kill", закрытых >= 3)
    дать("rampage", закрытых >= 5)
    дать("fearless", завершённых > 50)
    дать("shark", сложных >= 3)
    дать("kenny", у_пациента >= 5)
    дать("quickdraw", закрыл and 0 < разговор.duration_sec < _БЫСТРО_СЕК)
    дать("best-of-the-best", разговор.overall is not None and разговор.overall >= 10)
    дать("no-lunch", в_день >= 3)
    # «Упал — вставай»: важно, что до этого разговора шли десять подряд
    # без сделки. Именно подряд, а не десять всего за всё время
    дать("get-up", сводка.подряд_без_сделки >= 10)

    # --- Оценками этапов. ПРИБЛИЖЕНИЕ, и это надо помнить ---
    #
    # «Выявить все потребности» и «профилактировать все возражения» точными
    # признаками в системе не описаны: у нас есть оценка этапа от нуля до
    # десяти, а не перечень выявленного. Берём максимум оценки как «сделал
    # всё, что можно» — ближайшее честное приближение. Появится разбор
    # по пунктам — условие надо будет переписать, а не подкручивать порог
    дать("detective", разговор.needs is not None and разговор.needs >= 10)
    дать("preemptive", разговор.objections is not None and разговор.objections >= 10)
    дать("scriptolog", разговор.все_этапы)

    # --- Разбором текста этого разговора ---
    реплики = разговор.реплики_менеджера
    сказал_менеджер = sum(len(р) for р in реплики)
    сказал_пациент = sum(len(р) for р in разговор.реплики_пациента)

    # «Глухарь» только у состоявшегося разговора: в пустом вопросов нет
    # по той же причине, по какой нет ничего
    дать(
        "deaf",
        bool(реплики) and not any(вопросы(р) for р in реплики),
    )
    дать(
        "chatterbox",
        not закрыл and сказал_пациент > 0 and сказал_менеджер > сказал_пациент,
    )
    дать("parrot", найти_присказку(реплики, _ПОПУГАЙ_ПОВТОРОВ)[1] >= _ПОПУГАЙ_ПОВТОРОВ)
    дать("youre-crazy", _есть_мат(реплики))
    дать(
        "door-is-there",
        разговор.outcome == "refused" and 0 < разговор.duration_sec < _МГНОВЕННО_СЕК,
    )

    return заработано


def _есть_мат(реплики: list[str]) -> bool:
    """Мат в речи менеджера. Полноты словаря не обещаем, ложных — не допускаем.

    Ищем по словам, а не подстрокой: цена «41 902 рубля» не должна открывать
    шуточный бейдж за брань. Лучше пропустить редкую форму, чем обвинить
    человека, назвавшего сумму.
    """
    for слово in _СЛОВО_РУС.findall(" ".join(реплики).lower()):
        if слово.startswith(_МАТ_НАЧАЛА):
            return True
        if any(сращение in слово for сращение in _МАТ_ЦЕЛИКОМ):
            return True
    return False


def продолжить(сводка: Сводка, разговор: Разговор) -> Сводка:
    """Сводка после этого разговора — для следующего шага при начислении.

    Отдельно от `оценить`, потому что у них разные обязанности: одна судит,
    другая накапливает. Смешай их — и порядок вызовов начнёт менять ответ.
    """
    закрыл = разговор.outcome == "paid"
    по_пациентам = dict(сводка.закрытых_по_пациентам)
    if закрыл and разговор.patient_id:
        по_пациентам[разговор.patient_id] = по_пациентам.get(разговор.patient_id, 0) + 1
    в_день = dict(сводка.разговоров_в_день)
    в_день[разговор.started_at_day] = в_день.get(разговор.started_at_day, 0) + 1
    return Сводка(
        завершённых=сводка.завершённых + 1,
        закрытых=сводка.закрытых + (1 if закрыл else 0),
        закрытых_сложным=сводка.закрытых_сложным + (1 if закрыл and разговор.patient_hard else 0),
        закрытых_по_пациентам=по_пациентам,
        подряд_без_сделки=0 if закрыл else сводка.подряд_без_сделки + 1,
        разговоров_в_день=в_день,
    )


# --- Слой базы ------------------------------------------------------------
#
# Ниже — всё, что ходит в Postgres. Держим отдельно от ядра намеренно:
# условия выдачи должны проверяться тестами без базы, и смешивать их
# с запросами значило бы потерять эту возможность.

# История пользователя: по строке на завершённый разговор, в порядке времени.
# Джойн с разбором и пациентом — здесь же, чтобы не ходить в базу по разу
# на разговор.
_ИСТОРИЯ_SQL = """
SELECT s."id",
       s."patientId",
       COALESCE(s."durationSec", 0) AS duration_sec,
       to_char(s."startedAt", 'YYYY-MM-DD') AS day,
       r."outcome"::text            AS outcome,
       r."overallScore"             AS overall,
       r."needsScore"               AS needs,
       r."objectionsScore"          AS objections,
       (r."contactScore"    IS NOT NULL
        AND r."iceBreakerScore" IS NOT NULL
        AND r."needsScore"      IS NOT NULL
        AND r."objectionsScore" IS NOT NULL
        AND r."closingScore"    IS NOT NULL) AS все_этапы,
       COALESCE(p."difficulty"::text = 'hard', false) AS patient_hard
FROM "Session" s
LEFT JOIN "SessionReview" r ON r."sessionId" = s."id"
LEFT JOIN "Patient" p       ON p."id" = s."patientId"
WHERE s."userId" = $1 AND s."status" = 'completed'
ORDER BY s."startedAt" ASC
"""

_РЕПЛИКИ_SQL = """
SELECT "role"::text AS role, "text"
FROM "Message" WHERE "sessionId" = $1 ORDER BY "createdAt" ASC
"""


def _из_строки(строка) -> Разговор:
    """Строка истории → разговор без реплик. Тексты добираются отдельно."""
    return Разговор(
        duration_sec=строка["duration_sec"],
        outcome=строка["outcome"],
        overall=строка["overall"],
        needs=строка["needs"],
        objections=строка["objections"],
        все_этапы=строка["все_этапы"],
        patient_id=строка["patientId"],
        patient_hard=строка["patient_hard"],
        started_at_day=строка["day"],
    )


async def _реплики(pool, session_id: str) -> tuple[list[str], list[str]]:
    """Реплики менеджера и пациента этого разговора."""
    строки = await pool.fetch(_РЕПЛИКИ_SQL, session_id)
    менеджер = [с["text"] for с in строки if с["role"] == "user"]
    пациент = [с["text"] for с in строки if с["role"] == "assistant"]
    return менеджер, пациент


async def выдать(pool, user_id: str, слаги: set[str], когда) -> list[str]:
    """Записывает бейджи, которых у человека ещё нет. Возвращает выданные.

    Идемпотентно: `ON CONFLICT DO NOTHING`. Бейдж выдаётся один раз, и дата
    получения не переписывается — иначе повторный прогон начисления сдвинул
    бы все даты на сегодня.
    """
    выданы: list[str] = []
    for слаг in sorted(слаги):
        строка = await pool.fetchrow(
            'INSERT INTO "UserAchievement" ("userId", "achievementId", "unlockedAt") '
            "VALUES ($1, $2, $3) ON CONFLICT DO NOTHING RETURNING \"achievementId\"",
            user_id,
            слаг,
            когда,
        )
        if строка is not None:
            выданы.append(слаг)
    return выданы


async def начислить_за_сессию(pool, session_id: str) -> list[str]:
    """Оценивает достижения после одного разговора. Возвращает новые.

    Историю читаем целиком и сворачиваем тем же `продолжить`, что и начисление
    задним числом: одна дорога вместо двух — значит они не разойдутся.
    """
    владелец = await pool.fetchrow(
        'SELECT "userId" FROM "Session" WHERE "id" = $1', session_id
    )
    if владелец is None:
        return []
    user_id = владелец["userId"]

    история = await pool.fetch(_ИСТОРИЯ_SQL, user_id)
    сводка = Сводка()
    текущий: Разговор | None = None
    for строка in история:
        разговор = _из_строки(строка)
        if строка["id"] == session_id:
            текущий = разговор
            break
        сводка = продолжить(сводка, разговор)

    # Разговора нет в истории — он ещё не завершён. Оценивать нечего
    if текущий is None:
        return []

    текущий.реплики_менеджера, текущий.реплики_пациента = await _реплики(pool, session_id)
    заработано = оценить(сводка, текущий)
    if not заработано:
        return []

    когда = await pool.fetchval(
        'SELECT COALESCE("endedAt", "startedAt") FROM "Session" WHERE "id" = $1',
        session_id,
    )
    return await выдать(pool, user_id, заработано, когда)
