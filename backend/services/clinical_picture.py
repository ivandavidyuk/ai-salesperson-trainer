"""Клиническая картина: чем человек такого возраста может болеть на самом деле.

Отдельный модуль, а не часть case_generator, намеренно. 06.08.2026 Дима (врач)
забраковал сгенерированные случаи: миопия, впервые возникшая в 48 и 44 года,
начальная катаракта с жалобой на даль вместо близи. «Так не бывает».

Причина была не в незнании модели — она медицину знает. Причина в том, что
её об этом не спрашивали: анамнез рождался одним полем из девяти, под
инструкцией «случай обязан подразумевать продаваемую услугу». Модель брала
услугу и подгоняла диагноз под неё. В замере это видно дословно — в графе
«объективно» стояло «требуется лазерная коррекция зрения».

Поэтому здесь про продажу не сказано ни слова, и списка услуг на входе нет.
Подгонять нечего. Услуга подбирается ПОСЛЕ, отдельным узким вопросом, и уже
не может повлиять на диагноз.

Справочников диагнозов мы не держим: механизм обязан работать на любой
отрасли, которую задаст руководитель, включая нишу без нашей экспертизы.
Опора — знания самой модели, а наше дело — задать правильный вопрос.
"""

import logging
from typing import Optional

from core.config import get_settings
from services.llm_json import ask_json

logger = logging.getLogger(__name__)

_PROVIDER_ATTEMPTS = 3
_SHAPE_ATTEMPTS = 2

# Меньше трёх — не из чего выбирать, если под первую картину у клиники нет
# услуги. Больше пяти — модель начинает выскребать редкости, а нам нужны
# частые случаи: тренажёр учит типовому разговору, а не консилиуму
_PICTURES_MIN = 3
_PICTURES_MAX = 5

# Диагноз — не место для размышлений вслух. Тот же список, что у анамнеза
# в case_generator, плюс дизъюнкция: «близорукость слабой ИЛИ средней
# степени» прошла прежнюю проверку, хотя это ровно то же гадание
_HEDGES = (
    "предположительн", "возможно", "вероятно", "скорее всего", "по-видимому",
    "неизвестн", "не установлен", "уточнить у",
)

_PICTURE_FIELDS = ("diagnosis", "ageRange", "complaints", "objective", "treatment")


CLINICAL_INSTRUCTIONS = """Ты — опытный врач той отрасли, которую назовут ниже.
Тебе дают возраст человека и короткое описание его быта. Назови клинические
картины, которые для такого человека правдоподобны.

О продажах, услугах и ценах тебя не спрашивают. Ты не знаешь, что умеет
клиника, и подстраиваться не подо что: назови то, что бывает на самом деле.

Верни JSON вида {"pictures": [...]} — от 3 до 5 картин, по УБЫВАНИЮ
вероятности для этого возраста. Первая — самая частая.

Поля каждой картины:

"diagnosis" — как состояние называется в этой отрасли. Одна строка,
  без пояснений.

"ageRange" — в каком возрасте это состояние появляется и у кого встречается.
  Одна строка. Это самопроверка: если возраст пациента в диапазон
  не попадает, картина не годится и её тут быть не должно.

"complaints" — на что человек жалуется своими словами, 1-2 предложения.
  Жалобы ДОЛЖНЫ СЛЕДОВАТЬ ИЗ ДИАГНОЗА. Не приписывай к диагнозу жалобы,
  которых он не даёт, и не бери жалобу «вообще плохо».

"objective" — что видит специалист при осмотре: находки, измерения, стадия.
  1-2 предложения. Только то, что действительно видно на осмотре.

"treatment" — что с этим состоянием делают. Название вмешательства или
  тактики, как это принято называть в отрасли. Одна строка.

ТРИ ПРОВЕРКИ. Пройди по каждой картине, прежде чем её оставить.

1. ВОЗРАСТ. Состояние, которое по своей природе врождённое или возникает
   в детстве, НЕ МОЖЕТ впервые появиться у взрослого. Взрослый может с ним
   жить давно — но тогда так и напиши, а не выдавай за новую находку.
   Ровно на этом ломались прежние сборки.

2. СЛЕДСТВИЕ. Прочитай жалобы, закрыв диагноз: приводят ли они именно
   к нему? Если из этих жалоб врач подумал бы о другом — картина неверна.
   Проверь и обратное: какие жалобы этот диагноз даёт РАНЬШЕ всего.
   Часто первой страдает не та функция, о которой хочется написать.

3. ОПРЕДЕЛЁННОСТЬ. Это медицинские сведения, а не рассуждение. «Возможно»,
   «вероятно», «предположительно», «слабой или средней степени» недопустимы:
   выбери одно и напиши как факт.

Только JSON, без markdown-обёртки."""


MATCH_INSTRUCTIONS = """Тебе дают клинические картины и список услуг клиники.
Для каждой картины скажи, какая услуга ЛЕЧИТ это состояние.

Это подбор, а не продажа. Не надо ничего пристраивать: если ни одна услуга
это состояние не лечит, так и ответь. Услуга, которая состоянию не помогает,
хуже, чем её отсутствие.

Диагностический приём (осмотр, обследование) услугой-лечением НЕ считается:
он предшествует лечению, а не заменяет его. Если из списка подходит только
диагностика — считай, что подходящей услуги нет.

Верни JSON вида {"matches": [...]}, по одному элементу на картину, в том же
порядке. Поля:

"diagnosis" — диагноз картины, дословно как дан. Нужен, чтобы не сбиться
  порядком.
"service" — ТОЧНОЕ название услуги из списка, слово в слово. Либо null,
  если ни одна не лечит это состояние.
"why" — одно предложение: почему эта услуга лечит именно это. Если null —
  почему ничего не подошло.

Только JSON, без markdown-обёртки."""


def build_clinical_messages(personality: dict, clinic: dict) -> list[dict]:
    """Запрос на картины. Услуг и цен в нём нет — и не должно появиться."""
    # Берём личность целиком: возраст и быт лежат внутри identity сплошным
    # текстом («Ты — Анжелика Сергеевна Кравцова, 44 года»), отдельного поля
    # с возрастом в профилях нет. Разбирать его регуляркой ненадёжно, а модель
    # прочитает сама
    личность = "\n\n".join(
        f"{ключ}: {значение if not isinstance(значение, list) else chr(10).join(значение)}"
        for ключ, значение in personality.items()
    )
    return [
        {"role": "system", "content": CLINICAL_INSTRUCTIONS},
        {
            "role": "user",
            "content": (
                f"ОТРАСЛЬ: {clinic.get('industry', '')}\n\n"
                f"ЧЕЛОВЕК:\n{личность}"
            ),
        },
    ]


def build_match_messages(pictures: list[dict], clinic: dict) -> list[dict]:
    """Запрос на подбор услуги. Узкий вопрос по уже готовым картинам."""
    услуги = "\n".join(
        f"- {у.get('name', '')}." + (f" {у['description']}" if у.get("description") else "")
        for у in clinic.get("services", [])
    )
    картины = "\n".join(
        f"{номер}. {к['diagnosis']} — {к['treatment']}"
        for номер, к in enumerate(pictures, 1)
    )
    return [
        {"role": "system", "content": MATCH_INSTRUCTIONS},
        {"role": "user", "content": f"КАРТИНЫ:\n{картины}\n\nУСЛУГИ КЛИНИКИ:\n{услуги}"},
    ]


def validate_pictures(answer: dict) -> Optional[str]:
    """Проверяет форму ответа с картинами. Возвращает причину отказа либо None."""
    картины = answer.get("pictures")
    if not isinstance(картины, list) or not картины:
        return "нет списка картин"
    if not _PICTURES_MIN <= len(картины) <= _PICTURES_MAX:
        return f"картин {len(картины)}, ожидалось {_PICTURES_MIN}-{_PICTURES_MAX}"

    for номер, картина in enumerate(картины, 1):
        if not isinstance(картина, dict):
            return f"картина {номер} не объект"
        пусто = [поле for поле in _PICTURE_FIELDS if not картина.get(поле)]
        if пусто:
            return f"картина {номер}: нет полей {', '.join(пусто)}"
        # Гадание в диагнозе опаснее, чем в прозе: менеджер читает анамнез
        # как данность, а «слабой или средней степени» данностью не является
        слитно = " ".join(str(картина[поле]) for поле in _PICTURE_FIELDS).lower()
        гадание = next((h for h in _HEDGES if h in слитно), None)
        if гадание:
            return f"картина {номер} гадает: «{гадание}»"
        if " или " in str(картина["diagnosis"]).lower():
            return f"картина {номер}: диагноз через «или» — это не диагноз"
    return None


async def generate_pictures(personality: dict, clinic: dict) -> Optional[list[dict]]:
    """Правдоподобные картины по возрасту. None, если не получилось."""
    settings = get_settings()
    messages = build_clinical_messages(personality, clinic)

    for попытка in range(1, _SHAPE_ATTEMPTS + 1):
        ответ = await ask_json(
            messages,
            model=settings.clinical_model,
            purpose="клиническая картина",
            attempts=_PROVIDER_ATTEMPTS,
            # Низкая намеренно: здесь нужна не живость, а верность. Живость
            # отвечает за прозу и остаётся во втором вызове
            temperature=0.2,
        )
        if ответ is None:
            return None

        беда = validate_pictures(ответ)
        if беда is None:
            return ответ["pictures"]
        logger.warning("Картины, попытка %d: ответ не годится — %s", попытка, беда)

    logger.error("Картины: %d ответа подряд не прошли проверку формы", _SHAPE_ATTEMPTS)
    return None


async def match_services(pictures: list[dict], clinic: dict) -> list[Optional[dict]]:
    """Для каждой картины — услуга клиники, которая её лечит, либо None.

    Порядок ответа совпадает с порядком картин. Название услуги сверяется
    со списком: выдуманное название — та же беда, что выдуманный диагноз,
    только с другого конца.
    """
    услуги = {у.get("name", ""): у for у in clinic.get("services", [])}
    ответ = await ask_json(
        build_match_messages(pictures, clinic),
        model=get_settings().clinical_model,
        purpose="подбор услуги",
        attempts=_PROVIDER_ATTEMPTS,
        temperature=0.0,  # выбор из списка, творчество тут не нужно
    )
    if ответ is None:
        return [None] * len(pictures)

    строки = ответ.get("matches")
    if not isinstance(строки, list) or len(строки) != len(pictures):
        logger.warning(
            "Подбор услуги: строк %s при %d картинах — считаем, что не подошло ничего",
            len(строки) if isinstance(строки, list) else "нет",
            len(pictures),
        )
        return [None] * len(pictures)

    итог: list[Optional[dict]] = []
    for строка in строки:
        имя = (строка or {}).get("service")
        if имя and имя in услуги:
            итог.append(услуги[имя])
        else:
            if имя:
                logger.warning("Подбор услуги: «%s» нет в списке клиники", имя)
            итог.append(None)
    return итог


def choose(
    pictures: list[dict],
    services: list[Optional[dict]],
    used_diagnoses: Optional[list[str]] = None,
) -> Optional[tuple[dict, dict]]:
    """Выбирает картину, у которой есть лечащая услуга. Чистая функция.

    Картины приходят по убыванию вероятности, и порядок мы уважаем: берём
    первую подходящую. Разнообразие — мягкое предпочтение поверх этого:
    среди подходящих сначала ищем диагноз, которого у других пациентов
    клиники ещё не было.

    Жёстко требовать различия нельзя. «Не повторяйся» — это ровно то давление
    сочинять, из которого выросла миопия в 44 года: правдоподобие важнее
    разнообразия.
    """
    было = {д.lower() for д in (used_diagnoses or [])}
    подошли = [
        (картина, услуга)
        # strict: длины обязаны совпадать — match_services это гарантирует,
        # и тихое расхождение здесь означало бы услугу не от той картины
        for картина, услуга in zip(pictures, services, strict=True)
        if услуга is not None
    ]
    if not подошли:
        return None

    свежие = [пара for пара in подошли if пара[0]["diagnosis"].lower() not in было]
    return свежие[0] if свежие else подошли[0]


async def pick(
    personality: dict,
    clinic: dict,
    used_diagnoses: Optional[list[str]] = None,
) -> Optional[tuple[dict, dict]]:
    """Картина и услуга под неё. None, если клиника ничем из найденного не лечит."""
    картины = await generate_pictures(personality, clinic)
    if not картины:
        return None

    услуги = await match_services(картины, clinic)
    выбор = choose(картины, услуги, used_diagnoses)
    if выбор is None:
        logger.warning(
            "Ни одну из %d картин клиника не лечит: %s",
            len(картины),
            ", ".join(к["diagnosis"] for к in картины),
        )
        return None

    картина, услуга = выбор
    logger.info("Картина «%s» → услуга «%s»", картина["diagnosis"], услуга.get("name", ""))
    return картина, услуга
