MATCH_INSTRUCTIONS = """Тебе дают клинические картины и список услуг клиники.
Для каждой картины скажи, какая услуга ЛЕЧИТ это состояние.

Это подбор, а не продажа. Не надо ничего пристраивать: если ни одна услуга
это состояние не лечит, так и ответь. Услуга, которая состоянию не помогает,
хуже, чем её отсутствие.

Что считать лечением. Услуга лечит, если после неё человеку становится лучше:
операция, процедура, курс, подбор и изготовление того, чем он будет
пользоваться. Не лечит услуга, после которой становится известен только
диагноз: осмотр, обследование, диагностика. Если из списка подходит одна
такая — считай, что подходящей услуги нет.

Подбор — это лечение, даже если он начинается с проверки. Человек уходит
с решением своей задачи, а не со сведениями о ней.

Верни JSON вида {"matches": [...]}, по одному элементу на картину, в том же
порядке. Поля:

"diagnosis" — диагноз картины, дословно как дан. Нужен, чтобы не сбиться
  порядком.
"service" — ТОЧНОЕ название услуги из списка, слово в слово. Либо null,
  если ни одна не лечит это состояние.
"why" — одно предложение: почему эта услуга лечит именно это. Если null —
  почему ничего не подошло.

Только JSON, без markdown-обёртки."""


def build_clinical_messages(personality: dict, clinic: dict) -> list[dict]:
    """Запрос на картины. Услуг и цен в нём нет — и не должно появиться."""
    # Берём личность целиком: возраст и быт лежат внутри identity сплошным
    # текстом («Ты — Анжелика Сергеевна Кравцова, 44 года»), отдельного поля
    # с возрастом в профилях нет. Разбирать его регуляркой ненадёжно, а модель
    # прочитает сама
    личность = "\n\n".join(
        f"{ключ}: {значение if not isinstance(значение, list) else chr(10).join(значение)}"
        for ключ, значение in personality.items()
    )
    return [
        {"role": "system", "content": CLINICAL_INSTRUCTIONS},
        {
            "role": "user",
            "content": (
                f"ОТРАСЛЬ: {clinic.get('industry', '')}\n\n"
                f"ЧЕЛОВЕК:\n{личность}"
            ),
        },
    ]


def build_match_messages(pictures: list[dict], clinic: dict) -> list[dict]:
    """Запрос на подбор услуги. Узкий вопрос по уже готовым картинам."""
    # Название и описание — РАЗНЫМИ строками. Когда они стояли в одной через
    # точку, модель на просьбу вернуть название «слово в слово» отдавала всю
    # строку вместе с описанием, и поиск по списку её не находил. В замере
    # 06.08 так провалились шесть сборок из восьми
    услуги = "\n".join(
        f"- {у.get('name', '')}"
        + (f"\n  (что входит: {у['description']})" if у.get("description") else "")
        for у in clinic.get("services", [])
    )
    картины = "\n".join(
        f"{номер}. {к['diagnosis']} — {к['treatment']}"
        for номер, к in enumerate(pictures, 1)
    )
    return [
        {"role": "system", "content": MATCH_INSTRUCTIONS},
        {"role": "user", "content": f"КАРТИНЫ:\n{картины}\n\nУСЛУГИ КЛИНИКИ:\n{услуги}"},
    ]


def validate_pictures(answer: dict) -> Optional[str]:
    """Проверяет форму ответа с картинами. Возвращает причину отказа либо None."""
    картины = answer.get("pictures")
    if not isinstance(картины, list) or not картины:
        return "нет списка картин"
    if not _PICTURES_MIN <= len(картины) <= _PICTURES_MAX:
        return f"картин {len(картины)}, ожидалось {_PICTURES_MIN}-{_PICTURES_MAX}"

    # Возраст числом — то, чем проверяется окно начала. Без него арифметика
    # невозможна, и картина «возрастная катаракта в 34» снова прошла бы
    try:
        возраст = int(float(str(answer.get("patientAge"))))
    except (TypeError, ValueError):
        return f"patientAge не число: {answer.get('patientAge')!r}"
    if not 0 < возраст < 120:
        return f"patientAge вне разумного: {возраст}"

    for номер, картина in enumerate(картины, 1):
        if not isinstance(картина, dict):
            return f"картина {номер} не объект"
        # onsetFrom может быть нулём — «not картина.get» его бы съел
        пусто = [
            поле
            for поле in _PICTURE_FIELDS
            if картина.get(поле) is None or картина.get(поле) == ""
        ]
        if пусто:
            return f"картина {номер}: нет полей {', '.join(пусто)}"

    # Негодные картины выбрасываем ПОШТУЧНО, а не бракуем весь набор.
    #
    # Раньше одно «возможно» в пятой картине отправляло на пересборку все
    # пять, и 07.08 так потерялся пациент: обе попытки спотыкались об одну
    # и ту же оговорку, а четыре здоровых картины уезжали вместе с ней.
    # Чем больше полей у картины, тем выше шанс оговорки хоть в одном —
    # значит цена браковки набора растёт, а польза нет.
    годные, выброшены = [], []
    for картина in картины:
        причина = годится_по_возрасту(картина, возраст) or _чем_плоха(картина)
        if причина:
            выброшены.append(f"{картина['diagnosis']} ({причина})")
        else:
            годные.append(картина)

    if выброшены:
        logger.info("Картины: выброшено %d — %s", len(выброшены), "; ".join(выброшены))
    if len(годные) < _ПОСЛЕ_ОТСЕВА:
        return f"после отсева осталось картин: {len(годные)}"
    answer["pictures"] = годные
    return None


def _чем_плоха(картина: dict) -> Optional[str]:
    """Причина выбросить картину, либо None. Чистая функция."""
    # Гадание в медицинских сведениях опаснее, чем в прозе: менеджер читает
    # анамнез как данность, а «слабой или средней степени» данностью не является
    слитно = " ".join(str(картина[поле]) for поле in _PICTURE_FIELDS).lower()
    гадание = next((h for h in _HEDGES if h in слитно), None)
    if гадание:
        return f"гадает: {гадание}"

    # «Или» проверяем в диагнозе и в находках осмотра — там оно значит,
    # что модель не выбрала. 07.08 прошло «помутнение в кортикальных или
    # ядерных слоях»: слов-уклонений нет, а определённости тоже.
    #
    # В остальных полях «или» законно: «замечает в очках или линзах» —
    # это условие, а не колебание
    for поле in ("diagnosis", "objective"):
        if " или " in str(картина.get(поле, "")).lower():
            return f"«или» в поле {поле} — не выбрано одно"

    if str(картина.get("common", "")).strip().lower() not in (_ОБЫЧНОЕ, _РЕДКОЕ):
        return f"common не «{_ОБЫЧНОЕ}» и не «{_РЕДКОЕ}»"

    # Модель, отказавшаяся заполнять поле, сообщает, что картина не годится.
    # 07.08 в «замечает при» стояло «Не применимо для данного возраста» —
    # прямее сказать нельзя, а мы это проглотили
    for поле in ("noticedWhen", "complaints", "objective"):
        if "не примен" in str(картина.get(поле, "")).lower():
            return f"модель отказалась заполнять {поле}"
    return None


def годится_по_возрасту(картина: dict, возраст: int) -> Optional[str]:
    """Проверка возраста арифметикой, а не на слово. Причина отказа либо None."""
    сырое = картина.get("onsetFrom")
    try:
        начало = int(float(str(сырое)))
    except (TypeError, ValueError):
        return f"onsetFrom не число: {сырое!r}"
    if начало < 0 or начало > 120:
        return f"onsetFrom вне разумного: {начало}"
    if возраст < начало:
        return f"начинается с {начало}, а человеку {возраст}"
    return None


async def generate_pictures(personality: dict, clinic: dict) -> Optional[list[dict]]:
    """Правдоподобные картины по возрасту. None, если не получилось."""
    settings = get_settings()
    messages = build_clinical_messages(personality, clinic)

    for попытка in range(1, _SHAPE_ATTEMPTS + 1):
        ответ = await ask_json(
            messages,
            model=settings.clinical_model,
            purpose="клиническая картина",
            attempts=_PROVIDER_ATTEMPTS,
            # Низкая намеренно: здесь нужна не живость, а верность. Живость
            # отвечает за прозу и остаётся во втором вызове
            temperature=0.2,
            # Три проверки в инструкции — про возраст, следствие и
            # определённость — это работа, а не чтение. На medium sonnet
            # тратил на неё 90 токенов с вызова: столько думают, чтобы
            # согласиться, а не чтобы проверить. Невозможные по возрасту
            # диагнозы держались именно поэтому
            # Замер 07.08: high поднимает размышление всего с 90 до 195 токенов
            # на вызов. Sonnet думает мало независимо от бюджета — доля
            # от потолка ему граница, а не цель, и платить за разницу не за что.
            # Подорожание сборки дали три новых поля, а не усилие
            reasoning="medium",
            # Потолок оставлен прежним, 8000. У Anthropic effort — доля
            # от max_tokens, и поднимать потолок значит поднимать бюджет
            # на мысли, то есть менять две вещи разом и терять понимание,
            # что сработало. Sonnet на medium брал 90 токенов при бюджете
            # в тысячи — бюджет ему граница, а не цель.
            #
            # Признак, что потолка не хватило: «ответ не разобрался» на
            # клиническом вызове. Тогда поднимать, но осознанно.
        )
        if ответ is None:
            return None

        беда = validate_pictures(ответ)
        if беда is None:
            return ответ["pictures"]
        logger.warning("Картины, попытка %d: ответ не годится — %s", попытка, беда)

    logger.error("Картины: %d ответа подряд не прошли проверку формы", _SHAPE_ATTEMPTS)
    return None


async def match_services(pictures: list[dict], clinic: dict) -> list[Optional[dict]]:
    """Для каждой картины — услуга клиники, которая её лечит, либо None.

    Порядок ответа совпадает с порядком картин. Название услуги сверяется
    со списком: выдуманное название — та же беда, что выдуманный диагноз,
    только с другого конца.
    """
    услуги = {у.get("name", ""): у for у in clinic.get("services", [])}
    ответ = await ask_json(
        build_match_messages(pictures, clinic),
        model=get_settings().clinical_model,
        purpose="подбор услуги",
        attempts=_PROVIDER_ATTEMPTS,
        temperature=0.0,  # выбор из списка, творчество тут не нужно
        # Подбор выглядит простым, но именно он однажды выдал «катаракта →
        # подбор очков» у сорокачетырёхлетней. Это ошибка суждения, а не
        # выбора из списка — и всё же high её не убрал, так что держим medium
        reasoning="medium",
    )
    if ответ is None:
        return [None] * len(pictures)

    строки = ответ.get("matches")
    if not isinstance(строки, list) or len(строки) != len(pictures):
        logger.warning(
            "Подбор услуги: строк %s при %d картинах — считаем, что не подошло ничего",
            len(строки) if isinstance(строки, list) else "нет",
            len(pictures),
        )
        return [None] * len(pictures)

    итог: list[Optional[dict]] = []
    for строка in строки:
        имя = (строка or {}).get("service")
        услуга = найти_услугу(имя, услуги)
        if имя and услуга is None:
            logger.warning("Подбор услуги: «%s» нет в списке клиники", имя)
        итог.append(услуга)
    return итог


def найти_услугу(имя: Optional[str], услуги: dict[str, dict]) -> Optional[dict]:
    """Ищет услугу по названию, прощая модели лишнее вокруг него.

    Точное совпадение — основной путь. Но модель то припишет к названию
    описание, то поставит точку в конце, и наказывать за это нечестно:
    услугу она выбрала верно, спотыкается наш разбор. Чистая функция —
    поэтому проверяема тестами без обращения к модели.
    """
    if not имя:
        return None
    обрезанное = имя.strip().rstrip(".").strip()
    if обрезанное in услуги:
        return услуги[обрезанное]

    свёрнутое = обрезанное.casefold()
    for название, услуга in услуги.items():
        свой = название.strip().casefold()
        # Название целиком в начале ответа: «Замена хрусталика. Операция
        # 20 минут…» — это выбранная услуга плюс её же описание
        if свёрнутое == свой or свёрнутое.startswith(свой):
            return услуга

    # Последняя попытка — на опечатку. В замере 06.08 модель написала
    # «Замена хрусталика с импластрацией ИОЛ», и пациент из-за одной буквы
    # остался без случая. Порог высокий: похожие названия услуг в одном
    # прайсе — обычное дело («лечение глаукомы» и «лечение катаракты»),
    # и спутать их хуже, чем не найти
    похожая = difflib.get_close_matches(свёрнутое, [н.casefold() for н in услуги], n=1, cutoff=0.9)
    if похожая:
        for название, услуга in услуги.items():
            if название.casefold() == похожая[0]:
                logger.info("Подбор услуги: «%s» опознано как «%s»", имя, название)
                return услуга
    return None


def choose(
    pictures: list[dict],
    services: list[Optional[dict]],
    used_diagnoses: Optional[list[str]] = None,
) -> list[tuple[dict, dict]]:
    """Пары «картина + лечащая услуга» по порядку предпочтения. Чистая функция.

    Отдаёт ВЕСЬ список, а не одну пару: критик, забраковав картину, берёт
    следующую отсюда — она уже оплачена, и новый клинический вызов не нужен.

    Картины приходят по убыванию вероятности, и порядок мы уважаем.
    Разнообразие — мягкое предпочтение поверх него: диагнозы, которых
    у других пациентов клиники ещё не было, поднимаются вперёд.

    Жёстко требовать различия нельзя. «Не повторяйся» — это ровно то давление
    сочинять, из которого выросла миопия в 44 года: правдоподобие важнее
    разнообразия.
    """
    было = {д.lower() for д in (used_diagnoses or [])}
    подошли = [
        (картина, услуга)
        # strict: длины обязаны совпадать — match_services это гарантирует,
        # и тихое расхождение здесь означало бы услугу не от той картины
        for картина, услуга in zip(pictures, services, strict=True)
        if услуга is not None
    ]
    # Редкое уходит в хвост при любом раскладе. Модель честно помечает
    # исключения, но 07.08 глаукома с пометкой «пик после 60» досталась
    # сорокавосьмилетнему: выбор смотрел только на наличие услуги.
    # Правдоподобие важнее и разнообразия, и порядка вероятности
    def обычное(пара: tuple[dict, dict]) -> bool:
        return str(пара[0].get("common", "")).strip().lower() == _ОБЫЧНОЕ

    def свежее(пара: tuple[dict, dict]) -> bool:
        return пара[0]["diagnosis"].lower() not in было

    # Порядок групп: обычное и незанятое, обычное занятое, редкое незанятое,
    # редкое занятое. Внутри группы сохраняется исходная вероятность
    группы = [
        [п for п in подошли if обычное(п) and свежее(п)],
        [п for п in подошли if обычное(п) and not свежее(п)],
        [п for п in подошли if not обычное(п) and свежее(п)],
        [п for п in подошли if not обычное(п) and not свежее(п)],
    ]
    return [пара for группа in группы for пара in группа]


async def pick(
    personality: dict,
    clinic: dict,
    used_diagnoses: Optional[list[str]] = None,
) -> list[tuple[dict, dict]]:
    """Пары «картина + услуга» по порядку предпочтения. Пустой список — нечем лечить.

    Отдаём все пригодные, а не первую: критик, забраковав картину, возьмёт
    следующую отсюда, и новый клинический вызов не понадобится.
    """
    картины = await generate_pictures(personality, clinic)
    if not картины:
        return []

    услуги = await match_services(картины, clinic)
    пары = choose(картины, услуги, used_diagnoses)
    if not пары:
        logger.warning(
            "Ни одну из %d картин клиника не лечит: %s",
            len(картины),
            ", ".join(к["diagnosis"] for к in картины),
        )
        return []

    logger.info(
        "Пригодных картин %d, первая — «%s» → «%s»",
        len(пары),
        пары[0][0]["diagnosis"],
        пары[0][1].get("name", ""),
    )
    return пары
