"""Слова отрасли для текстов, которые backend подмешивает роли и отдаёт оценщику.

Строка доверия, шкала и чек-лист оценщика, инструкции исхода написаны
на медицину: «менеджер по продажам медицинских услуг», «пациент», «оплатить
услугу». Эти тексты — источник правды: чек-лист утверждён врачом 04.09,
порог доверия считан на них, и у клиник они не меняются ни на байт —
для медицины перевод здесь тождественный. Другая отрасль получает те же
тексты с заменой отраслевых слов по таблице; таблица маленькая, потому что
почти всё в этих текстах про технику разговора, а не про медицину.

Почему перевод, а не отдельные тексты на отрасль: держать два чек-листа
значило бы держать две рубрики, и оценки разных отраслей перестали бы быть
сопоставимы (см. checklist.py). Рубрика одна, слова — свои.

Разборщик отрасли повторяет `industryRules` из frontend/scripts/patient-prompt.ts:
отрасль организации — свободный текст из формы руководителя, и всё, где нет
недвижимости, — клиника.
"""

import re
from typing import Callable, Union

МЕДИЦИНА = "медицина"
НЕДВИЖИМОСТЬ = "недвижимость"

_НЕДВИЖИМОСТЬ_КОРНИ = re.compile(r"недвиж|застройщ|офис продаж", re.IGNORECASE)


def industry_key(industry: Union[str, None]) -> str:
    """Ключ отрасли по названию организации: «Недвижимость: офис продаж» → недвижимость."""
    return НЕДВИЖИМОСТЬ if _НЕДВИЖИМОСТЬ_КОРНИ.search(industry or "") else МЕДИЦИНА


def _клиент(match: re.Match) -> str:
    # «пациент» и «клиент» склоняются одинаково, поэтому меняется только
    # основа, а окончание остаётся: пациентка → клиентка, пациентов → клиентов
    first = match.group(1)
    return {"П": "К", "п": "к"}[first] + "лиент"


# Порядок важен: длинные обороты раньше отдельных слов, иначе «оплатить
# услугу» распалось бы на два слова и перевод потерял бы смысл
_НЕДВИЖИМОСТЬ_ЗАМЕНЫ: list[tuple[re.Pattern, Union[str, Callable[[re.Match], str]]]] = [
    (re.compile(r"менеджера по продажам медицинских услуг"), "менеджера отдела продаж застройщика"),
    (re.compile(r"оплатить услугу"), "внести бронь"),
    (re.compile(r"«записываю вас на операцию»"), "«ставлю бронь»"),
    (re.compile(r"«вы согласны на операцию\?»"), "«вам нравится эта квартира?»"),
    (re.compile(r"как вести себя на приёме"), "как проходит встреча"),
    (re.compile(r"а не о симптоме"), "а не о квартире"),
    (re.compile(r"а не только симптом"), "а не только запрос"),
    (re.compile(r"вопрос о жалобе"), "вопрос о запросе"),
    (re.compile(r"«дешевле в соседней клинике»"), "«дешевле у соседнего застройщика»"),
    (re.compile(r"про наркоз и восстановление"), "про сроки сдачи и отделку"),
    (re.compile(r"ПАЦИЕНТ"), "КЛИЕНТ"),
    (re.compile(r"(?<![А-Яа-яЁё])([Пп])ациент"), _клиент),
]

_ЗАМЕНЫ = {НЕДВИЖИМОСТЬ: _НЕДВИЖИМОСТЬ_ЗАМЕНЫ}

# Чем не должен пахнуть перевод — то, что тест ищет в переведённых текстах
МЕДИЦИНСКИЕ_КОРНИ = ("пациент", "медицин", "услуг", "операци", "клиник", "приём", "симптом", "наркоз", "жалоб")


def translate(text: str, industry: Union[str, None]) -> str:
    """Тот же текст словами отрасли. Для медицины — без изменений."""
    for pattern, replacement in _ЗАМЕНЫ.get(industry_key(industry), []):
        text = pattern.sub(replacement, text)
    return text
