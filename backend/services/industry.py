"""Слова отрасли для текстов, которые backend подмешивает роли и отдаёт оценщику.

Строка доверия, шкала и чек-лист оценщика, инструкции исхода написаны
на медицину: «менеджер по продажам медицинских услуг», «пациент», «оплатить
услугу». Эти тексты — источник правды: чек-лист утверждён врачом 04.09,
порог доверия считан на них, и у клиник они не меняются ни на байт —
для медицины перевод здесь тождественный. Другая отрасль получает те же
тексты с заменой отраслевых слов по таблице; таблица маленькая, потому что
почти всё в этих текстах про технику разговора, а не про медицину.

Почему перевод, а не отдельные тексты на отрасль: держать два чек-листа
значило бы держать две рубрики, и оценки разных отраслей перестали бы быть
сопоставимы (см. checklist.py). Рубрика одна, слова — свои.

Отрасль — ключ организации (`Organization.industryKey`: «медицина»,
«недвижимость»), а не угадывание по тексту. Параметр `industry` у функций
этого модуля, llm.py, scoring.py, checklist.py — именно ключ. Список
отраслей тот же, что `ОТРАСЛИ` в frontend/scripts/industry-key.ts; разойдутся —
упадёт тест (tests/test_industry.py). Незнакомый ключ — медицина, как вела
себя организация до отраслей.
"""

import json
import re
from dataclasses import dataclass
from typing import Callable, Union

МЕДИЦИНА = "медицина"
НЕДВИЖИМОСТЬ = "недвижимость"


# Таблица замен: шаблон и на что менять; порядок строк — порядок замен
Замены = list[tuple[re.Pattern, Union[str, Callable[[re.Match], str]]]]


def _клиент(match: re.Match) -> str:
    # «пациент» и «клиент» склоняются одинаково, поэтому меняется только
    # основа, а окончание остаётся: пациентка → клиентка, пациентов → клиентов
    first = match.group(1)
    return {"П": "К", "п": "к"}[first] + "лиент"


# Порядок важен: длинные обороты раньше отдельных слов, иначе «оплатить
# услугу» распалось бы на два слова и перевод потерял бы смысл
_НЕДВИЖИМОСТЬ_ЗАМЕНЫ: Замены = [
    (re.compile(r"менеджера по продажам медицинских услуг"), "менеджера отдела продаж застройщика"),
    (re.compile(r"оплатить услугу"), "внести бронь"),
    # Сделка в офисе продаж закрывается бронью, и слово обязано быть одно
    # во всех текстах: строка доверия разрешала согласиться на «оплатить»,
    # а запрещала «внести бронь» — роль и оценщик читали разное
    (re.compile(r"«готовы(\s+)оплатить\?»"), r"«готовы\1бронировать?»"),
    (re.compile(r"([Пп]редлож\w*)(\s+)оплатить"), r"\1\2внести бронь"),
    (re.compile(r"([Пп]редложени\w)(\s+)об(\s+)оплате"), r"\1\2внести бронь"),
    (re.compile(r"предлагать оплату"), "предлагать бронь"),
    (re.compile(r"«записываю вас на операцию»"), "«ставлю бронь»"),
    (re.compile(r"«вы согласны на операцию\?»"), "«вам нравится эта квартира?»"),
    (re.compile(r"как вести себя на приёме"), "как проходит встреча"),
    (re.compile(r"самочувствие, погода"), "погода, легко ли нашли офис"),
    (re.compile(r"что перестал делать, чего избегает"), "что не так там, где живёт сейчас"),
    (re.compile(r"а не о симптоме"), "а не о квартире"),
    (re.compile(r"а не только симптом"), "а не только запрос"),
    # «Вопрос о запросе» — тавтология, поэтому словами того, что человек ищет
    (re.compile(r"вопрос о жалобе"), "вопрос о том, что клиент ищет"),
    (re.compile(r"«дешевле в соседней клинике»"), "«дешевле у соседнего застройщика»"),
    (re.compile(r"про наркоз и восстановление"), "про сроки сдачи и отделку"),
    (re.compile(r"ПАЦИЕНТ"), "КЛИЕНТ"),
    (re.compile(r"(?<![А-Яа-яЁё])([Пп])ациент"), _клиент),
]

@dataclass(frozen=True)
class МенеджерМодель:
    """Как менеджер-модель QA и симулятора называет себя и предмет продажи.

    Тексты вокруг — общие (qa/conversation.py, scripts/sim_conversation.py);
    здесь только слова, которые у отрасли свои.
    """

    # «Ты — менеджер {кто} «Название», отрасль»
    кто: str
    # «{прайс} и цены, которые ты знаешь наизусть»
    прайс: str
    # Подпись того, что менеджер видит до разговора: «Анамнез: …»
    заявка: str
    # «Доведи его до прямого предложения {предложение}»
    предложение: str
    # Роль менеджера в симуляторе, когда клиники в базе нет
    представление: str


@dataclass(frozen=True)
class Отрасль:
    """Всё, что у отрасли своё на backend."""

    # Таблица замен для строки доверия, оценщика и разбора; у медицины
    # пустая — её тексты эталонные
    замены: Замены
    менеджер: МенеджерМодель


ОТРАСЛИ: dict[str, Отрасль] = {
    МЕДИЦИНА: Отрасль(
        замены=[],
        менеджер=МенеджерМодель(
            кто="клиники",
            прайс="Услуги",
            заявка="Анамнез",
            предложение="оплатить лечение",
            представление="Ты — менеджер по продажам в частной клинике, разговариваешь с пациентом.",
        ),
    ),
    НЕДВИЖИМОСТЬ: Отрасль(
        замены=_НЕДВИЖИМОСТЬ_ЗАМЕНЫ,
        менеджер=МенеджерМодель(
            кто="отдела продаж",
            прайс="Квартиры, условия",
            заявка="Заявка",
            предложение="внести бронь",
            представление=(
                "Ты — менеджер отдела продаж застройщика, разговариваешь с покупателем квартиры."
            ),
        ),
    ),
}


def ключ_отрасли(industry: Union[str, None]) -> str:
    """Ключ из базы как есть; пустой и незнакомый — медицина."""
    return industry if industry in ОТРАСЛИ else МЕДИЦИНА


def отрасль(industry: Union[str, None]) -> Отрасль:
    """Настройки отрасли по ключу организации."""
    return ОТРАСЛИ[ключ_отрасли(industry)]

# Чем не должен пахнуть перевод — то, что тест ищет в переведённых текстах
МЕДИЦИНСКИЕ_КОРНИ = ("пациент", "медицин", "услуг", "операци", "клиник", "приём", "симптом", "наркоз", "жалоб")


def медицинская_отрасль(industry: Union[str, None]) -> bool:
    """Клиника ли это — то есть работает ли для неё клинический конвейер."""
    return ключ_отрасли(industry) == МЕДИЦИНА


def есть_диагностика(industry: Union[str, None]) -> bool:
    """Бывает ли у отрасли результат диагностики.

    Документ — медицинский осмотр с находками врача. Офису продаж его
    показывать некуда: кнопки на экране звонка нет, а генерация стоит
    денег за каждый полный разговор.
    """
    return медицинская_отрасль(industry)


def pick_variant(base: str, variants: object, industry: Union[str, None]) -> str:
    """Текст по отрасли из JSON-колонки `promptByIndustry` типа тренировки.

    `variants` приходит из asyncpg как строка JSON или как dict (смотря
    как настроен кодек), поэтому принимаем оба. Нет варианта для отрасли —
    базовый текст, пропущенный через перевод: у нейтральных типов он
    и так без медицинских слов, у медицины перевод тождественный.
    """
    if isinstance(variants, (str, bytes)):
        try:
            variants = json.loads(variants or "{}")
        except ValueError:
            variants = {}
    if not isinstance(variants, dict):
        variants = {}
    свой = variants.get(ключ_отрасли(industry))
    if isinstance(свой, str) and свой.strip():
        return свой
    return translate(base or "", industry)


def translate(text: str, industry: Union[str, None]) -> str:
    """Тот же текст словами отрасли. Для медицины — без изменений."""
    for pattern, replacement in отрасль(industry).замены:
        text = pattern.sub(replacement, text)
    return text
