"""Результат диагностики: документ, который менеджер показывает по кнопке.

Менеджер отправляет пациента на диагностику почти в каждом разговоре,
а результата не существовало — и он придумывал его сам, естественно такой,
с которым удобнее закрывать. Теперь документ генерируется на старте полного
разговора (пока менеджер проверяет микрофон и читает анамнез) и ждёт кнопки.

ОПОРА — АНАМНЕЗ, А НЕ ДИАГНОСТИКА С НУЛЯ. Анамнез вычитан человеком
и уже содержит диагноз, стадию и измерения. Модель не ставит диагноз —
она продолжает готовую историю болезни: та же болезнь, показатели по
выбранному исходу. Так «возрастная катаракта в 34» здесь невозможна
по построению: болезнь пришла из проверенного текста.

ИСХОД ВЫБИРАЕТ КОД, НЕ МОДЕЛЬ. Четыре градации от «без особых изменений»
до «почти полная потеря функции» (пример Димы для офтальмологии, обобщён
на отрасли), взвешенная случайность на каждую сессию — реиграбельность.
Модель, выбирающая исход сама, тяготела бы к драматичному: драматичное
интереснее писать.

Свежий результат на каждую сессию — значит, вычитки заранее нет. Вместо
неё три предохранителя: опора на анамнез, обязательная норма при каждом
показателе (число без нормы непроверяемо, выдуманное — ловимо) и валидатор
по правилам генератора случаев (без гаданий, без выводов о продаже).
"""

import logging
import random
from typing import Optional

from core.config import get_settings
from services.llm_json import ask_json

logger = logging.getLogger(__name__)

_PROVIDER_ATTEMPTS = 2
_SHAPE_ATTEMPTS = 2

# Четыре исхода диагностики. Веса — на выбор кодом: «полная потеря» задумана
# крайне редкой, «без изменений» — нечастой (разговор без срочности тоже
# тренировка, но основная масса — ухудшение, ради которого фича и делалась).
# Правится здесь, без перегенераций и миграций.
ИСХОДЫ: tuple[tuple[str, int, str], ...] = (
    (
        "без изменений",
        20,
        "Без особых изменений: показатели соответствуют тому, что уже "
        "известно из анамнеза, с поправкой на прошедшее время. Ничего "
        "нового диагностика не нашла.",
    ),
    (
        "умеренное ухудшение",
        40,
        "Несильное, но существенное ухудшение: функция снизилась примерно "
        "на 20-30% относительно того, что следует из анамнеза; часть "
        "показателей пограничная — на самой границе нормы.",
    ),
    (
        "сильное ухудшение",
        37,
        "Сильные изменения: функция снизилась примерно на 40-60% "
        "относительно того, что следует из анамнеза; ухудшение человек "
        "уже ощущает в быту.",
    ),
    (
        "крайний исход",
        3,
        "Крайний исход: почти полная потеря функции больного органа "
        "(в терминах отрасли). Такое бывает крайне редко — пиши сдержанно "
        "и клинически, без драматизации.",
    ),
)

# Гадания и выводы о продаже — те же правила, что у генератора случаев
# (case_generator._HEDGES): менеджер читает документ как данность
_HEDGES = (
    "предположительн", "возможно", "вероятно", "скорее всего", "по-видимому",
    "неизвестн", "не установлен", "уточнить у",
)
_SALES_CONCLUSIONS = (
    "требуется ", "показана ", "показано ", "рекомендована ", "рекомендовано ",
    "рекомендуется ", "необходима ", "необходимо ",
)

_MIN_LEN = 120
_MAX_LEN = 1600

INSTRUCTIONS = """Ты — врач диагностического кабинета. Пациент только что
прошёл обследование; ниже его анамнез из карты. Напиши РЕЗУЛЬТАТ сегодняшней
диагностики.

ГЛАВНОЕ ПРАВИЛО: ты ПРОДОЛЖАЕШЬ эту историю болезни, а не начинаешь новую.
Болезнь та же, что в анамнезе, — диагноз указан его последней строкой.
Не добавляй новых заболеваний и не переименовывай имеющееся. Сегодняшние
показатели должны сходиться с анамнезом: то, что было измерено раньше,
не может волшебно улучшиться, а динамика — соответствовать заданному исходу.

ИСХОД ЗАДАН НИЖЕ ОТДЕЛЬНЫМ БЛОКОМ. Не выбирай его сам — исполни заданный.

ФОРМА ДОКУМЕНТА, ровно четыре части, каждая с новой строки:

Имя Отчество пациента
Объект исследования: что обследовали (оба глаза по отдельности, зуб с
  номером, конкретный орган — как принято в отрасли).
Способ исследования: какими методами (названия исследований, как они
  пишутся в заключениях этой отрасли).
Показатели исследования: 3-6 строк, КАЖДАЯ строка — параметр, измеренное
  значение И НОРМА рядом (в скобках или через тире). Где есть прежнее
  значение в анамнезе — покажи динамику «было → стало». Если норма зависит
  от условия (возраст, состояние) — назови условие.

ЧЕГО В ДОКУМЕНТЕ БЫТЬ НЕ ДОЛЖНО:
- названий услуг и рекомендаций к лечению («требуется», «показана»,
  «рекомендуется» — это вывод о продаже, а не находка). Документ даёт
  менеджеру факты, предлагать — его работа;
- гаданий: «предположительно», «возможно», «вероятно» недопустимы,
  это сведения, а не рассуждение;
- жалоб пациента и его слов — только то, что видит и меряет аппаратура
  и врач.

Пиши на русском, клиническим языком отрасли, компактно: менеджер читает
документ между репликами разговора, у него полминуты.

Верни JSON вида {"document": "текст документа"}. Только JSON."""


def выбрать_исход(rng: Optional[random.Random] = None) -> tuple[str, str]:
    """(ключ, описание для модели) — взвешенный случайный выбор кодом.

    rng параметром — ради тестов: взвешенный выбор без подмены генератора
    не проверить.
    """
    r = rng or random
    ключи_и_описания = [(к, о) for к, _, о in ИСХОДЫ]
    веса = [в for _, в, _ in ИСХОДЫ]
    return r.choices(ключи_и_описания, weights=веса, k=1)[0]


def чем_плох(document: str, имя: str) -> Optional[str]:
    """Проверка документа. Возвращает причину отказа либо None. Чистая функция."""
    text = (document or "").strip()
    if len(text) < _MIN_LEN:
        return f"документ подозрительно короткий: {len(text)} символов"
    if len(text) > _MAX_LEN:
        return f"документ раздут: {len(text)} символов — менеджеру не прочесть в бою"

    lowered = text.lower()
    гадание = next((h for h in _HEDGES if h in lowered), None)
    if гадание:
        return f"документ гадает: «{гадание}»"
    вывод = next((s for s in _SALES_CONCLUSIONS if s in lowered), None)
    if вывод:
        return f"вывод о продаже вместо находки: «{вывод.strip()}»"

    # Имя в шапке — первая строка формата. Сверяем по первому слову имени:
    # модель может склонить отчество, а имя в именительном остаётся
    первое_слово = имя.split()[0].lower() if имя.strip() else ""
    if первое_слово and первое_слово not in lowered:
        return "в шапке нет имени пациента"

    return None


async def generate_result(
    имя: str,
    anamnesis: str,
    industry: str,
    исход_описание: str,
) -> Optional[str]:
    """Документ диагностики поверх готового анамнеза. None — не получилось.

    Температура низкая: здесь нужна верность анамнезу, а не живость —
    живым должен быть разговор, а не заключение врача.
    """
    settings = get_settings()
    messages = [
        {"role": "system", "content": INSTRUCTIONS},
        {
            "role": "user",
            "content": (
                f"ОТРАСЛЬ: {industry or 'медицина'}\n\n"
                f"ПАЦИЕНТ: {имя}\n\n"
                f"АНАМНЕЗ ИЗ КАРТЫ:\n{anamnesis}\n\n"
                f"ИСХОД СЕГОДНЯШНЕЙ ДИАГНОСТИКИ (исполни именно его):\n"
                f"{исход_описание}"
            ),
        },
    ]

    for attempt in range(1, _SHAPE_ATTEMPTS + 1):
        ответ = await ask_json(
            messages,
            model=settings.clinical_model,
            purpose="результат диагностики",
            attempts=_PROVIDER_ATTEMPTS,
            temperature=0.3,
            max_tokens=8000,
        )
        if ответ is None:
            return None

        document = str(ответ.get("document") or "").strip()
        беда = чем_плох(document, имя)
        if беда is None:
            return document
        logger.warning(
            "Результат диагностики, попытка %d: не годится — %s", attempt, беда
        )

    logger.error(
        "Результат диагностики: %d ответа подряд не прошли проверку",
        _SHAPE_ATTEMPTS,
    )
    return None
