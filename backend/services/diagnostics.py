"""Результат диагностики: документ, который менеджер показывает по кнопке.

Менеджер отправляет пациента на диагностику почти в каждом разговоре,
а результата не существовало — и он придумывал его сам, естественно такой,
с которым удобнее закрывать.

ФОРМА — НЕ НАША ВЫДУМКА. Это бланк, который выдают в клиниках и который
менеджеры умеют читать: «Первичный осмотр», дальше разделы, где заголовок
каждого — НАЗВАНИЕ ИССЛЕДОВАНИЯ, а под ним значения. Эталон офтальмологии
дал эксперт (острота вдаль, острота вблизи, рефрактометрия, пневмотонометрия,
ведущий глаз), стоматологический аналог — раздел «Объективно» карты 043/у.
Норм рядом со значениями НЕТ: в настоящем документе их не пишут, менеджер
их знает. Одобрено экспертом по обеим отраслям 31.08.

ЭТА ЖЕ ФОРМА — У ПРЕСЕТОВ. Основной путь теперь не генерация, а готовый
вычитанный врачом документ из `PatientCase.diagnosticsPreset`; сюда попадают
только случаи, которых пресет не покрывает (клиника перегенерировала их
под свой прайс). Формы две быть не может: менеджер увидит один жанр
в обеих отраслях, поэтому правится она здесь и в пресетах одновременно.

ОПОРА — АНАМНЕЗ, А НЕ ДИАГНОСТИКА С НУЛЯ. Анамнез вычитан человеком
и уже содержит диагноз, стадию, измерения и давность («год назад на осмотре
найдены…»). Модель не ставит диагноз и не выдумывает срок — она продолжает
готовую историю: та же болезнь, показатели по выбранному исходу, интервал
из текста. Так «возрастная катаракта в 34» здесь невозможна по построению.

ИСХОД ВЫБИРАЕТ КОД, НЕ МОДЕЛЬ. Четыре градации, взвешенная случайность
на каждую сессию — реиграбельность. Модель, выбирающая исход сама, тяготела
бы к драматичному: драматичное интереснее писать.

Свежий результат на каждую сессию — значит, вычитки заранее нет. Предохранители:
опора на анамнез, проверка формы и валидатор по правилам генератора случаев
(без гаданий, без выводов о продаже). Прежний предохранитель «норма при каждом
показателе» отменён вместе с нормами — вместо него держит форму `чем_плох`.
"""

import logging
import random
import re
from typing import Optional

from core.config import get_settings
from services.llm_json import ask_json

logger = logging.getLogger(__name__)

_PROVIDER_ATTEMPTS = 2
_SHAPE_ATTEMPTS = 2

# Четыре исхода диагностики. Веса — на выбор кодом: «полная потеря» задумана
# крайне редкой, «без изменений» — нечастой (разговор без срочности тоже
# тренировка, но основная масса — ухудшение, ради которого фича и делалась).
# Правится здесь, без перегенераций и миграций.
#
# Описания намеренно НЕ говорят «функция снизилась на 20-30%». Это было
# офтальмологическое: у глаза функция одна и она измеряется. В стоматологии
# измеряемой функции нет ни у одного диагноза, кроме адентии, а «почти полная
# потеря функции зуба» означает удаление, то есть отмену целевой продажи.
# Поэтому градации заданы через то, ЧТО именно нашла диагностика.
ИСХОДЫ: tuple[tuple[str, int, str], ...] = (
    (
        "без изменений",
        20,
        "Без особых изменений: то же самое, но измерено точнее, чем позволял "
        "осмотр. Показатели соответствуют известному из анамнеза, с поправкой "
        "на прошедшее время. Ничего нового диагностика не нашла.",
    ),
    (
        "умеренное ухудшение",
        40,
        "Несильное, но существенное ухудшение. Двигаются только те показатели, "
        "которые в этой отрасли реально меняются за прошедший срок: воспаление, "
        "чувствительность, охват, гигиенические индексы. Часть значений "
        "пограничная — у самой границы того, что считается нормальным.",
    ),
    (
        "сильное ухудшение",
        37,
        "Сильные изменения: несколько показателей заметно хуже, чем следует "
        "из анамнеза, и человек уже ощущает это в быту. Диагноз ТОТ ЖЕ — "
        "ухудшение не должно переводить состояние в соседнее заболевание.",
    ),
    (
        "крайний исход",
        3,
        "Крайний исход: состояние на пределе того, что бывает при этой болезни, "
        "с признаками обострения. Такое бывает крайне редко — пиши сдержанно "
        "и клинически, без драматизации. Диагноз всё равно остаётся прежним.",
    ),
)

# Гадания и выводы о продаже — те же правила, что у генератора случаев
# (case_generator._HEDGES): менеджер читает документ как данность
_HEDGES = (
    "предположительн", "возможно", "вероятно", "скорее всего", "по-видимому",
    "неизвестн", "не установлен", "уточнить у",
)
_SALES_CONCLUSIONS = (
    "требуется ", "показана ", "показано ", "рекомендована ", "рекомендовано ",
    "рекомендуется ", "необходима ", "необходимо ",
)

# Следы прежнего бланка. Модель, обученная на медицинских текстах, легко
# сползает обратно к «Объект исследования:» и к нормам в скобках, а документ
# при этом остаётся правдоподобным — поэтому ловим прямо.
_СТАРЫЙ_БЛАНК = ("объект исследования", "способ исследования")
_НОРМА_В_СТРОКЕ = re.compile(r"[(\-–—]\s*норма\b", re.IGNORECASE)

# Заголовок раздела: **Название исследования:** с новой строки
_ЗАГОЛОВОК = re.compile(r"^\s*\*\*[^*]+\*\*", re.MULTILINE)
_МИН_РАЗДЕЛОВ = 3

_MIN_LEN = 120
_MAX_LEN = 1600

INSTRUCTIONS = """Ты — врач диагностического кабинета. Пациент только что
прошёл обследование; ниже его анамнез из карты. Напиши РЕЗУЛЬТАТ сегодняшней
диагностики — так, как его печатают в клинике и выдают на руки.

ГЛАВНОЕ ПРАВИЛО: ты ПРОДОЛЖАЕШЬ эту историю болезни, а не начинаешь новую.
Болезнь та же, что в анамнезе, — диагноз указан его последней строкой.
Не добавляй новых заболеваний и не переименовывай имеющееся.

СРОК БЕРИ ИЗ АНАМНЕЗА. Там сказано, когда поставлен диагноз или сделано
предыдущее обследование («год назад на осмотре…», «около четырёх лет назад»).
Ухудшение должно быть правдоподобным ИМЕННО ЗА ЭТОТ СРОК. Показатель, который
за такой срок физически почти не меняется, оставь на месте и покажи ухудшение
по другому — по тому, что действительно движется. Если срок в анамнезе
не назван, считай, что прошло несколько месяцев.

ИСХОД ЗАДАН НИЖЕ ОТДЕЛЬНЫМ БЛОКОМ. Не выбирай его сам — исполни заданный.

ФОРМА ДОКУМЕНТА:

**Первичный осмотр** Имя Отчество, возраст

**Название исследования:**
значения — по стороне, по зубу, по органу, как принято в отрасли
**Название следующего исследования:**
значения

Заголовок каждого раздела — НАЗВАНИЕ ИССЛЕДОВАНИЯ, которое реально делают
в этой отрасли, обёрнутое в ** ** и с двоеточием. Разделов от трёх до шести.
Под заголовком — только измеренные значения, каждое с новой строки.
Никаких «Объект исследования» и «Способ исследования» отдельными строками:
объект и способ и так видны из названия раздела и самих значений.

НОРМЫ НЕ ПИШИ. Ни в скобках, ни через тире, нигде. В настоящем заключении
норм нет — их знает тот, кто читает. Пиши голые значения.

ЧЕГО В ДОКУМЕНТЕ БЫТЬ НЕ ДОЛЖНО:
- названий услуг и рекомендаций к лечению («требуется», «показана»,
  «рекомендуется» — это вывод о продаже, а не находка). Документ даёт
  менеджеру факты, предлагать — его работа;
- гаданий: «предположительно», «возможно», «вероятно» недопустимы,
  это сведения, а не рассуждение;
- диагноза словами — менеджер его и так знает из карты;
- жалоб пациента и его слов — только то, что видит и меряет аппаратура
  и врач.

Пиши на русском, клиническим языком отрасли, компактно: менеджер читает
документ между репликами разговора, у него полминуты.

Верни JSON вида {"document": "текст документа"}. Только JSON."""


_ВОЗРАСТ = re.compile(r"^\s*(\d{1,3})\s+(?:год|года|лет)\b", re.IGNORECASE)


def возраст_из(описание: str) -> str:
    """Возраст из строки карточки вида «62 года · повод обращения».

    Возраст стоит в шапке документа, а в промпте его раньше не было вовсе —
    и первый же живой прогон дал Тамаре 68 лет вместо 62. Модель не виновата:
    ей нечего было взять. Поле `description` лежало рядом в том же запросе.
    """
    m = _ВОЗРАСТ.match(описание or "")
    return m.group(0).strip() if m else ""


def выбрать_исход(rng: Optional[random.Random] = None) -> tuple[str, str]:
    """(ключ, описание для модели) — взвешенный случайный выбор кодом.

    rng параметром — ради тестов: взвешенный выбор без подмены генератора
    не проверить.
    """
    r = rng or random
    ключи_и_описания = [(к, о) for к, _, о in ИСХОДЫ]
    веса = [в for _, в, _ in ИСХОДЫ]
    return r.choices(ключи_и_описания, weights=веса, k=1)[0]


def чем_плох(document: str, имя: str) -> Optional[str]:
    """Проверка документа. Возвращает причину отказа либо None. Чистая функция.

    Формы документа раньше не проверялось вовсе. После отмены норм это стало
    единственным, что удерживает бланк: без проверки модель сползает к прежним
    «Объект исследования:» и «(норма до 10%)», причём документ остаётся
    правдоподобным — а значит, поломка молчит.
    """
    text = (document or "").strip()
    if len(text) < _MIN_LEN:
        return f"документ подозрительно короткий: {len(text)} символов"
    if len(text) > _MAX_LEN:
        return f"документ раздут: {len(text)} символов — менеджеру не прочесть в бою"

    lowered = text.lower()
    гадание = next((h for h in _HEDGES if h in lowered), None)
    if гадание:
        return f"документ гадает: «{гадание}»"
    вывод = next((s for s in _SALES_CONCLUSIONS if s in lowered), None)
    if вывод:
        return f"вывод о продаже вместо находки: «{вывод.strip()}»"

    старое = next((с for с in _СТАРЫЙ_БЛАНК if с in lowered), None)
    if старое:
        return f"прежний бланк: строка «{старое}» отменена, заголовок — название исследования"
    норма = _НОРМА_В_СТРОКЕ.search(text)
    if норма:
        return f"норма рядом со значением: «{норма.group().strip()}» — их не пишут"

    разделов = len(_ЗАГОЛОВОК.findall(text))
    if разделов < _МИН_РАЗДЕЛОВ:
        return f"разделов {разделов}, нужно хотя бы {_МИН_РАЗДЕЛОВ} — заголовки в ** **"

    # Имя в шапке — первая строка формата. Сверяем по первому слову имени:
    # модель может склонить отчество, а имя в именительном остаётся
    первое_слово = имя.split()[0].lower() if имя.strip() else ""
    if первое_слово and первое_слово not in lowered:
        return "в шапке нет имени пациента"

    return None


async def generate_result(
    имя: str,
    anamnesis: str,
    industry: str,
    исход_описание: str,
    описание_пациента: str = "",
) -> Optional[str]:
    """Документ диагностики поверх готового анамнеза. None — не получилось.

    Температура низкая: здесь нужна верность анамнезу, а не живость —
    живым должен быть разговор, а не заключение врача.
    """
    settings = get_settings()
    возраст = возраст_из(описание_пациента)
    строка_пациента = f"{имя}, {возраст}" if возраст else имя
    messages = [
        {"role": "system", "content": INSTRUCTIONS},
        {
            "role": "user",
            "content": (
                f"ОТРАСЛЬ: {industry or 'медицина'}\n\n"
                f"ПАЦИЕНТ (в шапку — дословно, возраст не пересчитывай "
                f"и не выдумывай): {строка_пациента}\n\n"
                f"АНАМНЕЗ ИЗ КАРТЫ:\n{anamnesis}\n\n"
                f"ИСХОД СЕГОДНЯШНЕЙ ДИАГНОСТИКИ (исполни именно его):\n"
                f"{исход_описание}"
            ),
        },
    ]

    for attempt in range(1, _SHAPE_ATTEMPTS + 1):
        ответ = await ask_json(
            messages,
            model=settings.clinical_model,
            purpose="результат диагностики",
            attempts=_PROVIDER_ATTEMPTS,
            temperature=0.3,
            max_tokens=8000,
        )
        if ответ is None:
            return None

        document = str(ответ.get("document") or "").strip()
        беда = чем_плох(document, имя)
        if беда is None:
            return document
        logger.warning(
            "Результат диагностики, попытка %d: не годится — %s", attempt, беда
        )

    logger.error(
        "Результат диагностики: %d ответа подряд не прошли проверку",
        _SHAPE_ATTEMPTS,
    )
    return None
