"""Замер критика на размеченных данных: ловит ли брак и не трогает ли годное.

Пока критик не проверен, включать его нельзя. Непроверенный критик опаснее
отсутствующего: он бракует молча, и систематическая ошибка выглядит как
проверенное качество.

Разметку дали живые врачи. Восемь браков — настоящие случаи, которые они
забраковали 06-07.08. Восемь годных опираются на их же прямые утверждения
(«после 40 пресбиопия развивается абсолютно у всех», «кариес даёт о себе
знать если он прикорневой», «по стоматологии в целом всё ок»).

ЧИТАТЬ ИТОГ С ОГОВОРКОЙ. Годные размечены нами по правилам врачей, а не
помечены ими поштучно — прямых «этот хорош» у нас нет. Значит доля ложных
отказов измеряется приблизительнее, чем доля пропусков.

ОШИБКИ КРИТИКА НЕСИММЕТРИЧНЫ, и смотреть надо на обе. Пропущенный брак
дорог: врач видит чепуху. Ложный отказ дёшев: берём следующую картину.
Поэтому критик, который бракует всё подряд, бесполезен ровно так же,
как критик, который всё пропускает, — и то и другое видно только вместе.

Запуск внутри backend-контейнера на DE:

    python scripts/measure_critic.py
    python scripts/measure_critic.py --модели openai/gpt-5.6-luna,openai/gpt-4o-mini

ПЛАТНО: 16 вызовов на модель.
"""

import argparse
import asyncio
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from core.config import get_settings  # noqa: E402
from services import case_review, usage  # noqa: E402

_НАБОР = os.path.join(os.path.dirname(os.path.abspath(__file__)), "critic_labelled.json")
_ПАУЗА_СЕК = 1.0


async def прогнать(случаи: list[dict], модель: str) -> list[dict]:
    """Критик по каждому случаю. Разметку он не видит."""
    настройки = get_settings()
    настройки.critic_model = модель
    настройки.critic_enabled = True  # замер и есть та проверка, ради которой выключен

    итоги = []
    for номер, случай in enumerate(случаи, 1):
        годится, виновник, возражение = await case_review.review(
            {"identity": случай["identity"]},
            случай["picture"],
            {"anamnesis": случай["anamnesis"]},
            случай["service"],
        )
        сказал = "годится" if годится else "брак"
        итоги.append(
            {
                "диагноз": случай["picture"]["diagnosis"],
                "метка": случай["метка"],
                "сказал": сказал,
                "верно": сказал == случай["метка"],
                "виновник": виновник or "",
                "возражение": возражение,
                "почему_в_разметке": случай["почему"],
            }
        )
        print(f"  {номер}/{len(случаи)} {случай['picture']['diagnosis'][:34]:36} "
              f"метка {случай['метка']:8} критик {сказал}", file=sys.stderr, flush=True)
        await asyncio.sleep(_ПАУЗА_СЕК)
    return итоги


def отчёт(по_моделям: dict[str, list[dict]], счёт: dict) -> str:
    куски = ["# Замер критика на размеченных данных", ""]

    куски += ["## Итог", "", "| Модель | Поймано брака | Ложных отказов | Всего верно |", "|---|---|---|---|"]
    for модель, итоги in по_моделям.items():
        браки = [и for и in итоги if и["метка"] == "брак"]
        годные = [и for и in итоги if и["метка"] == "годится"]
        поймано = sum(1 for и in браки if и["сказал"] == "брак")
        ложных = sum(1 for и in годные if и["сказал"] == "брак")
        верно = sum(1 for и in итоги if и["верно"])
        куски.append(
            f"| `{модель}` | {поймано} из {len(браки)} | {ложных} из {len(годные)} "
            f"| {верно} из {len(итоги)} |"
        )
    куски.append("")

    for модель, итоги in по_моделям.items():
        куски += [f"## {модель}", ""]
        for и in итоги:
            знак = "OK " if и["верно"] else "МИМО"
            куски.append(f"**{знак} · {и['диагноз']}** — метка «{и['метка']}», критик сказал «{и['сказал']}»")
            куски.append("")
            куски.append(f"- в разметке: {и['почему_в_разметке']}")
            if и["возражение"]:
                куски.append(f"- критик ({и['виновник']}): {и['возражение']}")
            куски.append("")

    куски += ["## Расход", "", "```json", json.dumps(счёт, ensure_ascii=False, indent=2), "```"]
    return "\n".join(куски)


async def main() -> None:
    разбор = argparse.ArgumentParser(description="Замер критика на размеченных данных")
    разбор.add_argument("--набор", default=_НАБОР)
    разбор.add_argument("--модели", default=None,
                        help="через запятую; по умолчанию — critic_model из настроек")
    доводы = разбор.parse_args()

    with open(доводы.набор, encoding="utf-8") as файл:
        случаи = json.load(файл)["cases"]

    модели = (
        [м.strip() for м in доводы.модели.split(",")]
        if доводы.модели
        else [get_settings().critic_model]
    )
    print(f"Случаев {len(случаи)}, моделей {len(модели)}. ПЛАТНО.", file=sys.stderr)

    по_моделям = {}
    with usage.учёт() as счёт:
        for модель in модели:
            print(f"=== {модель} ===", file=sys.stderr, flush=True)
            по_моделям[модель] = await прогнать(случаи, модель)

    print(отчёт(по_моделям, счёт.как_словарь()))


if __name__ == "__main__":
    asyncio.run(main())
