"""Сторож живости генератора результата диагностики.

Зачем он вообще нужен. После перехода на пресеты все 42 случая обеих отраслей
имеют вычитанный врачом документ, и `main.py` в этом случае модель НЕ зовёт —
показывает пресет. То есть генератор в бою больше не выполняется ни разу.
Первым его отказ увидит боевой клиент, у которого случай собран генератором:
он нажмёт кнопку и получит «Не удалось сгенерировать» — а мы узнаем об этом
от него же.

Механизм, который не выполняется, ломается молча: сменилась модель у
провайдера, переименовали поле в ответе, уехал формат промпта — тесты этого
не заметят, потому что проверяют чистые функции, а не живой вызов.

Поэтому здесь один честный прогон: берём анамнез, зовём генератор ровно так,
как его зовёт прод, и смотрим, вернулся ли документ, проходящий `чем_плох`.

    docker exec ai-trainer-backend-1 sh -c 'cd /app && python scripts/smoke_diagnostics.py'

ПЛАТНО: один-два вызова клинической модели (около цента). Запускать после
правок в diagnostics.py, после смены модели и просто раз в месяц — чтобы
поломку нашёл этот скрипт, а не клиент.

Код возврата: 0 — генератор жив, 1 — нет. Годится для ручного прогона
и для будущей проверки по расписанию.
"""

import argparse
import asyncio
import logging
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from services import diagnostics  # noqa: E402

logger = logging.getLogger(__name__)

# Анамнез и карточка настоящего пресетного пациента: генератору нужен вход,
# похожий на боевой, а выдуманный на ходу текст проверял бы не то. Тамара —
# та же, на которой отлаживали форму документа и которую читал эксперт.
ИМЯ = "Тамара Михайловна"
ОПИСАНИЕ = "62 года · диагностика зрения"
ОТРАСЛЬ = "офтальмология"
АНАМНЕЗ = (
    "Обратилась с жалобами на постепенное снижение зрения вдаль на обоих "
    "глазах в течение полутора лет. Отмечает туман перед глазами, усиление "
    "засветов от фар при вождении в тёмное время суток, потребность в более "
    "ярком освещении при чтении. Очки, подобранные два года назад, помогают "
    "хуже. Сопутствующих заболеваний глаз ранее не выявлялось, травм и "
    "операций не было. Общее состояние удовлетворительное. "
    "Диагноз: Возрастная катаракта"
)
# Прайс — только для проверки: документ не имеет права называть услугу
УСЛУГИ = (
    "Замена хрусталика с имплантацией ИОЛ",
    "Лазерная коррекция зрения",
    "Лечение глаукомы",
    "Подбор очков и контактных линз",
    "Полная диагностика зрения",
)


async def main() -> int:
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument(
        "--исход",
        default="умеренное ухудшение",
        help="какой исход диагностики исполнить (ключ из ИСХОДЫ)",
    )
    разбор.add_argument(
        "--показать", action="store_true", help="напечатать документ целиком"
    )
    аргументы = разбор.parse_args()

    исходы = {ключ: описание for ключ, _, описание in diagnostics.ИСХОДЫ}
    if аргументы.исход not in исходы:
        print(f"Неизвестный исход. Есть: {', '.join(исходы)}")
        return 1

    print(f"Пациент: {ИМЯ}, {ОПИСАНИЕ}")
    print(f"Исход:   {аргументы.исход}")
    print("Зову генератор…\n")

    документ = await diagnostics.generate_result(
        ИМЯ,
        АНАМНЕЗ,
        ОТРАСЛЬ,
        исходы[аргументы.исход],
        ОПИСАНИЕ,
        УСЛУГИ,
    )

    if документ is None:
        print("ГЕНЕРАТОР МЁРТВ: документ не вернулся.")
        print("Смотреть: ключ провайдера, имя модели в настройках, логи выше.")
        return 1

    # Проверку прогоняем ещё раз явно: generate_result уже её прошёл, но
    # печатать вердикт полезно — видно, что сторожит именно то, что думаем
    возраст = diagnostics.возраст_из(ОПИСАНИЕ)
    беда = diagnostics.чем_плох(документ, ИМЯ, УСЛУГИ, возраст)
    разделов = len(diagnostics._ЗАГОЛОВОК.findall(документ))

    print(f"ГЕНЕРАТОР ЖИВ: {len(документ)} символов, разделов {разделов}.")
    print(f"Проверка формы: {беда or 'прошёл'}")
    if аргументы.показать:
        print("\n" + "-" * 60)
        print(документ)
        print("-" * 60)
    else:
        print("\nПервые строки:")
        for строка in документ.splitlines()[:4]:
            print("  " + строка)
        print("  … (целиком — с ключом --показать)")

    return 0 if беда is None else 1


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    sys.exit(asyncio.run(main()))
