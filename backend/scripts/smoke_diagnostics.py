"""Сторож живости генератора результата диагностики.

Зачем он вообще нужен. После перехода на пресеты все 42 случая обеих отраслей
имеют вычитанный врачом документ, и `main.py` в этом случае модель НЕ зовёт —
показывает пресет. То есть генератор в бою больше не выполняется ни разу.
Первым его отказ увидит боевой клиент, у которого случай собран генератором:
он нажмёт кнопку и получит «Не удалось сгенерировать» — а мы узнаем об этом
от него же.

Механизм, который не выполняется, ломается молча: сменилась модель у
провайдера, переименовали поле в ответе, уехал формат промпта — тесты этого
не заметят, потому что проверяют чистые функции, а не живой вызов.

Поэтому здесь один честный прогон: берём анамнез, зовём генератор ровно так,
как его зовёт прод, и смотрим, вернулся ли документ, проходящий `чем_плох`.

    docker exec ai-trainer-backend-1 sh -c 'cd /app && python scripts/smoke_diagnostics.py'

ВХОД БЕРЁТСЯ ИЗ БАЗЫ, а не из строки в этом файле. Первая версия несла
выдуманный анамнез «по мотивам» пресетного — без единой цифры. На таком
входе генератор волен писать любые значения, и документ сходится с чем
угодно: сторож проверял живость вызова, но не верность анамнезу, то есть
половину своего смысла. Копия текста здесь и отставала бы от репозитория
при первой же правке пресета.

ПЛАТНО: один-два вызова клинической модели (около цента). Запускать после
правок в diagnostics.py, после смены модели и просто раз в месяц — чтобы
поломку нашёл этот скрипт, а не клиент.

Код возврата: 0 — генератор жив, 1 — нет. Годится для ручного прогона
и для будущей проверки по расписанию.
"""

import argparse
import asyncio
import logging
import os
import sys

import asyncpg

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from core.config import get_settings  # noqa: E402
from services import diagnostics  # noqa: E402

logger = logging.getLogger(__name__)

# Пациент по умолчанию — тот, на котором отлаживали форму документа
# и которого читал эксперт
ПАЦИЕНТ = "Тамара Михайловна"
ОТРАСЛЬ = "офтальмология"

# Случай пресетной организации: ровно то, с чем работает прод. Услуги той же
# организации нужны для проверки «документ не называет услугу» — в промпт
# они не идут
ЗАПРОС = """
    SELECT p."name"            AS имя,
           pc."anamnesis"      AS анамнез,
           pc."description"    AS описание,
           o."industry"        AS отрасль,
           COALESCE((SELECT array_agg(s."name") FROM "Service" s
                      WHERE s."organizationId" = o."id"), ARRAY[]::text[]) AS услуги
      FROM "PatientCase" pc
      JOIN "Patient" p      ON p."id" = pc."patientId"
      JOIN "Organization" o ON o."id" = pc."organizationId"
     WHERE o."isPreset" AND o."industry" = $1 AND p."name" = $2
     LIMIT 1
"""


async def взять_случай(отрасль: str, имя: str) -> asyncpg.Record | None:
    settings = get_settings()
    соединение = await asyncpg.connect(dsn=settings.asyncpg_dsn)
    try:
        return await соединение.fetchrow(ЗАПРОС, отрасль, имя)
    finally:
        await соединение.close()


async def main() -> int:
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--пациент", default=ПАЦИЕНТ, help="имя пресетного пациента")
    разбор.add_argument("--отрасль", default=ОТРАСЛЬ, help="отрасль пресета")
    разбор.add_argument(
        "--исход",
        default="умеренное ухудшение",
        help="какой исход диагностики исполнить (ключ из ИСХОДЫ)",
    )
    разбор.add_argument(
        "--показать", action="store_true", help="напечатать документ целиком"
    )
    аргументы = разбор.parse_args()

    исходы = {ключ: описание for ключ, _, описание in diagnostics.ИСХОДЫ}
    if аргументы.исход not in исходы:
        print(f"Неизвестный исход. Есть: {', '.join(исходы)}")
        return 1

    случай = await взять_случай(аргументы.отрасль, аргументы.пациент)
    if случай is None or not (случай["анамнез"] or "").strip():
        print(
            f"Не нашёл случай «{аргументы.пациент}» в пресете «{аргументы.отрасль}». "
            f"Сначала npm run seed:presets."
        )
        return 1

    анамнез = случай["анамнез"].strip()
    описание = (случай["описание"] or "").strip()
    услуги = list(случай["услуги"] or [])

    print(f"Пациент: {случай['имя']}, {описание}")
    print(f"Анамнез: {len(анамнез)} символов, из базы (пресет «{аргументы.отрасль}»)")
    print(f"Услуг в прайсе: {len(услуги)}")
    print(f"Исход:   {аргументы.исход}")
    print("Зову генератор…\n")

    документ = await diagnostics.generate_result(
        случай["имя"],
        анамнез,
        случай["отрасль"] or аргументы.отрасль,
        исходы[аргументы.исход],
        описание,
        услуги,
    )

    if документ is None:
        print("ГЕНЕРАТОР МЁРТВ: документ не вернулся.")
        print("Смотреть: ключ провайдера, имя модели в настройках, логи выше.")
        return 1

    # Проверку прогоняем ещё раз явно: generate_result уже её прошёл, но
    # печатать вердикт полезно — видно, что сторожит именно то, что думаем
    возраст = diagnostics.возраст_из(описание)
    беда = diagnostics.чем_плох(документ, случай["имя"], услуги, возраст)
    разделов = len(diagnostics._ЗАГОЛОВОК.findall(документ))

    print(f"ГЕНЕРАТОР ЖИВ: {len(документ)} символов, разделов {разделов}.")
    print(f"Проверка формы: {беда or 'прошёл'}")
    print(
        "\nВЕРНОСТЬ АНАМНЕЗУ КОДОМ НЕ ПРОВЕРЯЕТСЯ — прочитай сам или прогони\n"
        "scripts/review_diagnostics.py. Смотреть в первую очередь на числа:\n"
        "показатель не может стать лучше без лечения, а диагноз — смениться."
    )
    print("\nАНАМНЕЗ (вход):")
    print("  " + анамнез.replace("\n", "\n  "))
    print("\nДОКУМЕНТ (выход):")
    if аргументы.показать:
        print("  " + документ.replace("\n", "\n  "))
    else:
        for строка in документ.splitlines()[:4]:
            print("  " + строка)
        print("  … (целиком — с ключом --показать)")

    return 0 if беда is None else 1


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    sys.exit(asyncio.run(main()))
