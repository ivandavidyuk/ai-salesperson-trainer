"""Критик читает пару «анамнез + документ диагностики».

Документы пресетов написаны руками и лежат в репозитории фронтенда. Значит
они прошли мимо генератора, а вместе с ним — мимо `чем_плох`, единственной
проверки, которая у сгенерированного была. Валидатор пресетов на TypeScript
ловит форму: имя, разделы, нормы, упоминание услуги. Он не умеет и не должен
уметь читать СОДЕРЖАНИЕ — сказать, что документ противоречит истории болезни.

Ровно тем же приёмом и по той же причине сделан `review_presets.py`: там
критик читает случай, здесь — пару «анамнез и его сегодняшний результат».
Вопрос у критика один и узкий: сходится ли документ с анамнезом. Узкий
намеренно — критик, которого просят «оценить качество», хвалит.

    cd frontend && npm run --silent dump:presets > пресеты.json
    docker cp пресеты.json ai-trainer-backend-1:/tmp/
    docker exec ai-trainer-backend-1 sh -c \\
        'cd /app && python scripts/review_diagnostics.py --файл /tmp/пресеты.json'

ПЛАТНО, но дёшево: один вызов дешёвой модели на документ. Случаи без
документа пропускаются молча — их просто ещё не написали.

Скрипт ничего не чинит и никуда не пишет: правки идут в репозиторий руками.
"""

import argparse
import asyncio
import json
import logging
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from core.config import get_settings  # noqa: E402
from services import usage  # noqa: E402
from services.llm_json import ask_json  # noqa: E402

logger = logging.getLogger(__name__)

# Провайдер троттлит, если бить вплотную — та же пауза, что при сборке
_ПАУЗА_СЕК = 1.0

ВОПРОС = """Ты — врач, вычитывающий документы перед выдачей пациентам.
Тебе дают ИСТОРИЮ БОЛЕЗНИ из карты и РЕЗУЛЬТАТ сегодняшнего обследования
того же человека. Ответь на один вопрос: сходятся ли они.

Документ ОБЯЗАН показывать ту же болезнь с небольшим ухудшением. Срок между
записями назван в истории болезни.

БРАКУЙ, если:
- болезнь в документе другая или добавилась новая;
- показатель ухудшился сильнее, чем возможно за названный срок (кость,
  убыль пародонта, глубина некариозного дефекта меняются годами и почти
  незаметно; воспаление, налёт, чувствительность — неделями);
- показатель, который в истории уже измерен, вдруг УЛУЧШИЛСЯ без лечения;
- ухудшение перевело состояние в соседнее заболевание (например, борозда
  стала пародонтальным карманом, пульпит стал периодонтитом);
- числа противоречат друг другу или невозможны для этого человека
  (возраст, пол, набор зубов, оперированный глаз);
- документ называет диагноз словами, советует лечение или упоминает услугу.

НЕ БРАКУЙ за то, что документ неполон: он короткий намеренно, его читают
за полминуты. И не требуй норм рядом со значениями — в настоящем заключении
их не пишут.

Верни JSON: {"годится": true|false, "возражение": "одной фразой, чем плохо"}.
Если годится — возражение пустой строкой. Только JSON."""


async def прогнать(случаи: list[dict], модель: str) -> list[dict]:
    """Каждую пару — критику. Возвращает строки отчёта."""
    итог: list[dict] = []

    for номер, строка in enumerate(случаи, 1):
        сообщения = [
            {"role": "system", "content": ВОПРОС},
            {
                "role": "user",
                "content": (
                    f"ОТРАСЛЬ: {строка.get('industry', '')}\n\n"
                    f"ПАЦИЕНТ: {строка.get('patientName', '')}\n"
                    f"{строка.get('personality', {}).get('identity', '')}\n\n"
                    f"ИСТОРИЯ БОЛЕЗНИ ИЗ КАРТЫ:\n"
                    f"{строка.get('case', {}).get('anamnesis', '')}\n\n"
                    f"РЕЗУЛЬТАТ СЕГОДНЯШНЕГО ОБСЛЕДОВАНИЯ:\n"
                    f"{строка.get('diagnostics') or ''}"
                ),
            },
        ]
        ответ = await ask_json(
            сообщения,
            model=модель,
            purpose="вычитка документа диагностики",
            attempts=2,
            temperature=0.0,
            max_tokens=2000,
        )
        # Молчание провайдера — не «годится». Считаем неизвестным и говорим
        # об этом вслух: молчаливое «ок» здесь опаснее брака
        if ответ is None:
            годится, возражение = False, "критик не ответил — прогнать повторно"
        else:
            годится = bool(ответ.get("годится"))
            возражение = str(ответ.get("возражение") or "").strip()

        итог.append(
            {
                "отрасль": строка.get("industry", ""),
                "имя": строка.get("patientName", ""),
                "диагноз": (строка.get("picture") or {}).get("diagnosis", ""),
                "годится": годится,
                "возражение": возражение,
            }
        )
        метка = "годится" if годится else f"БРАК: {возражение}"
        print(
            f"  {номер}/{len(случаи)} {строка.get('patientName', '')} "
            f"[{строка.get('industry', '')}] — {метка}",
            file=sys.stderr,
            flush=True,
        )
        await asyncio.sleep(_ПАУЗА_СЕК)
    return итог


async def main() -> None:
    разбор = argparse.ArgumentParser(
        description="Критик читает пары «анамнез + документ диагностики»"
    )
    разбор.add_argument("--файл", required=True, help="JSON из npm run dump:presets")
    разбор.add_argument("--отрасль", default=None, help="только одна отрасль")
    разбор.add_argument("--модель", default=None,
                        help="модель критика; по умолчанию critic_model из настроек")
    доводы = разбор.parse_args()

    with open(доводы.файл, encoding="utf-8") as файл:
        случаи = json.load(файл)
    if доводы.отрасль:
        случаи = [с for с in случаи if с.get("industry") == доводы.отрасль]

    всего = len(случаи)
    случаи = [с for с in случаи if (с.get("diagnostics") or "").strip()]
    if not случаи:
        print(
            f"Ни у одного из {всего} случаев нет документа диагностики — "
            "вычитывать нечего.",
            file=sys.stderr,
        )
        sys.exit(2)

    logging.basicConfig(level=logging.INFO, format="%(message)s", stream=sys.stderr)

    настройки = get_settings()
    модель = доводы.модель or настройки.critic_model
    print(
        f"Критик {модель}. Документов {len(случаи)} из {всего} случаев. ПЛАТНО.",
        file=sys.stderr,
    )

    with usage.учёт() as счёт:
        строки = await прогнать(случаи, модель)

    брак = [с for с in строки if not с["годится"]]
    print(f"\nГодятся {len(строки) - len(брак)} из {len(строки)}.", file=sys.stderr)
    for с in брак:
        print(
            f"  БРАК · {с['отрасль']} · {с['имя']} · {с['диагноз']}: {с['возражение']}",
            file=sys.stderr,
        )

    print(json.dumps({"документы": строки, "расход": счёт.как_словарь()},
                     ensure_ascii=False, indent=2))


if __name__ == "__main__":
    asyncio.run(main())
