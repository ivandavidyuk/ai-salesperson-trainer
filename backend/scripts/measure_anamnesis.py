"""Замер правдоподобия анамнезов на трёх случаях, забракованных врачом.

Повод. 06.08.2026 Дима (врач) забраковал сгенерированные случаи: «придуманы
случаи, но они иногда противоречат законам природы». Миопия, впервые
возникшая в 48 и 44 года; начальная катаракта с жалобой на даль вместо близи.

Первым заходом этот скрипт мерил вклад температуры и показал, что дело
не в ней: при 0.2 подлог оставался, а в графе «объективно» стояло
«требуется лазерная коррекция зрения» — вывод о продаже вместо находки.
Тот замер лежит в истории PR #88.

Теперь скрипт мерит новый конвейер целиком: диагноз ставит отдельный вызов,
не знающий про услуги, услуга подбирается под диагноз, проза пишется
последней. Критерий — воспроизводится ли брак, названный у каждого пациента
в фикстуре.

Считается только считаемое: форма ответа и расход токенов. Правдоподобен ли
диагноз, регуляркой не определить — тексты кладутся рядом и читаются глазами.

Запуск внутри backend-контейнера на DE: из России путь до OpenRouter другой,
и ключ живёт там же.

    python scripts/measure_anamnesis.py
    python scripts/measure_anamnesis.py --повторов 5
    python scripts/measure_anamnesis.py --модель anthropic/claude-opus-4.5

ПЛАТНО. По умолчанию 9 сборок, в каждой 3 вызова модели.
"""

import argparse
import asyncio
import json
import os
import sys
from datetime import datetime, timezone

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from core.config import get_settings  # noqa: E402
from services import case_generator, usage  # noqa: E402

_НАБОР = os.path.join(os.path.dirname(os.path.abspath(__file__)), "anamnesis_regression.json")

# Провайдер троттлит, если бить вплотную. В бою случаи собираются
# последовательно по той же причине (см. rebuildCases)
_ПАУЗА_СЕК = 1.5


async def прогнать(набор: dict, повторов: int) -> list[dict]:
    """Все пациенты × повторы. Последовательно, с паузами."""
    клиника = набор["clinic"]
    строки: list[dict] = []
    всего = len(набор["patients"]) * повторов
    сделано = 0

    for пациент in набор["patients"]:
        for номер in range(1, повторов + 1):
            случай = await case_generator.generate_case(пациент["personality"], клиника)
            строки.append(
                {
                    "пациент": пациент["name"],
                    "возраст": пациент["возраст"],
                    "прежний_брак": пациент["брак"],
                    "повтор": номер,
                    "диагноз": (случай or {}).get("diagnosis"),
                    "услуга": (случай or {}).get("service"),
                    "анамнез": (случай or {}).get("anamnesis"),
                    "карточка": (случай or {}).get("description"),
                }
            )
            сделано += 1
            print(f"  {сделано}/{всего} {пациент['name']} #{номер}",
                  file=sys.stderr, flush=True)
            await asyncio.sleep(_ПАУЗА_СЕК)
    return строки


def отчёт(строки: list[dict], модель: str, клиническая: str, счёт: dict) -> str:
    """Markdown: диагноз, услуга и анамнез рядом — чтобы видеть подлог."""
    куски = [
        "# Замер анамнезов",
        "",
        f"Проза: `{модель}` · картина: `{клиническая}`",
        f"{datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC",
        "",
        "Смотреть на три вещи: правдоподобен ли диагноз для возраста, следуют",
        "ли из него жалобы, и не стоит ли в анамнезе вывод о продаже",
        "(«требуется…», «показана…») вместо находки осмотра.",
        "",
    ]

    for имя in dict.fromkeys(с["пациент"] for с in строки):
        свои = [с for с in строки if с["пациент"] == имя]
        куски += [
            f"## {имя}, {свои[0]['возраст']} лет",
            "",
            f"**Прежний брак:** {свои[0]['прежний_брак']}",
            "",
        ]
        for с in свои:
            if not с["анамнез"]:
                куски += [f"**{с['повтор']}.** случай не собрался", ""]
                continue
            куски += [
                f"**{с['повтор']}.** {с['диагноз']} → продаём: {с['услуга']}",
                "",
                f"> {с['анамнез']}",
                ">",
                f"> карточка: {с['карточка']}",
                "",
            ]

    куски += ["## Расход", "", "```json", json.dumps(счёт, ensure_ascii=False, indent=2), "```"]
    return "\n".join(куски)


async def main() -> None:
    разбор = argparse.ArgumentParser(description="Замер правдоподобия анамнезов")
    разбор.add_argument("--набор", default=_НАБОР, help="фикстура с личностями и клиникой")
    разбор.add_argument("--повторов", type=int, default=3,
                        help="сборок на пациента (по умолчанию 3)")
    разбор.add_argument("--модель", default=None,
                        help="модель прозы; по умолчанию case_model из настроек")
    разбор.add_argument("--клиническая", default=None,
                        help="модель клинического шага; по умолчанию clinical_model")
    разбор.add_argument("--вывод", default=None, help="куда положить отчёт (иначе только stdout)")
    доводы = разбор.parse_args()

    with open(доводы.набор, encoding="utf-8") as файл:
        набор = json.load(файл)

    # Настройки кешируются, поэтому подменяем поля на месте: так замер умеет
    # сравнивать модели, не требуя пересборки контейнера с другим окружением
    настройки = get_settings()
    if доводы.модель:
        настройки.case_model = доводы.модель
    if доводы.клиническая:
        настройки.clinical_model = доводы.клиническая

    всего = len(набор["patients"]) * доводы.повторов
    print(
        f"Проза {настройки.case_model}, картина {настройки.clinical_model}, "
        f"сборок {всего}. ПЛАТНО.",
        file=sys.stderr,
    )

    with usage.учёт() as счёт:
        строки = await прогнать(набор, доводы.повторов)

    текст = отчёт(строки, настройки.case_model, настройки.clinical_model, счёт.как_словарь())
    # Печатаем всегда: файлы внутри контейнера переживают только его самого,
    # а деплой пересоздаёт контейнер вместе с ними
    print(текст)
    if доводы.вывод:
        with open(доводы.вывод, "w", encoding="utf-8") as файл:
            файл.write(текст)
        print(f"Отчёт: {доводы.вывод}", file=sys.stderr)


if __name__ == "__main__":
    asyncio.run(main())
