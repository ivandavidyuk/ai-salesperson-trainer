"""Замер: сколько брака в анамнезах даёт температура, а сколько устройство.

Повод. 06.08.2026 Дима (врач) забраковал сгенерированные случаи: «придуманы
случаи, но они иногда противоречат законам природы». Три примера — миопия,
впервые возникшая в 48 и 44 года, и начальная катаракта с жалобой на даль
вместо близи.

Причин у этого две, и они разной цены. Дешёвая — `temperature=0.7`, одна
на все девять полей: живость прозы и точность диагноза требуют разного.
Дорогая — устройство: инструкция велит подразумевать продаваемую услугу,
поэтому модель берёт услугу и подгоняет диагноз под неё.

Этот скрипт отделяет одно от другого ДО того, как переделывать генератор
и платить за сильную модель. Гоняет нынешний код на неизменной фикстуре
при разных температурах и складывает анамнезы рядом — читать глазами.

Читать глазами и правда придётся: «правдоподобен ли диагноз» регуляркой
не определяется. Скрипт считает только то, что считается, — прошёл ли ответ
проверку формы и сколько ушло токенов.

Запуск внутри backend-контейнера на DE: из России путь до OpenRouter другой,
и ключ живёт там же.

    python scripts/measure_anamnesis.py
    python scripts/measure_anamnesis.py --повторов 5 --температуры 0.2,0.5,0.7
    python scripts/measure_anamnesis.py --модель anthropic/claude-opus-4.5

ПЛАТНО. При настройках по умолчанию — 18 вызовов на самой дешёвой модели,
это центы. С `--модель` посильнее считайте заново.
"""

import argparse
import asyncio
import json
import os
import sys
from datetime import datetime, timezone

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from core.config import get_settings  # noqa: E402
from services import usage  # noqa: E402
from services.case_generator import build_messages, validate_case  # noqa: E402
from services.llm_json import ask_json  # noqa: E402

_НАБОР = os.path.join(os.path.dirname(os.path.abspath(__file__)), "anamnesis_regression.json")

# Провайдер троттлит, если бить вплотную. В бою случаи собираются
# последовательно по той же причине (см. rebuildCases)
_ПАУЗА_СЕК = 1.5
# Столько же, сколько у генератора в бою: замер должен мерить генератор,
# а не нашу настойчивость
_ПОПЫТОК_ПРОВАЙДЕРА = 3


async def один_прогон(личность: dict, клиника: dict, модель: str, температура: float) -> dict:
    """Один вызов генератора. Возвращает анамнез и что с ним не так по форме."""
    ответ = await ask_json(
        build_messages(личность, клиника),
        model=модель,
        purpose="замер анамнеза",
        attempts=_ПОПЫТОК_ПРОВАЙДЕРА,
        temperature=температура,
        max_tokens=8000,
    )
    if ответ is None:
        return {"анамнез": None, "форма": "провайдер не ответил"}

    # validate_case правит ответ на месте (чистит словарь) — для замера это
    # безразлично, нам нужен только вердикт
    беда = validate_case(ответ, личность)
    return {
        "анамнез": ответ.get("anamnesis"),
        "карточка": ответ.get("description"),
        "форма": беда,
    }


async def прогнать(набор: dict, модель: str, температуры: list[float], повторов: int) -> list[dict]:
    """Все пациенты × все температуры × повторы. Последовательно, с паузами."""
    клиника = набор["clinic"]
    строки = []
    всего = len(набор["patients"]) * len(температуры) * повторов
    сделано = 0

    for пациент in набор["patients"]:
        for температура in температуры:
            for номер in range(1, повторов + 1):
                итог = await один_прогон(пациент["personality"], клиника, модель, температура)
                строки.append(
                    {
                        "пациент": пациент["name"],
                        "возраст": пациент["возраст"],
                        "прежний_брак": пациент["брак"],
                        "температура": температура,
                        "повтор": номер,
                        **итог,
                    }
                )
                сделано += 1
                # В stderr, чтобы не мешалось в перенаправленном отчёте
                print(f"  {сделано}/{всего} {пациент['name']} t={температура} #{номер}",
                      file=sys.stderr, flush=True)
                await asyncio.sleep(_ПАУЗА_СЕК)
    return строки


def отчёт(строки: list[dict], модель: str, счёт: dict) -> str:
    """Markdown: анамнезы сгруппированы по пациенту и температуре."""
    куски = [
        "# Замер анамнезов",
        "",
        f"Модель: `{модель}` · {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC",
        "",
        "Правдоподобие диагноза проверяется чтением — ниже только тексты.",
        "Смотреть на то, повторяется ли прежний брак, названный у пациента.",
        "",
    ]

    for имя in dict.fromkeys(с["пациент"] for с in строки):
        свои = [с for с in строки if с["пациент"] == имя]
        куски += [
            f"## {имя}, {свои[0]['возраст']} лет",
            "",
            f"**Прежний брак:** {свои[0]['прежний_брак']}",
            "",
        ]
        for температура in dict.fromkeys(с["температура"] for с in свои):
            куски += [f"### temperature = {температура}", ""]
            for с in (x for x in свои if x["температура"] == температура):
                пометка = f" — ФОРМА: {с['форма']}" if с["форма"] else ""
                куски.append(f"**{с['повтор']}.**{пометка}")
                куски.append("")
                куски.append(f"> {с['анамнез'] or '(не собрался)'}")
                if с.get("карточка"):
                    куски.append(">")
                    куски.append(f"> карточка: {с['карточка']}")
                куски.append("")

    куски += ["## Расход", "", "```json", json.dumps(счёт, ensure_ascii=False, indent=2), "```"]
    return "\n".join(куски)


async def main() -> None:
    разбор = argparse.ArgumentParser(description="Замер правдоподобия анамнезов")
    разбор.add_argument("--набор", default=_НАБОР, help="фикстура с личностями и клиникой")
    разбор.add_argument("--повторов", type=int, default=3,
                        help="прогонов на пациента и температуру (по умолчанию 3)")
    разбор.add_argument("--температуры", default="0.2,0.7",
                        help="через запятую (по умолчанию 0.2,0.7)")
    разбор.add_argument("--модель", default=None, help="по умолчанию — case_model из настроек")
    разбор.add_argument("--вывод", default=None, help="куда положить отчёт (иначе только stdout)")
    доводы = разбор.parse_args()

    with open(доводы.набор, encoding="utf-8") as файл:
        набор = json.load(файл)

    модель = доводы.модель or get_settings().case_model
    температуры = [float(t) for t in доводы.температуры.split(",")]
    всего = len(набор["patients"]) * len(температуры) * доводы.повторов
    print(f"Модель {модель}, вызовов {всего}. ПЛАТНО.", file=sys.stderr)

    with usage.учёт() as счёт:
        строки = await прогнать(набор, модель, температуры, доводы.повторов)

    текст = отчёт(строки, модель, счёт.как_словарь())
    # Печатаем всегда: результаты внутри контейнера переживают только
    # его самого, а деплой пересоздаёт контейнер вместе с файлами
    print(текст)
    if доводы.вывод:
        with open(доводы.вывод, "w", encoding="utf-8") as файл:
            файл.write(текст)
        print(f"Отчёт: {доводы.вывод}", file=sys.stderr)


if __name__ == "__main__":
    asyncio.run(main())
