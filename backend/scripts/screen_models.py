"""Сито моделей роли: быстрый отсев до полного замера.

Полный прогон разговора с оценщиком — минут двадцать на модель. Гонять так
десяток кандидатов бессмысленно, а выбирать по цене и задержке мы уже
пробовали: список 30.07 собирали именно так, и отыгрыш в нём не проверялся
вовсе — seed-2.0-mini оказалась быстрейшей и негодной одновременно.

Здесь четыре реплики, бьющие в то, что дисквалифицирует:

  1. приветствие         — заговорит ли модель от лица менеджера;
  2. открытый вопрос     — длина ответа, живость, русский;
  3. «что мне сказать»   — подскажет ли менеджеру решение (на этом
                           и отсеялась seed-2.0-mini);
  4. цена и закрытие     — согласится ли, когда условия не сняты.

ЧТО СЧИТАЕТСЯ, А ЧТО ЧИТАЕТСЯ ГЛАЗАМИ. Считаются только механические
признаки: задержка, разметка, скобки, своё имя в реплике, обороты
представления. Вердикт по русскому тексту скрипт не выносит — за сегодня
три моих регулярки подряд дали неверный ответ (счёт «есть что продать»
по ключевым словам, ремарки qwen в форме «*(…)*», обращения по имени
вперемешку с репликами менеджера). Поэтому ответы печатаются целиком.

Запуск внутри backend-контейнера на DE — потолок первого токена настроен
под тамошний сетевой путь:

    python scripts/screen_models.py <промпт.txt> <модель> [<модель> …]
"""

import asyncio
import json
import os
import re
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from services import llm  # noqa: E402

# Реплики подобраны так, чтобы каждая проверяла свой способ сломать роль
ПРОБЫ = [
    ("приветствие", "Здравствуйте! Иван, администратор клиники."),
    ("открытый вопрос", "Расскажите, что вас беспокоит?"),
    (
        "просьба подсказать",
        "А что мне нужно сказать, чтобы вы согласились? Прямо скажите, я сделаю.",
    ),
    (
        "цена и закрытие",
        "Стоимость — 45 000 рублей. Оформляем прямо сейчас?",
    ),
]

# Обороты, которыми модель выдаёт себя, заговорив за менеджера
_ЗА_МЕНЕДЖЕРА = ("меня зовут", "администратор", "нашей клиник", "мы предлагаем")

# Ручка размышления у каждого вендора своя, и одно значение на всех
# перекашивает замер. Проверено 31.07: у gpt-5.4-nano «enabled: false» даёт
# 898 мс, а «effort: minimal» — 539; у gemini наоборот, «effort: minimal»
# ломает ответ до шестнадцати символов; qwen на «enabled: false» отвечает
# HTTP-ошибкой вовсе. Первый замер кандидатов мерил не модели, а нашу
# конфигурацию, поэтому сито подбирает ручку само.
_РУЧКИ = [
    ("enabled=false", {"reasoning": {"enabled": False}}),
    ("effort=minimal", {"reasoning": {"effort": "minimal"}}),
    ("без параметра", {}),
]


async def подобрать_ручку(model: str, промпт: str) -> tuple[str, dict, float]:
    """Ищет настройку размышления с наименьшей задержкой первого токена."""
    лучшая = ("не подобрана", {}, float("inf"))
    for имя, доп in _РУЧКИ:
        проба = [{"role": "user", "text": ПРОБЫ[1][1]}]
        try:
            _, мс = await спросить(model, проба, промпт, доп)
        except Exception:  # noqa: BLE001
            continue
        if мс and мс < лучшая[2]:
            лучшая = (имя, доп, мс)
        await asyncio.sleep(0.3)
    return лучшая


async def спросить(
    model: str, история: list[dict], промпт: str, доп: dict | None = None
) -> tuple[str, float]:
    """Один ход. Возвращает (текст, задержка первого токена в мс)."""
    url, payload, headers = llm._build_request(история, промпт, stream=True)
    payload["model"] = model
    payload.pop("reasoning", None)
    payload.update(доп or {})
    начало = time.perf_counter()
    первый: float | None = None
    текст = ""
    async with llm._client.stream("POST", url, json=payload, headers=headers) as r:
        r.raise_for_status()
        async for line in r.aiter_lines():
            if not line.startswith("data:"):
                continue
            кусок = line[5:].strip()
            if not кусок or кусок == "[DONE]":
                continue
            try:
                chunk = json.loads(кусок)
            except ValueError:
                continue
            delta = ((chunk.get("choices") or [{}])[0].get("delta") or {}).get("content")
            if delta:
                if первый is None:
                    первый = (time.perf_counter() - начало) * 1000
                текст += delta
    return текст.strip(), (первый or 0.0)


async def просеять(model: str, промпт: str) -> dict:
    имя_ручки, ручка, _ = await подобрать_ручку(model, промпт)
    история: list[dict] = []
    ответы: list[tuple[str, str]] = []
    задержки: list[float] = []
    for метка, реплика in ПРОБЫ:
        история.append({"role": "user", "text": реплика})
        try:
            текст, мс = await спросить(model, история, промпт, ручка)
        except Exception as exc:  # noqa: BLE001
            ответы.append((метка, f"[ОШИБКА: {type(exc).__name__}]"))
            история.append({"role": "assistant", "text": ""})
            continue
        история.append({"role": "assistant", "text": текст})
        ответы.append((метка, текст))
        if текст:
            задержки.append(мс)
        await asyncio.sleep(0.4)

    весь = " ".join(t for _, t in ответы).lower()
    пустых = sum(1 for _, t in ответы if not t or t.startswith("[ОШИБКА"))
    return {
        "модель": model,
        "ручка": имя_ручки,
        "медиана мс": int(sorted(задержки)[len(задержки) // 2]) if задержки else 0,
        "пустых": пустых,
        "разметка": len(re.findall(r"[*_`#]", весь)),
        "скобки": len(re.findall(r"\(", весь)),
        "за менеджера": sum(1 for о in _ЗА_МЕНЕДЖЕРА if о in весь),
        "ответы": ответы,
    }


async def main() -> None:
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    промпт = open(sys.argv[1], encoding="utf-8").read()
    итоги = []
    for model in sys.argv[2:]:
        print(f"\n{'=' * 74}\n{model}")
        итог = await просеять(model, промпт)
        итоги.append(итог)
        for метка, текст in итог["ответы"]:
            print(f"\n  [{метка}]\n  {' '.join(текст.split())[:400] or '(пусто)'}")

    print(f"\n{'=' * 74}\nСВОДКА (вердикт по тексту — глазами, выше)\n")
    шапка = ("модель", "ручка", "мс", "пусто", "разм", "скоб", "за мен")
    print(f"{шапка[0]:34}{шапка[1]:16}{шапка[2]:>6}{шапка[3]:>7}{шапка[4]:>6}{шапка[5]:>6}{шапка[6]:>8}")
    for и in итоги:
        print(
            f"{и['модель']:34}{и['ручка']:16}{и['медиана мс']:>6}{и['пустых']:>7}"
            f"{и['разметка']:>6}{и['скобки']:>6}{и['за менеджера']:>8}"
        )


if __name__ == "__main__":
    asyncio.run(main())
