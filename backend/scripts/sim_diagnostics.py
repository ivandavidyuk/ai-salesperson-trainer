"""Прогон сценки диагностики: как роль живёт с показанным документом.

Проверяет три вещи, ради которых блок написан:
  * пациент ПРИЗНАЁТ поход на диагностику (не спорит «я никуда не ходила»
    со своим же промптом, где сказано «пришла пройти диагностику»);
  * НЕ ЗАЧИТЫВАЕТ цифры из документа — на прямой вопрос отвечает в духе
    «врач распечатку дал, вот, посмотрите»;
  * НЕ СДАЁТСЯ от испуга: предложение оплатить при невзятом пороге доверия
    по-прежнему получает отказ, каким бы тревожным ни был итог.

Запуск внутри backend-контейнера (потолок первого токена настроен под сетевой
путь DE, локально ложно срабатывает):

    python scripts/sim_diagnostics.py <промпт.txt> [сколько прогонов]
    python scripts/sim_diagnostics.py <промпт.txt> 8 --документ файл.txt

Документ по умолчанию — офтальмологический, под промпт Тамары. Метки рядом
с ответами — подсказка, а не вердикт: читать глазами.

ПЛАТНО: по четыре хода роли на прогон.
"""

import asyncio
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from core.config import get_settings  # noqa: E402
from services import llm  # noqa: E402

_TURN_PAUSE_SEC = 1.5

# История до сценки: контакт установлен, жалобы прозвучали. Дальше менеджер
# отыгрывает поход голосом — как и в бою, кнопке предшествует речь
ИСТОРИЯ = [
    ("user", "Тамара Михайловна, здравствуйте! Иван, администратор клиники."),
    ("assistant", "Здравствуйте, Иван."),
    ("user", "Расскажите, что вас беспокоит со зрением?"),
    (
        "assistant",
        "Последние лет пять хуже стало. И вдаль, и вблизи. Вблизи в очках "
        "вообще не вижу — снимаю и подношу к самому носу.",
    ),
    (
        "user",
        "Понял вас. Давайте так: сейчас вас проводят на диагностику, это "
        "минут сорок, а потом мы с вами всё обсудим по результатам. Хорошо?",
    ),
    ("assistant", "Хорошо, давайте."),
    (
        "user",
        "Тамара Михайловна, с возвращением, присаживайтесь. Результаты "
        "уже у меня.",
    ),
]

ДОКУМЕНТ = (
    "Тамара Михайловна\n"
    "Объект исследования: правый и левый глаз.\n"
    "Способ исследования: визометрия, авторефрактометрия, тонометрия.\n"
    "Показатели исследования:\n"
    "Острота зрения: OD 0,3 (было 0,4), OS 0,2 (было 0,3) — норма 1,0.\n"
    "Рефракция: OD −5,75 дптр (было −5,25), OS −4,5 дптр — норма 0.\n"
    "ВГД: 19 и 19 мм рт. ст. — норма до 21, ближе к границе."
)

# Сцена после показа. Метка — что проверяем этим ходом
СЦЕНА = [
    (
        "признаёт поход",
        "Ну как вы, не устали от обследования?",
    ),
    (
        "не зачитывает цифры",
        "Вам врач по результатам что-нибудь говорил?",
    ),
    (
        "реакция на итог",
        "Смотрите, по результатам зрение действительно просело с прошлого "
        "раза, и заметно. Это как раз то, о чём вы говорили — и вблизи, "
        "и вдаль.",
    ),
    (
        "не сдаётся от испуга",
        "Поэтому тянуть я бы не стал. Давайте оформим замену хрусталика "
        "и оплатим сегодня, время на завтра как раз есть?",
    ),
]

# Цифры и единицы из документа: их появление в репликах — повод насторожиться
_ЦИФРЫ = re.compile(r"0,[23]\b|−?5,75|−?4,5\b|дптр|мм рт|ВГД|OD\b|OS\b")


async def _reply(history: list[dict], prompt: str) -> str:
    chunks: list[str] = []
    async for delta in llm.stream_reply(history, prompt):
        chunks.append(delta)
    return "".join(chunks).strip()


async def main() -> None:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if not args:
        print(__doc__)
        sys.exit(1)
    prompt_path = args[0]
    runs = int(args[1]) if len(args) > 1 else 4

    документ = ДОКУМЕНТ
    if "--документ" in sys.argv:
        with open(sys.argv[sys.argv.index("--документ") + 1], encoding="utf-8") as fh:
            документ = fh.read()

    with open(prompt_path, encoding="utf-8") as fh:
        role = fh.read()

    # Порог доверия НЕ взят намеренно: последний ход сцены проверяет,
    # что испуг от ухудшения не подменяет собой снятые страхи
    prompt = (
        f"{role}\n\n{llm.trust_instruction(False)}\n\n"
        f"{llm.diagnostics_instruction(документ)}"
    )

    print(f"промпт: {len(role)} символов — {prompt_path}")
    print(f"модель: {get_settings().llm_model}")
    print(f"прогонов: {runs}\n")

    for run in range(1, runs + 1):
        print(f"{'=' * 74}\nПРОГОН {run}")
        history = [{"role": r, "text": t} for r, t in ИСТОРИЯ]
        for метка, line in СЦЕНА:
            history.append({"role": "user", "text": line})
            reply = await _reply(history, prompt)
            history.append({"role": "assistant", "text": reply})

            подсказки = []
            if _ЦИФРЫ.search(reply):
                подсказки.append("!! похоже, зачитывает цифры из документа")
            if метка == "не сдаётся от испуга" and re.search(
                r"давайте оформ|согласна|оформляйте", reply.lower()
            ):
                подсказки.append("!! похоже, согласилась при невзятом пороге")
            tail = ("  ← " + ", ".join(подсказки)) if подсказки else ""

            print(f"\n  [{метка}]\n  М: {line}")
            print(f"  Т: {reply or '(пусто)'}{tail}")
            await asyncio.sleep(_TURN_PAUSE_SEC)
        print()


if __name__ == "__main__":
    asyncio.run(main())
