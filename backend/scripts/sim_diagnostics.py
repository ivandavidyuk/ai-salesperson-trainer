"""Прогон сценки диагностики: как роль живёт с показанным документом.

Проверяет три вещи, ради которых блок написан:
  * пациент ПРИЗНАЁТ поход на диагностику (не спорит «я никуда не ходила»
    со своим же промптом, где сказано «пришла пройти диагностику»);
  * НЕ ЗАЧИТЫВАЕТ цифры из документа — на прямой вопрос отвечает в духе
    «врач распечатку дал, вот, посмотрите»;
  * НЕ СДАЁТСЯ от испуга: предложение оплатить при невзятом пороге доверия
    по-прежнему получает отказ, каким бы тревожным ни был итог.

Запуск внутри backend-контейнера (потолок первого токена настроен под сетевой
путь DE, локально ложно срабатывает):

    python scripts/sim_diagnostics.py <промпт.txt> --документ файл.txt
    python scripts/sim_diagnostics.py <промпт.txt> 8 --документ файл.txt \
        --отрасль стоматология

`--документ` ОБЯЗАТЕЛЕН. Раньше здесь лежал офтальмологический документ
по умолчанию, и стоматологический промпт молча прогонялся против чужого
заключения: сценка выглядела осмысленной, а проверяла бессмыслицу.

Метки рядом с ответами — подсказка, а не вердикт: читать глазами.

ПЛАТНО: по четыре хода роли на прогон.
"""

