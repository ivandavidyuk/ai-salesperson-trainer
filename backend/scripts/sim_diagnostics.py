def собрать_сцену(отрасль: dict) -> list[tuple[str, str]]:
    """Четыре хода после показа документа. Метка — что проверяем."""
    return [
        ("признаёт поход", "Ну как вы, не устали от обследования?"),
        ("не зачитывает цифры", "Вам врач по результатам что-нибудь говорил?"),
        (
            "реакция на итог",
            f"Смотрите, по результатам {отрасль['просело']}. Это как раз то, "
            f"о чём вы говорили.",
        ),
        (
            "не сдаётся от испуга",
            f"Поэтому тянуть я бы не стал. Давайте оформим {отрасль['услуга']} "
            f"и оплатим сегодня, время как раз есть?",
        ),
    ]


def следы_документа(документ: str) -> re.Pattern:
    """Регулярка «цифры из ЭТОГО документа», собранная из него самого.

    Раньше здесь стояла константа под числа Тамары. На стоматологическом
    документе (проценты, индексы, номера зубов) она не находила ничего —
    и метка «зачитывает цифры» не поднималась НИКОГДА. Прибор показывал
    «норма» при отключённом датчике, а по нему собирались проверять 42
    документа.
    """
    токены: set[str] = set()
    # Дробные числа — самый верный след: 0,3 / 5,75 / 1,5
    токены.update(re.findall(r"\d+[,.]\d+", документ))
    # Целые от двух цифр: 18 мм рт. ст., зуб 36, 28%. Однозначные не берём —
    # «два» и «пять» звучат в обычной речи и дали бы ложные срабатывания
    токены.update(re.findall(r"\b\d{2,}\b", документ))
    # Аббревиатуры: OD, OS, ВГД, КЛКТ, OHI-S. Два и больше заглавных подряд —
    # обычное слово с большой буквы под это не подходит
    токены.update(re.findall(r"\b[A-ZА-ЯЁ]{2,}(?:-[A-ZА-ЯЁ]+)?\b", документ))
    # Единицы измерения — их произносят вслух вместе с числом
    for единица in ("дптр", "мм рт", "мкА", "мм", "мкм", "%"):
        if единица in документ:
            токены.add(единица)

    if not токены:
        # Документ без единого числа — такого быть не должно, но пусть
        # сторож молчит явно, а не совпадает со всем подряд
        return re.compile(r"(?!x)x")

    # Длинные первыми: «5,75» должно ловиться раньше, чем «75»
    по_длине = sorted(токены, key=len, reverse=True)
    return re.compile("|".join(re.escape(т) for т in по_длине))


async def _reply(history: list[dict], prompt: str) -> str:
    chunks: list[str] = []
    async for delta in llm.stream_reply(history, prompt):
        chunks.append(delta)
    return "".join(chunks).strip()


def _флаг(имя: str) -> str | None:
    if имя not in sys.argv:
        return None
    i = sys.argv.index(имя)
    return sys.argv[i + 1] if i + 1 < len(sys.argv) else None


async def main() -> None:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    путь_документа = _флаг("--документ")
    if not args or not путь_документа:
        print(__doc__)
        sys.exit(1)

    # Позиционные: первый — промпт, второй — число прогонов. Значения флагов
    # тоже попадают в args, поэтому число берём только если оно и правда число
    prompt_path = args[0]
    runs = 4
    for a in args[1:]:
        if a.isdigit():
            runs = int(a)
            break

    имя_отрасли = _флаг("--отрасль") or "офтальмология"
    if имя_отрасли not in ОТРАСЛИ:
        print(f"неизвестная отрасль: {имя_отрасли}. Есть: {', '.join(ОТРАСЛИ)}")
        sys.exit(1)
    отрасль = ОТРАСЛИ[имя_отрасли]

    with open(путь_документа, encoding="utf-8") as fh:
        документ = fh.read()
    with open(prompt_path, encoding="utf-8") as fh:
        role = fh.read()

    цифры = следы_документа(документ)
    сцена = собрать_сцену(отрасль)

    # Порог доверия НЕ взят намеренно: последний ход сцены проверяет,
    # что испуг от ухудшения не подменяет собой снятые страхи
    prompt = (
        f"{role}\n\n{llm.trust_instruction(False)}\n\n"
        f"{llm.diagnostics_instruction(документ)}"
    )

    print(f"промпт: {len(role)} символов — {prompt_path}")
    print(f"документ: {len(документ)} символов — {путь_документа}")
    print(f"отрасль: {имя_отрасли}")
    print(f"модель: {get_settings().llm_model}")
    print(f"прогонов: {runs}\n")

    for run in range(1, runs + 1):
        print(f"{'=' * 74}\nПРОГОН {run}")
        history = [{"role": r, "text": t} for r, t in отрасль["история"]]
        for метка, line in сцена:
            history.append({"role": "user", "text": line})
            reply = await _reply(history, prompt)
            history.append({"role": "assistant", "text": reply})

            подсказки = []
            найдено = цифры.findall(reply)
            if найдено:
                подсказки.append(
                    "!! похоже, зачитывает из документа: "
                    + ", ".join(sorted(set(найдено))[:4])
                )
            if метка == "не сдаётся от испуга" and re.search(
                r"давайте оформ|согласна|согласен|оформляйте", reply.lower()
            ):
                подсказки.append("!! похоже, согласился при невзятом пороге")
            tail = ("  ← " + ", ".join(подсказки)) if подсказки else ""

            print(f"\n  [{метка}]\n  М: {line}")
            print(f"  Т: {reply or '(пусто)'}{tail}")
            await asyncio.sleep(_TURN_PAUSE_SEC)
        print()


if __name__ == "__main__":
    asyncio.run(main())
