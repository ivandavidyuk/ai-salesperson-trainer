"""Настройки сервиса, читаются из переменных окружения (.env).

Используется pydantic-settings: имена полей сопоставляются с переменными
окружения без учёта регистра (например, LLM_API_KEY -> llm_api_key).
"""

from functools import lru_cache

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    # Файл .env берётся из текущей рабочей директории (папка backend)
    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        extra="ignore",
    )

    # LLM — любой OpenAI-совместимый провайдер (сейчас OpenRouter)
    llm_api_key: str = ""
    llm_base_url: str = "https://openrouter.ai/api/v1"
    # Роль — единственная модель на горячем пути: её сбой менеджер слышит
    # как тишину.
    #
    # ПЕРЕЕЗД 31.07.2026 с gemini-2.5-flash-lite. Прежний выбор держался
    # на медиане (435 мс), но обрывает ход не медиана, а хвост: у 2.5
    # максимум 3124 мс при потолке в 2 с, и два хода из четырнадцати
    # срывались. Плюс пустые ответы — HTTP 200, finish_reason=stop, ноль
    # символов — от двух до пяти на десять ходов.
    #
    # Замер 31.07 (backend-контейнер на DE, payload как в бою):
    #
    #   модель                   медиана   макс   ремарок за разговор
    #   gemini-3.5-flash-lite      430      876    0
    #   gemini-2.5-flash-lite      409     3124    12-15
    #   claude-haiku-4.5           997     2018    14 строк
    #
    # Прежний комментарий утверждал, что 3.5 для роли непригодна: «Reasoning
    # is mandatory» и первый токен дольше 10 с. Это мерили НЕ ТОЙ РУЧКОЙ —
    # у неё работает effort: minimal, а не enabled: false. См. reasoning_for
    # в services/llm.py: одно значение на всех перекашивает любой замер.
    #
    # И 2.5 всё равно отключают 16 октября 2026.
    llm_model: str = "google/gemini-3.5-flash-lite"

    # Модель второго захода, если основная не ответила. Другой вендор —
    # в этом весь смысл: отказ у Google приходит штормами, и повтор той же
    # моделью попадает в тот же шторм.
    #
    # Замер 31.07.2026: у роли пропадало от двух до пяти ходов из десяти,
    # причём HTTP 200, finish_reason=stop и ноль символов — «модель молчит
    # по своей воле». Резерв на маршрутизации OpenRouter такое не ловит:
    # для него это успешный ответ, переключаться не на что. Значит ловим сами.
    #
    # Haiku выбрана по хвосту, а не по медиане: она вдвое медленнее в среднем
    # (997 против 409 мс), но её максимум 2018 мс против 3124 у Gemini,
    # а обрывает ход именно хвост. Плюс шесть независимых провайдеров.
    #
    # Пустая строка отключает резерв: тогда второй заход идёт той же моделью,
    # как было раньше.
    fallback_model: str = "anthropic/claude-haiku-4.5"

    # Оценщик разговора — отдельная модель от роли. Требования обратные:
    # роли важна задержка (у неё размышление выключено), оценщику —
    # устойчивость суждения, а ждать его никто не ждёт: он вне критического
    # пути. Отдельная переменная позволяет менять его, не трогая пайплайн.
    #
    # ФОНОВЫЙ оценщик — ходит после каждого хода, ~16–20 раз за разговор,
    # ПАРАЛЛЕЛЬНО живому разговору. Отсюда два требования: дёшево и, главное,
    # мимо очереди роли. Пока обе стояли на google/gemini-2.5-flash-lite,
    # половина его запросов получала «429 temporarily rate-limited upstream»,
    # а задержка разговора выросла с 480–1500 мс до 5–7 с на пиках.
    # Вендор поэтому берём другой: лимит у OpenRouter считается по конкретной
    # модели вышестоящего, и соседняя модель того же Google развела бы хуже.
    scorer_model: str = "openai/gpt-4o-mini"

    # ИТОГОВЫЙ оценщик — один вызов, и он происходит ПОСЛЕ конца разговора.
    # Конкурировать с ролью он не может по определению, поэтому запрет
    # на вендора роли сюда не распространяется, а экономить на единственном
    # запросе бессмысленно: его вердикт попадает в базу навсегда.
    #
    # Выбран замером на семи живых расшифровках (27.07.2026, два прогона
    # на каждую). Устойчивость исхода: gemini-3.5-flash-lite 7/7,
    # gpt-4o-mini 7/7, gpt-5.6-luna 6/7, claude-haiku-4.5 4/7. При равной
    # устойчивости gemini быстрее (1.1–1.9 с) и пишет разбор по обязательным
    # условиям пациента, а не общими словами — а judgeNotes нужны нам
    # для сверки вердиктов роли и оценщика.
    final_scorer_model: str = "google/gemini-3.5-flash-lite"

    # ГЕНЕРАТОР СЛУЧАЯ — придумывает, с чем пациент пришёл в эту клинику,
    # по её отрасли и прайсу. Запускается при сохранении формы, вне разговора,
    # поэтому задержка не важна вовсе.
    #
    # Выбрана замером 30.07.2026: шесть моделей от $3 до $210 за сотню клиник,
    # два прогона, стоматологический случай на личности Тамары. По содержанию
    # дешёвая не уступила флагману ни в чём — ни одной выдуманной цены,
    # возражения выведены из страхов личности, словарь корректен. Отличалась
    # только стабильность формата, а это лечится схемой ответа и повтором,
    # которые здесь и стоят.
    #
    # Платить в 23 раза больше за неразличимое по нашим критериям качество
    # незачем: 100 пациентов на клинику это ~$0.09 против ~$2.10 у Sonnet.
    #
    # ПЕРЕСМОТРЕНО 31.07.2026: 2.5-flash-lite не годится не по качеству,
    # а по доступности. Она отдаёт 429 («rate-limited upstream» — Google душит
    # общий пул OpenRouter) пачками, и сборка двадцати одного случая
    # растягивалась на час с лишним против 2.5 минут у 3.5-flash-lite.
    # На той же нагрузке: 7.5 секунды на пациента против нескольких минут
    # ожидания в повторах.
    #
    # Разница в цене — ~$0.47 против ~$0.09 за сотню пациентов, то есть
    # тридцать восемь центов на клинику. Сборка идёт один раз при заполнении
    # формы, а руководитель ждёт её с лоадером: час ожидания дороже.
    #
    # Роль остаётся на 2.5-flash-lite: там решает задержка первого токена,
    # и конкуренции за квоту нет — генерация идёт, когда никто не разговаривает.
    case_model: str = "google/gemini-3.5-flash-lite"

    # Клиническая картина и подбор услуги под неё. Отдельная настройка,
    # потому что это единственное место, где имеет смысл платить за лучшую
    # модель: шаг выполняется РАЗ НА ПАЦИЕНТА при заведении клиники, а не
    # в разговоре. Двадцать один пациент — двадцать один вызов, и даже
    # на модели верхнего класса это около $2.50 на клинику разово против
    # $1.89 за час разговора.
    #
    # Цена ошибки здесь несоразмерна экономии: 06.08 врач забраковал сборку
    # целиком за диагнозы, которых не бывает.
    clinical_model: str = "google/gemini-3.5-flash-lite"

    # Порог допуска к согласию: средняя по первым четырём этапам.
    # Регулятор сложности — ниже ближе к жизни, выше строже к технике
    deal_score_threshold: float = 7.0

    # ElevenLabs — STT (Realtime) и TTS
    elevenlabs_api_key: str = ""
    elevenlabs_voice_id: str = ""
    # eleven_flash_v2_5 — минимальная задержка; eleven_v3 — эмоции и audio-теги
    elevenlabs_tts_model: str = "eleven_flash_v2_5"
    elevenlabs_stt_model: str = "scribe_v2_realtime"

    # Barge-in: менеджер может перебить ИИ голосом — воспроизведение
    # обрывается. Рубильник на случай ложных срабатываний от эха на проде.
    barge_in_enabled: bool = True

    # Инфраструктура (те же значения, что и в Next.js приложении)
    database_url: str = ""
    redis_url: str = ""
    jwt_secret: str = ""

    @property
    def asyncpg_dsn(self) -> str:
        """DSN для asyncpg.

        Prisma добавляет в строку параметр ?schema=public, который asyncpg
        не понимает, поэтому отбрасываем query-часть.
        """
        return self.database_url.split("?", 1)[0]


@lru_cache
def get_settings() -> Settings:
    """Возвращает единственный экземпляр настроек (кешируется)."""
    return Settings()
