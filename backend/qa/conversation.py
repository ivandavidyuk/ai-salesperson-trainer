"""Один разговор матрицы: пациент × тип тренировки.

Работает боевым кодом — `llm.stream_reply`, `llm.build_system_prompt`,
`scoring.review_conversation`. Своих копий здесь нет и быть не должно:
31.07 симулятор со своей склейкой истории месяц врал про модели, и цена
этого была день работы.

Отдельная забота — сбои. Сейчас в проекте всё наоборот: `lib/cases.ts:57`
выбрасывает и статус, и тело ответа, и причину отказа я узнавал, дёргая
бэкенд руками. Здесь сохраняется всё, вплоть до готовой команды для повтора
одной клетки.
"""

import asyncio
import logging
import time
from dataclasses import asdict, dataclass, field
from typing import Optional

from services import llm, scoring

from qa.store import Клиника, Пациент, ТипТренировки

# Сколько ходов играет модель-менеджер. Одиннадцать — длина наших сценариев;
# двадцать нужны там, где критерий накопительный («пять возражений подряд»):
# на коротком разговоре он не набирается из-за обрыва, а не из-за менеджера
_ХОДОВ_ПО_УМОЛЧАНИЮ = 11
_ХОДОВ_НАКОПИТЕЛЬНЫМ = 20
_НАКОПИТЕЛЬНЫЕ = {"s4", "intercept"}

# Прогон терпеливее боя: там потерянный ход — событие, которое надо видеть,
# здесь он только портит замер поведения
_ПОПЫТОК = 4
_ПАУЗА_ПОВТОРА = 3.0
# Пауза между ходами: симулятор бьёт по API вплотную и сам себе устраивает 429
_ПАУЗА_ХОДА = 1.5


@dataclass
class Ход:
    номер: int
    менеджер: str
    пациент: str
    # Время до первой дельты. Именно оно упирается в потолок 2 с в бою,
    # и именно оно решает, услышит ли менеджер паузу
    первый_токен_мс: Optional[int] = None
    весь_ответ_мс: Optional[int] = None
    # Предупреждения services.llm, пойманные за этот ход: уход к резерву,
    # пустой ответ, отказ провайдера. Раньше они тонули в общем логе
    предупреждения: list[str] = field(default_factory=list)


@dataclass
class Сбой:
    ход: int
    тип: str
    сообщение: str
    предупреждения: list[str] = field(default_factory=list)


@dataclass
class Разговор:
    пациент: str
    тип: str
    сценарий: Optional[str]
    ходы: list[Ход] = field(default_factory=list)
    сбои: list[Сбой] = field(default_factory=list)
    # Итог боевого разбора: у полного разговора исход сделки, у тренировки
    # «этап отработан или нет». None — разбор не вернулся
    разбор: Optional[dict] = None
    длительность_с: float = 0.0
    команда_повтора: str = ""

    def история(self) -> list[dict]:
        """Расшифровка в том же виде, в каком её видит боевой оценщик."""
        история: list[dict] = []
        for ход in self.ходы:
            история.append({"role": "user", "text": ход.менеджер})
            история.append({"role": "assistant", "text": ход.пациент})
        return история

    def as_dict(self) -> dict:
        return asdict(self)


class ЛовецЛогов(logging.Handler):
    """Складывает предупреждения services.llm в текущий ход.

    Иначе информация о сбое остаётся только в общем логе контейнера, где
    её не связать с конкретной клеткой матрицы. А это ровно то, ради чего
    инструмент и затевался: при ошибке — максимум подробностей.
    """

    def __init__(self) -> None:
        super().__init__(level=logging.WARNING)
        self.записи: list[str] = []

    def emit(self, record: logging.LogRecord) -> None:
        self.записи.append(record.getMessage())

    def забрать(self) -> list[str]:
        собранное, self.записи = self.записи, []
        return собранное


def ходов_для(тип: ТипТренировки) -> int:
    """Длина прогона: накопительным критериям одиннадцати ходов мало.

    Замерено 04.08: «пять возражений подряд» на одиннадцати ходах брал один
    пациент из трёх, на двадцати — все три. Критерий был в порядке, коротка
    была мерка.
    """
    return _ХОДОВ_НАКОПИТЕЛЬНЫМ if тип.слаг in _НАКОПИТЕЛЬНЫЕ else _ХОДОВ_ПО_УМОЛЧАНИЮ


def промпт_менеджера(
    тип: ТипТренировки,
    клиника: Optional[Клиника] = None,
    пациент: Optional[Пациент] = None,
) -> str:
    """Роль менеджера: ровно то, что видит живой менеджер, и ничего сверх.

    Видит он три вещи: карточку упражнения, прайс своей клиники и анамнез
    пациента на экране звонка. Всё это отдаём.

    Чего не видит и не увидит здесь: промпт роли. Там условия согласия,
    и менеджер, прочитавший их, проверял бы не навык, а умение прочитать
    ответы — ровно то, на что жаловался врач, когда пациенты сами
    проговаривали свой подход. Рубрику и критерий не даём по той же причине.

    Поводом стал разбор 10.08: без прайса симулятор выдумывал услугу
    и продавал Виталию лазерную коррекцию за 45 000, тогда как в его случае
    подбор очков от 3 500. Снять страх «как линзы выдержат пыль на стройке»
    было нечем в принципе, и отказ означал не строгость пациента, а то,
    что разговаривали о разном.
    """
    середина = (
        "Разговор идёт с середины: знакомство и рассказ о проблеме уже позади. "
        "Не здоровайся и не начинай сначала — продолжай с того, что говорит "
        "пациент. Оформлять и записывать сегодня не нужно.\n\n"
        if not тип.считает_сделку
        else ""
    )
    где = (
        f"Ты — менеджер клиники «{клиника.название}», {клиника.отрасль}.\n\n"
        f"Услуги и цены, которые ты знаешь наизусть:\n{клиника.прайс()}\n\n"
        "Называй только эти услуги и эти цены. Ничего не выдумывай: если "
        "нужного нет в списке, так и скажи.\n\n"
        if клиника and клиника.услуги
        else "Ты — менеджер по продажам в частной клинике.\n\n"
    )

    карточка = ""
    if пациент and (пациент.анамнез or пациент.карточка):
        строки = [f"Перед тобой карточка пациента — {пациент.имя}"]
        if пациент.карточка:
            строки.append(пациент.карточка)
        if пациент.анамнез:
            строки.append(f"Анамнез: {пациент.анамнез}")
        карточка = "\n".join(строки) + "\n\n"

    return (
        f"{где}"
        f"{карточка}"
        f"Сейчас ты отрабатываешь навык: {тип.описание}\n\n"
        f"{середина}"
        "Говори как живой человек: коротко, одна мысль за реплику, без "
        "списков и заголовков. Отвечай на то, что пациент сказал прямо "
        "сейчас, а не по заготовленному плану.\n\n"
        "Если пациент задал прямой вопрос — отвечай на него, а не рядом. "
        "Не знаешь ответа — так и скажи, но не переводи тему: человек, "
        "которому не отвечают, спрашивает снова и перестаёт доверять.\n\n"
        "В ответе — только твоя реплика, без пояснений и без кавычек."
    )


async def _ответ(history: list[dict], prompt: str) -> tuple[str, int, int]:
    """Ответ модели с замером времени до первого токена.

    Возвращает (текст, мс до первой дельты, мс на весь ответ). Потолок
    первого токена внутри stream_reply не трогаем — он и есть предмет замера.
    """
    for попытка in range(1, _ПОПЫТОК + 1):
        начало = time.monotonic()
        первый: Optional[float] = None
        куски: list[str] = []
        try:
            async for дельта in llm.stream_reply(history, prompt):
                if первый is None:
                    первый = time.monotonic()
                куски.append(дельта)
        except Exception:
            if попытка == _ПОПЫТОК:
                raise
            await asyncio.sleep(_ПАУЗА_ПОВТОРА)
            continue

        текст = "".join(куски).strip()
        if текст:
            конец = time.monotonic()
            до_первого = int(((первый or конец) - начало) * 1000)
            return текст, до_первого, int((конец - начало) * 1000)
        if попытка == _ПОПЫТОК:
            return "", 0, 0
        await asyncio.sleep(_ПАУЗА_ПОВТОРА)
    return "", 0, 0


async def _реплика_менеджера(история: list[dict], промпт: str) -> str:
    """Ход менеджера-модели. Роли переворачиваются: для него пациент — user."""
    зеркало = [
        {"role": "assistant" if item["role"] == "user" else "user", "text": item["text"]}
        for item in история
    ]
    if not зеркало:
        зеркало = [{"role": "user", "text": "(пациент молча ждёт, начни разговор)"}]
    текст, _, _ = await _ответ(зеркало, промпт)
    return текст


async def провести(
    пациент: Пациент,
    тип: ТипТренировки,
    реплики: Optional[list[str]] = None,
    сценарий: Optional[str] = None,
    клиника: Optional[Клиника] = None,
) -> Разговор:
    """Проводит один разговор и собирает по нему всё, что можно собрать.

    `реплики` — готовый сценарий менеджера. Если их нет, менеджера играет
    модель: там, где разговор ведёт пациент, заготовленные реплики отвечают
    по своему плану и промахиваются мимо заданного вопроса.
    """
    разговор = Разговор(
        пациент=пациент.слаг,
        тип=тип.слаг,
        сценарий=сценарий,
        команда_повтора=(
            f"python -m qa.run --patients {пациент.слаг} --types {тип.слаг}"
        ),
    )

    # Склейка ровно как в бою (services/session.py): роль, потом блок этапа
    роль = llm.build_system_prompt(пациент.промпт, тип.промпт)
    менеджер_модель = реплики is None
    роль_менеджера = (
        промпт_менеджера(тип, клиника, пациент) if менеджер_модель else ""
    )
    всего = len(реплики) if реплики else ходов_для(тип)

    ловец = ЛовецЛогов()
    логгер = logging.getLogger("services.llm")
    логгер.addHandler(ловец)
    начало = time.monotonic()

    try:
        for номер in range(1, всего + 1):
            ловец.забрать()  # чужие записи предыдущего хода нам не нужны

            if менеджер_модель:
                try:
                    строка = await _реплика_менеджера(разговор.история(), роль_менеджера)
                except Exception as exc:  # noqa: BLE001
                    разговор.сбои.append(
                        Сбой(
                            ход=номер,
                            тип=f"менеджер:{type(exc).__name__}",
                            сообщение=str(exc)[:500],
                            предупреждения=ловец.забрать(),
                        )
                    )
                    continue
                if not строка:
                    разговор.сбои.append(
                        Сбой(ход=номер, тип="менеджер:пусто", сообщение="",
                             предупреждения=ловец.забрать())
                    )
                    continue
            else:
                строка = реплики[номер - 1]

            история = разговор.история()
            # Реплика менеджера уходит в историю ДО запроса — как в TurnManager
            # (main.py). Иначе роль отвечает на предыдущий ход, а история
            # заканчивается сообщением ассистента: чередование нарушено
            история.append({"role": "user", "text": строка})

            try:
                ответ, первый_мс, весь_мс = await _ответ(история, роль)
            except Exception as exc:  # noqa: BLE001
                разговор.сбои.append(
                    Сбой(
                        ход=номер,
                        тип=f"роль:{type(exc).__name__}",
                        сообщение=str(exc)[:500],
                        предупреждения=ловец.забрать(),
                    )
                )
                continue

            предупреждения = ловец.забрать()
            if not ответ:
                разговор.сбои.append(
                    Сбой(ход=номер, тип="роль:пусто", сообщение="",
                         предупреждения=предупреждения)
                )
                continue

            разговор.ходы.append(
                Ход(
                    номер=номер,
                    менеджер=строка,
                    пациент=ответ,
                    первый_токен_мс=первый_мс,
                    весь_ответ_мс=весь_мс,
                    предупреждения=предупреждения,
                )
            )
            await asyncio.sleep(_ПАУЗА_ХОДА)

        # Боевой разбор — тот же, что получит менеджер после живого разговора
        if разговор.ходы:
            try:
                итог = await scoring.review_conversation(
                    разговор.история(),
                    роль,
                    rubric=тип.рубрика,
                    done_when=тип.критерий,
                    scores_deal=тип.считает_сделку,
                    stage_key=тип.ключ_этапа,
                )
                if итог is not None:
                    разговор.разбор = {
                        "исход": итог.outcome,
                        "этап_отработан": итог.drill_passed,
                        "общая": итог.overall,
                        "этапы": итог.stages.as_dict(),
                        "закрытие": итог.closing,
                        "сильная_сторона": итог.strength,
                        "точка_роста": итог.growth_point,
                        "разбор_для_нас": итог.judge_notes,
                    }
            except Exception as exc:  # noqa: BLE001
                разговор.сбои.append(
                    Сбой(ход=0, тип=f"разбор:{type(exc).__name__}",
                         сообщение=str(exc)[:500])
                )
    finally:
        логгер.removeHandler(ловец)
        разговор.длительность_с = round(time.monotonic() - начало, 1)

    return разговор
