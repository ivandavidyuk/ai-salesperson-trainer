def _итог_разбора(результат: dict) -> str:
    разбор = (результат.get("разговор") or {}).get("разбор")
    if not разбор:
        return "—"
    if разбор.get("исход"):
        return f"{разбор['исход']} {разбор.get('общая', '')}"
    отработан = разбор.get("этап_отработан")
    метка = "этап взят" if отработан else "этап не взят"
    return f"{метка} {разбор.get('общая', '')}"


def сводка(каталог: Path) -> str:
    """summary.md: таблица клеток, поводы посмотреть и что просело."""
    результаты = загрузить_прогон(каталог)
    мета = json.loads((каталог / "run.json").read_text(encoding="utf-8"))

    строки = [
        f"# Прогон {каталог.name}",
        "",
        f"Клеток: {len(результаты)} · роль `{мета.get('модель_роли')}` · "
        f"читатель `{мета.get('модель_читателя')}` · код `{мета.get('git', '?')[:8]}`",
        "",
        "Инструмент **докладывает, а не судит**. «Посмотреть» — это повод",
        "открыть расшифровку, а не приговор.",
        "",
    ]

    if мета.get("замечания"):
        строки += ["## Замечания к данным", ""]
        строки += [f"- {з}" for з in мета["замечания"]] + [""]

    медиана = медиана_прогона(результаты)
    тревожные = [(r, поводы_посмотреть(r, медиана)) for r in результаты]
    смотреть = [(r, п) for r, п in тревожные if п]

    строки += [
        f"## Посмотреть: {len(смотреть)} из {len(результаты)}",
        "",
    ]
    if медиана is None:
        строки += [
            "_Клеток мало — многословность не проверялась: сравнивать не с чем._",
            "",
        ]
    else:
        # Выброс ловится сравнением с соседями, а поголовная многословность
        # так не ловится по определению: если длинны все, никто не выбивается.
        # Поэтому разброс печатается всегда — пусть его видит человек
        длины = _длины(результаты)
        строки += [
            f"_Длина реплики по прогону: медиана {медиана} зн. "
            f"({round(медиана / 15, 1)} с), от {длины[0]} до {длины[-1]}. "
            "Выброс ловится сравнением с соседями — если длинны все, "
            "поводов не будет, и смотреть надо на этот разброс._",
            "",
        ]
    if смотреть:
        строки += ["| Пациент | Тип | Поводы | Разбор |", "|---|---|---|---|"]
        for результат, поводы in смотреть:
            р = результат["разговор"]
            строки.append(
                f"| {р['пациент']} | {р['тип']} | {', '.join(поводы)} "
                f"| {_итог_разбора(результат)} |"
            )
    else:
        строки.append("Поводов посмотреть нет.")
    строки.append("")

    строки += ["## Все клетки", "", "| Пациент | Тип | Реплики | Разбор |", "|---|---|---|---|"]
    for результат in результаты:
        р = результат["разговор"]
        строки.append(
            f"| {р['пациент']} | {р['тип']} | {_строка_метрик(результат)} "
            f"| {_итог_разбора(результат)} |"
        )

    return "\n".join(строки) + "\n"


def _метрики_по_клеткам(результаты: Iterable[dict]) -> dict[str, dict]:
    return {_клетка(р): (р.get("метрики") or {}) for р in результаты}


def сравнить(новый: Path, старый: Path) -> str:
    """Что изменилось. Клетки, которых нет в новом прогоне, — «не гонялись».

    Иначе перегон двух пациентов выглядел бы как обвал по остальным
    девятнадцати, и сравнение стало бы бесполезным ровно в том сценарии,
    ради которого затевалось.
    """
    новые = _метрики_по_клеткам(загрузить_прогон(новый))
    старые = _метрики_по_клеткам(загрузить_прогон(старый))

    интересные = ("немых_ходов", "ходов_с_ремаркой", "повторов", "знаков_медиана",
                  "секунд_максимум", "ходов_с_латиницей", "ходов_с_чужим_именем")

    строки = [
        f"# Сравнение: {новый.name} против {старый.name}",
        "",
        f"В новом прогоне {len(новые)} клеток, в старом {len(старые)}. "
        f"Не гонялось в новом: {len(set(старые) - set(новые))}.",
        "",
        "| Клетка | Что | Было | Стало |",
        "|---|---|---|---|",
    ]

    изменений = 0
    for клетка in sorted(новые):
        если_было = старые.get(клетка)
        if если_было is None:
            строки.append(f"| {клетка} | новая клетка | — | — |")
            изменений += 1
            continue
        for ключ in интересные:
            было, стало = если_было.get(ключ), новые[клетка].get(ключ)
            if было != стало:
                строки.append(f"| {клетка} | {ключ} | {было} | {стало} |")
                изменений += 1

    if not изменений:
        строки.append("| — | различий нет | | |")

    непроверенные = sorted(set(старые) - set(новые))
    if непроверенные:
        строки += ["", "## Не гонялись в новом прогоне", ""]
        строки += [f"- {к}" for к in непроверенные]

    return "\n".join(строки) + "\n"


def прочитать_каталог(путь: Optional[str]) -> Optional[Path]:
    """Каталог прогона по имени или пути; None — если не указан."""
    if not путь:
        return None
    каталог = Path(путь)
    if not каталог.exists():
        каталог = Path("qa-runs") / путь
    if not (каталог / "run.json").exists():
        raise SystemExit(f"не похоже на прогон: {каталог}")
    return каталог
