"""Сводка прогона, сравнение двух прогонов и отбор помеченных клеток.

Инструмент только докладывает: статусы здесь — способ отсортировать внимание,
а не вердикт. Порогов, кода возврата и «не прошло» нет намеренно — любое
число сейчас было бы выдумано, а выдуманный красный вердикт быстро научил бы
игнорировать инструмент целиком.
"""

import json
from pathlib import Path
from statistics import median
from typing import Iterable, Optional

def _клетка(результат: dict) -> str:
    return f"{результат['разговор']['пациент']}__{результат['разговор']['тип']}"


# Во сколько раз реплики должны быть длиннее обычного, чтобы это стоило
# посмотреть. Не порог качества: сравниваем клетку с ОСТАЛЬНЫМИ клетками
# того же прогона, а не с выдуманным числом. У Оксаны 31.07 было 507 знаков
# при медиане 180 по остальным — втрое, и это оказалось настоящим дефектом
_ВО_СКОЛЬКО_ДЛИННЕЕ = 2.0

# Меньше этого числа клеток распределения нет, и сравнивать не с чем:
# на одиночном прогоне выброс не виден по определению
_КЛЕТОК_ДЛЯ_СРАВНЕНИЯ = 5


def _длины(результаты: Iterable[dict]) -> list[int]:
    """Обычные длины реплик по клеткам, где разговор состоялся."""
    return sorted(
        (р.get("метрики") or {}).get("знаков_медиана", 0)
        for р in результаты
        if (р.get("метрики") or {}).get("реплик")
    )


def медиана_прогона(результаты: Iterable[dict]) -> Optional[int]:
    """Обычная длина реплики в этом прогоне. None — сравнивать не с чем.

    Настоящая медиана, а не «серединный по индексу»: на шести клетках
    `len//2` брал четвёртое значение и завышал норму так, что выброс
    переставал быть выбросом. Оксана 04.08 из-за этого не помечалась.
    """
    длины = _длины(результаты)
    if len(длины) < _КЛЕТОК_ДЛЯ_СРАВНЕНИЯ:
        return None
    return int(median(длины)) or None


def поводы_посмотреть(
    результат: dict, медиана_по_прогону: Optional[int] = None
) -> list[str]:
    """Почему на эту клетку стоит взглянуть. Пусто — поводов нет.

    Список намеренно грубый: лучше показать лишнее, чем спрятать настоящее.
    Каждый повод здесь однажды был реальным дефектом, найденным вручную.

    `медиана_по_прогону` — обычная длина реплики в этом же прогоне. С ней
    ловится многословность: не по выдуманному порогу, а по тому, насколько
    клетка выбивается из остальных.
    """
    поводы: list[str] = []
    м = результат.get("метрики") or {}
    разговор = результат.get("разговор") or {}
    чтение = результат.get("чтение") or {}

    if разговор.get("сбои"):
        поводы.append(f"сбоев: {len(разговор['сбои'])}")
    if not разговор.get("ходы"):
        поводы.append("разговор не состоялся")
    if м.get("немых_ходов"):
        поводы.append(f"немых ходов: {м['немых_ходов']}")
    if м.get("ходов_с_ремаркой"):
        поводы.append(f"ремарок: {м['ходов_с_ремаркой']}")
    if м.get("ходов_с_латиницей"):
        поводы.append(f"латиница: {м['ходов_с_латиницей']}")
    if м.get("ходов_с_чужим_именем"):
        поводы.append(f"чужое имя: {м['ходов_с_чужим_именем']}")
    if м.get("повторов"):
        поводы.append(f"повторов: {м['повторов']}")
    if разговор.get("разбор") is None and разговор.get("ходы"):
        поводы.append("разбор не пришёл")

    # Многословность. Сравниваем с остальными клетками прогона: абсолютного
    # порога у нас нет и взять его неоткуда, а «втрое длиннее соседей» —
    # это факт из данных. Так выглядела Оксана, и так её было видно
    своя = м.get("знаков_медиана") or 0
    if медиана_по_прогону and своя >= медиана_по_прогону * _ВО_СКОЛЬКО_ДЛИННЕЕ:
        поводы.append(
            f"реплики длиннее обычных: {м.get('секунд_медиана')} с против "
            f"{round(медиана_по_прогону / 15, 1)} с"
        )

    # Любая находка читателя — повод. Он проинструктирован возвращать пустой
    # список, когда всё хорошо, и каждая находка приходит с цитатой: если он
    # что-то выписал, это уже стоит прочесть, независимо от серьёзности
    находки = чтение.get("находки") or []
    if находки:
        высоких = sum(1 for н in находки if н.get("серьёзность") == "высокая")
        хвост = f" (из них серьёзных: {высоких})" if высоких else ""
        поводы.append(f"находок читателя: {len(находки)}{хвост}")
    if чтение.get("ошибка"):
        поводы.append("читатель не отработал")

    return поводы


def загрузить_прогон(каталог: Path) -> list[dict]:
    """Все результаты прогона, отсортированные по клетке."""
    результаты = []
    for файл in sorted((каталог / "results").glob("*.json")):
        результаты.append(json.loads(файл.read_text(encoding="utf-8")))
    return результаты


def помеченные(каталог: Path) -> list[tuple[str, str]]:
    """Клетки прошлого прогона, на которые стоило посмотреть.

    Отсюда берёт список `--failed-from`: починили двоих — перегоняем двоих,
    а не всю матрицу заново.
    """
    результаты = загрузить_прогон(каталог)
    медиана = медиана_прогона(результаты)
    пары = []
    for результат in результаты:
        if поводы_посмотреть(результат, медиана):
            разговор = результат["разговор"]
            пары.append((разговор["пациент"], разговор["тип"]))
    return пары


