"""Механические проверки расшифровки: то, что считается арифметикой.

Каждая из них — это счёт, который я уже вёл руками разовыми скриптами
31.07–04.08. Здесь он становится штатным и одинаковым от прогона к прогону.

Модели тут нет вовсе: всё, для чего нужна модель, живёт в `qa/reader.py`.
Разделение не косметическое — арифметика дешёвая, воспроизводимая и не врёт,
поэтому она считается всегда, а чтение моделью можно отключить.
"""

import re
from dataclasses import asdict, dataclass, field
from statistics import median

# Настоящая функция чистки, а не копия: именно она стоит перед синтезом в бою,
# и проверять надо её поведение. Тесты импортируют её так же (tests/
# test_strip_for_speech.py), значит импорт main из скрипта уже отработан
from main import strip_for_speech  # noqa: E402

# Скорость русской речи в синтезе, знаков в секунду. Нужна, чтобы переводить
# длину реплики в то, что менеджер реально слышит: «507 знаков» ни о чём
# не говорит, «сорок секунд подряд» — говорит всё
_ЗНАКОВ_В_СЕКУНДУ = 15.0

# Ниже этого реплика считается немой: после чистки не осталось речи.
# Три знака, а не ноль, — «...» и одиночная буква тоже тишина
_НЕМАЯ_РЕПЛИКА = 3

# Доля общих слов, при которой считаем, что пациент повторяется. 0.6 —
# наблюдение, а не закон: у Оксаны повторы шли около 0.7, у здоровых
# пациентов соседние реплики держались ниже 0.4
_ПОРОГ_ПОВТОРА = 0.6

_РЕМАРКА = re.compile(r"\([^)]*\)|\*[^*]+\*")
_ЛАТИНИЦА = re.compile(r"[A-Za-z]")
_КИРИЛЛИЦА = re.compile(r"[А-Яа-яЁё]")
_СЛОВО = re.compile(r"[А-Яа-яЁё]{4,}")


@dataclass
class Повтор:
    ход: int
    похож_на_ход: int
    доля: float


@dataclass
class Метрики:
    """Числа по одной расшифровке. Ничего не решают — только описывают."""

    реплик: int = 0

    # Немые ходы: после strip_for_speech речи не осталось. Этой проверкой
    # 31.07 пойман Станислав, который одиннадцать ходов подряд выдавал
    # ремарки в скобках — в бою менеджер услышал бы тишину
    немых_ходов: int = 0
    немые_на_ходах: list[int] = field(default_factory=list)

    # Ремарки и разметка ДО чистки. Ноль немых ходов ещё не значит, что
    # ремарок нет: они могут идти вперемешку с речью и всё равно уродуют её
    ходов_с_ремаркой: int = 0

    # Длина реплики. Медиана, а не среднее: один монолог на десять реплик
    # среднее перекашивает, а медиана показывает обычный ход
    знаков_медиана: int = 0
    знаков_максимум: int = 0
    секунд_медиана: float = 0.0
    секунд_максимум: float = 0.0

    повторов: int = 0
    повторы: list[Повтор] = field(default_factory=list)

    # Выход из роли: латиница в русской реплике. llama-4-maverick 31.07
    # на закрытии заговорила по-английски как ассистент
    ходов_с_латиницей: int = 0

    # Пациент зовёт менеджера собственным именем — баг, найденный 31.07
    # у gpt-5.4-nano: шесть раз за разговор
    ходов_с_чужим_именем: int = 0

    def as_dict(self) -> dict:
        return asdict(self)


def реплики_пациента(история: list[dict]) -> list[str]:
    """Только то, что сказал пациент: менеджер здесь не проверяется."""
    return [
        item.get("text", "")
        for item in история
        if item.get("role") == "assistant"
    ]


def секунд_речи(текст: str) -> float:
    """Сколько это примерно звучит вслух — по очищенному тексту.

    Считаем по очищенному не для точности, а по смыслу: ремарку синтез
    не произносит, и включать её в длину значило бы завышать.
    """
    return round(len(strip_for_speech(текст)) / _ЗНАКОВ_В_СЕКУНДУ, 1)


def _значимые_слова(текст: str) -> set[str]:
    """Слова от четырёх букв: короткие служебные совпадают у всех подряд."""
    return {слово.lower() for слово in _СЛОВО.findall(текст)}


def доля_совпадения(первый: str, второй: str) -> float:
    """Доля общих значимых слов относительно меньшей из двух реплик.

    Относительно меньшей, а не объединения: короткая реплика, целиком
    повторяющая кусок длинной, — это повтор, и знаменатель по объединению
    его бы замаскировал.
    """
    a, b = _значимые_слова(первый), _значимые_слова(второй)
    if not a or not b:
        return 0.0
    return round(len(a & b) / min(len(a), len(b)), 2)


def имя_пациента(промпт: str) -> str | None:
    """Имя из первой строки промпта: «Ты — Тамара Михайловна ...»."""
    совпадение = re.search(r"Ты\s+—\s+([А-ЯЁ][а-яё]+)", промпт)
    return совпадение.group(1) if совпадение else None


def посчитать(история: list[dict], промпт_роли: str = "") -> Метрики:
    """Все механические проверки за один проход по репликам пациента."""
    реплики = реплики_пациента(история)
    м = Метрики(реплик=len(реплики))
    if not реплики:
        return м

    имя = имя_пациента(промпт_роли)
    длины: list[int] = []

    for номер, реплика in enumerate(реплики, 1):
        очищенная = strip_for_speech(реплика)
        длины.append(len(очищенная))

        if len(очищенная) < _НЕМАЯ_РЕПЛИКА:
            м.немых_ходов += 1
            м.немые_на_ходах.append(номер)

        if _РЕМАРКА.search(реплика):
            м.ходов_с_ремаркой += 1

        # Латиница считается значимой только рядом с кириллицей: реплика
        # целиком на латинице бывает у имён брендов, а вот английская фраза
        # посреди русской речи — это уже выход из роли
        латиница = len(_ЛАТИНИЦА.findall(реплика))
        if латиница >= 4 and _КИРИЛЛИЦА.search(реплика):
            м.ходов_с_латиницей += 1

        if имя and re.search(rf"\b{re.escape(имя)}\b", реплика):
            # Пациент произносит СВОЁ имя. В ответ на «как к вам обращаться»
            # это нормально, поэтому смотрим, обращается ли он им к собеседнику:
            # имя рядом с «вы», «вас», «вам» в одной фразе
            for фраза in re.split(r"[.!?]", реплика):
                if имя in фраза and re.search(r"\b[Вв]ы\b|\b[Вв]ас\b|\b[Вв]ам\b", фраза):
                    м.ходов_с_чужим_именем += 1
                    break

    м.знаков_медиана = int(median(длины))
    м.знаков_максимум = max(длины)
    м.секунд_медиана = round(м.знаков_медиана / _ЗНАКОВ_В_СЕКУНДУ, 1)
    м.секунд_максимум = round(м.знаков_максимум / _ЗНАКОВ_В_СЕКУНДУ, 1)

    # Повторы ищем со всеми предыдущими, а не только с соседней: пациент
    # возвращается к своей теме через ход-два, и соседняя пара это пропустит
    for номер, реплика in enumerate(реплики, 1):
        for предыдущий, прежняя in enumerate(реплики[: номер - 1], 1):
            доля = доля_совпадения(реплика, прежняя)
            if доля >= _ПОРОГ_ПОВТОРА:
                м.повторов += 1
                м.повторы.append(
                    Повтор(ход=номер, похож_на_ход=предыдущий, доля=доля)
                )
                break  # одного совпадения на ход достаточно

    return м
