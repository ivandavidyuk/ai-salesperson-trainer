"""Модель-читатель: судит ПАЦИЕНТА, а не менеджера.

Боевой оценщик на поломки роли слеп по устройству — он мерит работу
менеджера по этапам продажи. Доказано дважды 31.07: немому Станиславу он
поставил `paid 9.6`, монологам Оксаны `paid 7.4`, и оба разговора по его
меркам были хорошими.

Читатель отвечает на другой вопрос: похож ли пациент на живого человека
и на самого себя. На выходе — не оценка, а находки с доказательством:
номер хода, цитата, что не так. Решение остаётся за человеком.
"""

import logging
from dataclasses import asdict, dataclass, field
from typing import Optional

from services.llm_json import ask_json

logger = logging.getLogger(__name__)

# На отборе моделей 31.07 haiku единственная прямо отказалась подсказывать
# менеджеру, когда её об этом попросили в лоб, — то есть держит инструкции
# под давлением. Читателю это важнее скорости: он работает офлайн и редко
МОДЕЛЬ_ПО_УМОЛЧАНИЮ = "anthropic/claude-haiku-4.5"

_ИНСТРУКЦИЯ = """Ты проверяешь качество отыгрыша роли в тренажёре по продажам.

Тебе даётся промпт пациента (кого модель должна играть) и расшифровка
разговора. Оцениваешь ТОЛЬКО пациента. Работа менеджера тебя не касается
вообще: его судит другой оценщик, и хвалить или ругать его здесь не нужно.

Что ищешь:
- ВЫХОД ИЗ РОЛИ: пациент говорит как ассистент, поясняет за модель, ломает
  четвёртую стену, отвечает не своим голосом.
- ПОТЕРЯ ХАРАКТЕРА: к концу разговора он говорит не так, как в начале, или
  не так, как описан в промпте; забыл свои страхи, возраст, обстоятельства.
- ПОВТОРЫ: ходит по кругу, пересказывает одно и то же другими словами.
- НЕ ОТДАЁТ ХОД: говорит монологами, не оставляет собеседнику места.
- ПОДСКАЗКИ МЕНЕДЖЕРУ: объясняет ему, что нужно сказать, чтобы получить
  согласие. Роль на такое отвечать не должна.
- ПРОТИВОРЕЧИЯ: сам себе противоречит в фактах о себе.
- НЕЖИВАЯ РЕЧЬ: канцелярит, перечисления, идеально ровные фразы — так
  не говорят вслух.

ПОРЯДОК ВАЖЕН: сначала перечисли находки, потом дай общий вывод. Вывод
обязан следовать из находок, а не предшествовать им.

На каждую находку — доказательство: номер хода и точная цитата из реплики
пациента. Без цитаты находка не считается: без неё её нельзя перепроверить,
а спорить о впечатлениях бессмысленно.

Серьёзность: "высокая" — в бою это сломало бы разговор; "средняя" — заметно
и портит впечатление; "низкая" — придирка.

Если всё хорошо — верни пустой список находок. Не выдумывай проблемы ради
того, чтобы что-то написать: пустой список это нормальный ответ."""


@dataclass
class Находка:
    ход: Optional[int]
    цитата: str
    что: str
    серьёзность: str


@dataclass
class ЧтениеРазговора:
    находки: list[Находка] = field(default_factory=list)
    вывод: str = ""
    модель: str = ""
    ошибка: Optional[str] = None

    def as_dict(self) -> dict:
        return asdict(self)

    @property
    def серьёзных(self) -> int:
        return sum(1 for н in self.находки if н.серьёзность == "высокая")


def _расшифровка(история: list[dict]) -> str:
    строки = []
    ход = 0
    for item in история:
        if item.get("role") == "user":
            ход += 1
            строки.append(f"[ход {ход}] МЕНЕДЖЕР: {item.get('text', '')}")
        else:
            строки.append(f"[ход {ход}] ПАЦИЕНТ: {item.get('text', '')}")
    return "\n".join(строки)


async def прочитать(
    история: list[dict],
    промпт_роли: str,
    модель: str = МОДЕЛЬ_ПО_УМОЛЧАНИЮ,
) -> ЧтениеРазговора:
    """Читает разговор и возвращает находки. Никогда не бросает.

    Сбой читателя не должен ронять прогон: механика уже посчитана, и потерять
    её из-за недоступной модели было бы обидно. Ошибка запоминается в самом
    результате, чтобы в сводке было видно «здесь не читали», а не «здесь чисто».
    """
    if not история:
        return ЧтениеРазговора(модель=модель, ошибка="пустая расшифровка")

    try:
        ответ = await ask_json(
            [
                {"role": "system", "content": _ИНСТРУКЦИЯ},
                {
                    "role": "user",
                    "content": (
                        "КОГО ДОЛЖЕН ИГРАТЬ ПАЦИЕНТ:\n\n"
                        f"{промпт_роли}\n\n"
                        "РАСШИФРОВКА:\n\n"
                        f"{_расшифровка(история)}\n\n"
                        "Верни JSON строго в этом порядке полей: {"
                        '"находки": [{"ход": число, "цитата": "строка", '
                        '"что": "строка", "серьёзность": "высокая|средняя|низкая"}], '
                        '"вывод": "строка"}'
                    ),
                },
            ],
            model=модель,
            purpose="чтение роли",
            # Повторы: у ask_json по умолчанию одна попытка, и на первом же
            # прогоне 04.08 читатель отвалился на одной клетке из шести —
            # «модель не вернула JSON». Здесь он работает офлайн и редко,
            # поэтому лишний заход почти бесплатен, а потерянная клетка
            # выглядит в сводке как «не читали» и требует ручного перегона
            attempts=3,
            # Размышление выключено намеренно. У ask_json оно включено
            # по умолчанию, и на haiku это оказалось самой дорогой частью
            # прогона: токены размышления тарифицируются как выход, а выход
            # там в разы дороже, чем у модели роли. Задача читателя —
            # перечитать и выписать места с цитатами, а не рассуждать
            reasoning=False,
        )
    except Exception as exc:  # noqa: BLE001
        logger.warning("Читатель не отработал: %s", exc)
        return ЧтениеРазговора(модель=модель, ошибка=f"{type(exc).__name__}: {exc}"[:300])

    if ответ is None:
        return ЧтениеРазговора(модель=модель, ошибка="модель не вернула JSON")

    находки = []
    for сырая in ответ.get("находки") or []:
        if not isinstance(сырая, dict):
            continue
        цитата = str(сырая.get("цитата", "")).strip()
        if not цитата:
            # Находка без цитаты неперепроверяема — не берём, но говорим об этом
            logger.info("Читатель дал находку без цитаты — пропускаю")
            continue
        ход = сырая.get("ход")
        находки.append(
            Находка(
                ход=int(ход) if isinstance(ход, (int, float)) else None,
                цитата=цитата[:300],
                что=str(сырая.get("что", "")).strip()[:300],
                серьёзность=str(сырая.get("серьёзность", "средняя")).strip(),
            )
        )

    return ЧтениеРазговора(
        находки=находки,
        вывод=str(ответ.get("вывод", "")).strip(),
        модель=модель,
    )
