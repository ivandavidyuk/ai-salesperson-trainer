"""Разбор ответа критика.

Критик — страховка поверх починенного порядка вызовов, а не основная защита.
Отсюда главное свойство, которое здесь и проверяется: его собственный сбой
не должен стоить пациенту случая. Непонятный ответ, пустой ответ, отказ
провайдера — всё это «годится», потому что молчаливый пропуск дешевле
молчаливой потери.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from services.case_review import (  # noqa: E402
    ВИНОВАТА_КАРТИНА,
    ВИНОВАТА_ПРОЗА,
    build_review_messages,
    разобрать,
)


def test_годится_проходит():
    годится, виновник, возражение = разобрать(
        {"checks": ["ок"] * 5, "fault": None, "objection": "", "verdict": "годится"}
    )
    assert годится is True
    assert виновник is None and возражение == ""


def test_брак_с_виновной_картиной():
    годится, виновник, возражение = разобрать(
        {
            "checks": ["возраст не тот"],
            "fault": "картина",
            "objection": "Миопия не начинается в 44 года",
            "verdict": "брак",
        }
    )
    assert годится is False
    assert виновник == ВИНОВАТА_КАРТИНА
    assert "44" in возражение


def test_брак_без_виновника_считается_прозой():
    # Прозу пересобрать дешевле, а картина остаётся в запасе на следующую
    # попытку — так неопределённость обходится дешевле всего
    годится, виновник, _ = разобрать({"fault": None, "objection": "что-то не так", "verdict": "брак"})
    assert годится is False and виновник == ВИНОВАТА_ПРОЗА


def test_брак_с_чужим_виновником_считается_прозой():
    годится, виновник, _ = разобрать({"fault": "непонятно кто", "verdict": "брак"})
    assert годится is False and виновник == ВИНОВАТА_ПРОЗА


def test_брак_без_пояснения_получает_заглушку():
    # Пустое возражение бесполезно и прозе на пересборке, и человеку,
    # который будет разбирать пометку
    _, _, возражение = разобрать({"fault": "проза", "objection": "", "verdict": "брак"})
    assert возражение


def test_сбой_критика_не_стоит_пациенту_случая():
    for ответ in (None, {}, {"verdict": ""}, "не словарь", []):
        годится, виновник, возражение = разобрать(ответ)
        assert годится is True, f"на {ответ!r} критик уронил бы пациента"
        assert виновник is None and возражение == ""


def test_регистр_вердикта_не_важен():
    годится, _, _ = разобрать({"verdict": "БРАК", "fault": "картина"})
    assert годится is False


def test_критику_видны_возраст_диагноз_и_анамнез():
    сообщения = build_review_messages(
        {"identity": "Ты — Анжелика Сергеевна, 44 года. Домохозяйка."},
        {"diagnosis": "Пресбиопия", "onset": "после 40", "stage": "начальная"},
        {"anamnesis": "Жалобы на чтение вблизи. Диагноз: Пресбиопия"},
        "Подбор очков",
    )
    текст = сообщения[1]["content"]
    assert "44 года" in текст
    assert "Пресбиопия" in текст
    assert "Подбор очков" in текст
    assert "Жалобы на чтение вблизи" in текст


def test_критик_спрашивает_узко_а_не_нравится_ли():
    инструкция = build_review_messages({}, {}, {}, "")[0]["content"]
    for вопрос in ("ОКНО НАЧАЛА", "ЧАСТОТА", "СТАДИЯ", "УСЛОВИЕ ПРОЯВЛЕНИЯ", "ЛЕЧЕНИЕ"):
        assert вопрос in инструкция
    # Разбор идёт раньше вывода: поле checks объявлено до verdict
    assert инструкция.index('"checks"') < инструкция.index('"verdict"')
