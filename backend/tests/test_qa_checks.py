def test_одиночная_латиница_не_тревога():
    м = посчитать(диалог("Мне ставили линзы ISO, всё хорошо."))
    assert м.ходов_с_латиницей == 0


def test_пациент_зовёт_менеджера_своим_именем():
    # Баг gpt-5.4-nano 31.07: шесть обращений за разговор
    промпт = "Ты — Тамара Михайловна Соколова, 62 года."
    м = посчитать(диалог("Тамара, вы мне объясните, что там по цене?"), промпт)
    assert м.ходов_с_чужим_именем == 1


def test_своё_имя_в_ответ_на_вопрос_нормально():
    промпт = "Ты — Тамара Михайловна Соколова, 62 года."
    м = посчитать(диалог("Тамара Михайловна."), промпт)
    assert м.ходов_с_чужим_именем == 0


def test_имя_берётся_из_первой_строки_промпта():
    assert имя_пациента("Ты — Ван Хао, 44 года.") == "Ван"
    assert имя_пациента("Без первой строки") is None


def test_доля_совпадения_считается_по_меньшей_реплике():
    # Короткая реплика, целиком повторяющая кусок длинной, — это повтор,
    # и знаменатель по объединению его бы замаскировал
    короткая = "долги приставы зарплата"
    длинная = "долги приставы зарплата операция клиника хирург анестезия"
    assert доля_совпадения(короткая, длинная) == 1.0


def test_пустая_расшифровка_не_роняет():
    м = посчитать([])
    assert м.реплик == 0
    assert м.знаков_медиана == 0


def test_секунды_считаются_по_очищенному():
    assert секунд_речи("(молчит) Да.") == round(len("Да.") / 15.0, 1)
