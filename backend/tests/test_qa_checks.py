"""Механические проверки расшифровки.

Проверяются на настоящих репликах из прогонов 31.07: если инструмент
не ловит уже известные дефекты, он бесполезен — это прямо записано
в плане как условие приёмки.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from qa.checks import (  # noqa: E402
    доля_совпадения,
    имя_пациента,
    посчитать,
    секунд_речи,
)


def диалог(*реплики_пациента: str) -> list[dict]:
    """Расшифровка, где менеджер говорит что угодно, а пациент — заданное."""
    история: list[dict] = []
    for текст in реплики_пациента:
        история.append({"role": "user", "text": "Реплика менеджера."})
        история.append({"role": "assistant", "text": текст})
    return история


def test_немой_ход_ловится():
    # Так молчал Станислав 31.07: одиннадцать ходов подряд одними ремарками,
    # и оценщик поставил за это paid 9.6
    м = посчитать(
        диалог(
            "*(Прищуривается, сканируя взглядом от макушки до ботинок)*",
            "Стойте. Вы сейчас солгали.",
        )
    )
    assert м.немых_ходов == 1
    assert м.немые_на_ходах == [1]
    assert м.ходов_с_ремаркой == 1


def test_речь_рядом_с_ремаркой_немой_не_считается():
    # Ремарка есть, но речь осталась — это не тишина, а неопрятность
    м = посчитать(диалог("*(кивает)* Хорошо, я вас слушаю."))
    assert м.немых_ходов == 0
    assert м.ходов_с_ремаркой == 1


def test_длина_меряется_по_очищенному():
    # Ремарка вслух не звучит, включать её в длину — завышать
    м = посчитать(диалог("(Долго молчит и разглядывает бумаги.) Да."))
    assert м.знаков_максимум == len("Да.")


def test_монолог_виден_в_секундах():
    # Оксана 31.07: 507 знаков в среднем против медианных 180 у остальных,
    # это сорок секунд непрерывной речи на один ход
    длинная = "Вы знаете, я так переживала, пока добиралась к вам. " * 12
    м = посчитать(диалог(длинная))
    assert м.секунд_максимум > 30


def test_медиана_не_ведётся_на_один_монолог():
    # Среднее один монолог перекашивает, медиана показывает обычный ход
    м = посчитать(диалог("Да.", "Нет.", "Хорошо.", "а" * 900))
    assert м.знаков_медиана < 20
    assert м.знаков_максимум == 900


def test_повтор_через_ход_ловится():
    # Пациент возвращается к своей теме не подряд, а через реплику —
    # сравнение только с соседней такое пропустило бы
    м = посчитать(
        диалог(
            "У меня долги, приставы звонят, зарплата серая, платить нечем.",
            "Хорошо, расскажите подробнее про операцию.",
            "Так ведь долги у меня, приставы звонят, зарплата серая совсем.",
        )
    )
    assert м.повторов == 1
    assert м.повторы[0].ход == 3
    assert м.повторы[0].похож_на_ход == 1


def test_разные_реплики_повтором_не_считаются():
    м = посчитать(
        диалог(
            "Сколько длится операция и чем обезболивают?",
            "А когда можно будет вернуться за руль?",
        )
    )
    assert м.повторов == 0


def test_английская_фраза_посреди_русской_речи():
    # llama-4-maverick 31.07 на закрытии заговорила по-английски как ассистент
    м = посчитать(диалог("Хорошо. I understand your concerns completely."))
