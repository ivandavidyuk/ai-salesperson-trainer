"""Конец разговора в прогоне полного разговора (qa.full_run).

Менеджер-модель заканчивает разговор словом «КОНЕЦ». Ошибка в одну сторону
обрывает прогон посреди продажи, в другую — гоняет его до потолка ходов
и пишет «КОНЕЦ» в реплику, которую слышит пациент.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from qa.full_run import конец_разговора  # noqa: E402


def test_одно_слово_заканчивает():
    assert конец_разговора("КОНЕЦ") == (True, "")
    assert конец_разговора("Конец.") == (True, "")


def test_реплика_с_концом_в_хвосте_уходит_без_него():
    assert конец_разговора("Всего доброго, выздоравливайте! КОНЕЦ") == (
        False,
        "Всего доброго, выздоравливайте!",
    )


def test_обычная_реплика_не_трогается():
    реплика = "Это ещё не конец лечения, впереди два занятия."
    assert конец_разговора(реплика) == (False, реплика)
