"""Чистка реплики перед синтезом.

Повод — замер моделей 31.07.2026: чистой не оказалось ни одной. Запрет
в промпте работает, но не всегда, а ремарка, дошедшая до TTS, звучит вслух
как реплика пациента. Это страховка на выходе, не замена запрету.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from main import strip_for_speech  # noqa: E402


def test_парная_ремарка_вырезается():
    # Так пишет gemini-2.5-flash-lite
    assert (
        strip_for_speech("(Прищуривается, внимательно слушает.) Сколько это стоит?")
        == "Сколько это стоит?"
    )


def test_разметка_вырезается():
    # Так пишет gpt-5.4-nano
    assert (
        strip_for_speech("Назовите **точную сумму** за оба глаза")
        == "Назовите точную сумму за оба глаза"
    )


def test_ремарка_со_звёздочками_вырезается():
    # Так пишет qwen: разметка и ремарка одновременно
    assert strip_for_speech("*(Молча беру папку, достаю лупу.)* Хорошо.") == "Хорошо."


def test_незакрытая_скобка_вырезается():
    # Ремарка из двух предложений разрывается делителем пополам —
    # обе половины одинаково не нужны
    assert strip_for_speech("(Молча беру у вас папку.") == ""
    assert strip_for_speech("Достаёт лупу, проверяет печати.)") == ""


def test_ремарка_целым_предложением_даёт_пустоту():
    # Синтезировать нечего — вызывающий код такое предложение пропускает
    assert strip_for_speech("(Говорит очень тихо, глядя в пол)") == ""


def test_нумерация_списка_убирается():
    assert strip_for_speech("1) Какая методика?") == "Какая методика?"


def test_обычная_реплика_не_страдает():
    текст = "Я не люблю сюрпризов. Назовите итог — сколько всё вместе?"
    assert strip_for_speech(текст) == текст


def test_многоточие_и_тире_сохраняются():
    # Речевые знаки, на них держится интонация
    текст = "Так… сейчас посчитаю. Это ведь окончательная сумма — без доплат?"
    assert strip_for_speech(текст) == текст


def test_пробелы_схлопываются():
    assert strip_for_speech("Да.  (кивает)   Конечно.") == "Да. Конечно."


# --- Прогон Jamaica 14.10: ремарки, которые звучали вслух ----------------


def test_квадратные_скобки_вырезаются():
    assert (
        strip_for_speech("[Егор заходит в кабинет на диагностику] Ну что, доктор?")
        == "Ну что, доктор?"
    )


def test_разорванная_квадратная_скобка_вырезается():
    # Делитель режет ремарку по точке внутри — обе половины не нужны
    assert strip_for_speech("[Егор заходит в кабинет на диагностику.") == ""
    assert strip_for_speech("Возвращается с результатами.]") == ""


def test_ремарка_в_звёздочках_между_фразами_вырезается():
    assert strip_for_speech("*пауза* А что вы здесь предлагаете?") == (
        "А что вы здесь предлагаете?"
    )
    assert strip_for_speech("Ну ладно. *вздыхает*") == "Ну ладно."
    assert strip_for_speech("*пауза*") == ""


def test_выделенное_слово_внутри_фразы_остаётся():
    # Это не ремарка, а интонация: без слова пропадёт смысл
    assert strip_for_speech("Это *очень* дорого.") == "Это очень дорого."
    assert strip_for_speech("*Нет*, я не согласна.") == "Нет, я не согласна."
