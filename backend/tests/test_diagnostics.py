"""Чистая логика результата диагностики: выбор исхода и валидатор документа.

Сетевые части (генерация, эндпоинт) тестами не покрываются — поведение
промпта проверяется симулятором и чтением, как и у остальных генераторов.
"""

import random

from services import diagnostics


def test_исходы_согласованы():
    """Ключи уникальны, веса положительны — иначе choices молча перекосится."""
    ключи = [к for к, _, _ in diagnostics.ИСХОДЫ]
    assert len(ключи) == len(set(ключи))
    assert all(в > 0 for _, в, _ in diagnostics.ИСХОДЫ)


def test_выбор_исхода_уважает_веса():
    """На фиксированном генераторе распределение повторяет веса.

    Не точную математику, а порядок: частый исход выпадает чаще редкого,
    и редкий («крайний») вообще выпадает — нулевой вес был бы регрессией.
    """
    rng = random.Random(42)
    счёт: dict[str, int] = {}
    for _ in range(2000):
        ключ, _ = diagnostics.выбрать_исход(rng)
        счёт[ключ] = счёт.get(ключ, 0) + 1

    assert счёт["умеренное ухудшение"] > счёт["без изменений"]
    assert счёт["сильное ухудшение"] > счёт["крайний исход"]
    assert счёт.get("крайний исход", 0) > 0


def test_выбор_возвращает_описание_своего_ключа():
    rng = random.Random(7)
    ключ, описание = diagnostics.выбрать_исход(rng)
    ожидаемое = {к: о for к, _, о in diagnostics.ИСХОДЫ}[ключ]
    assert описание == ожидаемое


def test_исходы_не_говорят_о_процентах_функции():
    """Прежние описания мерили «функцию» в процентах — офтальмологический
    язык. В стоматологии измеряемой функции нет ни у одного диагноза, кроме
    адентии, и «потеря функции зуба» означала бы удаление, то есть отмену
    целевой продажи. Формулировка обязана оставаться отраслево-нейтральной.
    """
    все = " ".join(о for _, _, о in diagnostics.ИСХОДЫ).lower()
    assert "функция снизилась" not in все
    assert "%" not in все


# Документ в одобренной форме: «Первичный осмотр», заголовки-исследования
# в ** **, значения под ними, НОРМ НЕТ.
ГОДНЫЙ = (
    "**Первичный осмотр** Тамара Михайловна, 62 года\n"
    "\n"
    "**Острота зрения вдаль:**\n"
    "OD 0,03 sph −5,5 cyl −0,75 ax 175 = 0,3\n"
    "OS 0,03 sph −6,0 cyl −1,0 ax 170 = 0,2\n"
    "**Острота зрения вблизи:**\n"
    "OD 0,1\n"
    "OS 0,08\n"
    "**Рефрактометрия:**\n"
    "OD sph −5,5 cyl −0,75 ax 175\n"
    "OS sph −6,0 cyl −1,0 ax 170\n"
    "**Пневмотонометрия (mmHg):**\n"
    "OD 18 мм рт. ст.\n"
    "OS 19 мм рт. ст."
)


def test_годный_документ_проходит():
    assert diagnostics.чем_плох(ГОДНЫЙ, "Тамара Михайловна") is None


def test_гадание_бракуется():
    плохой = ГОДНЫЙ + "\nПомутнение, предположительно, ядерное."
    assert "гадает" in diagnostics.чем_плох(плохой, "Тамара Михайловна")


def test_вывод_о_продаже_бракуется():
    """«Требуется операция» — вывод о продаже вместо находки: на этом
    в июле два врача забраковали сборку целиком."""
    плохой = ГОДНЫЙ + "\nРекомендуется замена хрусталика."
    assert "продаж" in diagnostics.чем_плох(плохой, "Тамара Михайловна")


def test_чужое_имя_бракуется():
    assert "имени" in diagnostics.чем_плох(ГОДНЫЙ, "Борис Семёнович")


def test_пустой_и_раздутый_бракуются():
    assert diagnostics.чем_плох("", "Тамара") is not None
    assert "раздут" in diagnostics.чем_плох("х" * 2000, "Тамара")


def test_прежний_бланк_бракуется():
    """Модель, обученная на медицинских текстах, сползает обратно
    к «Объект исследования:» — и документ при этом выглядит правдоподобно."""
    плохой = ГОДНЫЙ + "\nОбъект исследования: правый и левый глаз."
    беда = diagnostics.чем_плох(плохой, "Тамара Михайловна")
    assert "бланк" in беда


def test_норма_рядом_со_значением_бракуется():
    """Норм в настоящем заключении не пишут — их знает читатель. Ловим
    оба написания: в скобках и через тире."""
    for хвост in ("\nВГД: 18 мм рт. ст. (норма до 21)", "\nВГД: 18 — норма до 21"):
        беда = diagnostics.чем_плох(ГОДНЫЙ + хвост, "Тамара Михайловна")
        assert "норма" in беда, хвост


def test_слово_норма_само_по_себе_не_бракует():
    """«Слизистая в норме» — законная клиническая формулировка, а не бланк
    с нормами. Проверка не должна её ловить."""
    годный = ГОДНЫЙ + "\n**Биомикроскопия:**\nСлизистая в норме, отделяемого нет"
    assert diagnostics.чем_плох(годный, "Тамара Михайловна") is None


def test_мало_разделов_бракуется():
    """Два раздела — это не документ, а огрызок: менеджеру не с чем работать."""
    короткий = (
        "**Первичный осмотр** Тамара Михайловна, 62 года\n"
        "**Острота зрения вдаль:**\n"
        "OD 0,3\nOS 0,2\n"
        "И ещё немного текста, чтобы пройти проверку минимальной длины "
        "документа, которая стоит раньше проверки числа разделов."
    )
    беда = diagnostics.чем_плох(короткий, "Тамара Михайловна")
    assert "разделов" in беда


def test_возраст_вынимается_из_карточки():
    """Возраст стоит в шапке документа, а в промпте его не было вовсе —
    первый живой прогон дал Тамаре 68 лет вместо 62. Строка карточки
    («62 года · повод») лежала рядом в том же SQL-запросе."""
    assert diagnostics.возраст_из("62 года · вяжет только под лампой") == "62 года"
    assert diagnostics.возраст_из("72 года · жуёт на одну сторону") == "72 года"
    assert diagnostics.возраст_из("44 год · что-то") == "44 год"


def test_возраст_молчит_когда_его_нет():
    """Пустая строка лучше выдуманного числа: без возраста шапка просто
    останется без него, а не соврёт."""
    assert diagnostics.возраст_из("") == ""
    assert diagnostics.возраст_из("вяжет только под лампой") == ""
    assert diagnostics.возраст_из(None) == ""


def test_действие_клиники_бракуется():
    """«Подбор очков и контактных линз» — услуга из прайса, и документ
    не должен называть её ни в какой форме. Прежние проверки пропускали
    «с подобранной сегодня коррекцией»: это не рекомендация, а уже названная
    услуга — так проскочило пять документов из сорока двух."""
    плохой = ГОДНЫЙ + "\nОстрота с подобранной сегодня коррекцией 0,8"
    беда = diagnostics.чем_плох(плохой, "Тамара Михайловна")
    assert "действие" in беда
