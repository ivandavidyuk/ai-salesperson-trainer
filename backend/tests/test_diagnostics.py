"""Чистая логика результата диагностики: выбор исхода и валидатор документа.

Сетевые части (генерация, эндпоинт) тестами не покрываются — поведение
промпта проверяется симулятором и чтением, как и у остальных генераторов.
"""

import random

from services import diagnostics


def test_исходы_согласованы():
    """Ключи уникальны, веса положительны — иначе choices молча перекосится."""
    ключи = [к for к, _, _ in diagnostics.ИСХОДЫ]
    assert len(ключи) == len(set(ключи))
    assert all(в > 0 for _, в, _ in diagnostics.ИСХОДЫ)


def test_выбор_исхода_уважает_веса():
    """На фиксированном генераторе распределение повторяет веса.

    Не точную математику, а порядок: частый исход выпадает чаще редкого,
    и редкий («крайний») вообще выпадает — нулевой вес был бы регрессией.
    """
    rng = random.Random(42)
    счёт: dict[str, int] = {}
    for _ in range(2000):
        ключ, _ = diagnostics.выбрать_исход(rng)
        счёт[ключ] = счёт.get(ключ, 0) + 1

    assert счёт["умеренное ухудшение"] > счёт["без изменений"]
    assert счёт["сильное ухудшение"] > счёт["крайний исход"]
    assert счёт.get("крайний исход", 0) > 0


def test_выбор_возвращает_описание_своего_ключа():
    rng = random.Random(7)
    ключ, описание = diagnostics.выбрать_исход(rng)
    ожидаемое = {к: о for к, _, о in diagnostics.ИСХОДЫ}[ключ]
    assert описание == ожидаемое


ГОДНЫЙ = (
    "Тамара Михайловна\n"
    "Объект исследования: правый и левый глаз.\n"
    "Способ исследования: визометрия, авторефрактометрия, тонометрия.\n"
    "Показатели исследования:\n"
    "Острота зрения: OD 0,3 (было 0,4), OS 0,25 (было 0,3) — норма 1,0.\n"
    "Рефракция: OD −5,75 дптр (было −5,25) — норма 0.\n"
    "ВГД: 18 и 18 мм рт. ст. — норма до 21."
)


def test_годный_документ_проходит():
    assert diagnostics.чем_плох(ГОДНЫЙ, "Тамара Михайловна") is None


def test_гадание_бракуется():
    плохой = ГОДНЫЙ + "\nПомутнение, предположительно, ядерное."
    assert "гадает" in diagnostics.чем_плох(плохой, "Тамара Михайловна")


def test_вывод_о_продаже_бракуется():
    """«Требуется операция» — вывод о продаже вместо находки: на этом
    в июле два врача забраковали сборку целиком."""
    плохой = ГОДНЫЙ + "\nРекомендуется замена хрусталика."
    assert "продаж" in diagnostics.чем_плох(плохой, "Тамара Михайловна")


def test_чужое_имя_бракуется():
    assert "имени" in diagnostics.чем_плох(ГОДНЫЙ, "Борис Семёнович")


def test_пустой_и_раздутый_бракуются():
    assert diagnostics.чем_плох("", "Тамара") is not None
    assert "раздут" in diagnostics.чем_плох("х" * 2000, "Тамара")
