def test_повтор_раздела_бракуется():
    """Тот же заголовок дважды — обычная поломка длинной генерации,
    а читателю это выглядит как два разных исследования."""
    один = ГОДНЫЙ + "\n\n**Тонометрия:**\nOD 17 мм рт. ст."
    assert diagnostics.чем_плох(один, "Тамара Михайловна") is None

    дважды = один + "\n\n**Тонометрия:**\nOS 18 мм рт. ст."
    беда = diagnostics.чем_плох(дважды, "Тамара Михайловна")
    assert беда is not None and "дважды" in беда


def test_процент_больше_ста_бракуется():
    """Единственная величина, границы которой известны без отрасли.
    «118% точек» читается правдоподобно ровно до того мгновения,
    как на него посмотрят."""
    годный = ГОДНЫЙ + "\nОхват 100% поверхности"
    assert diagnostics.чем_плох(годный, "Тамара Михайловна") is None

    беда = diagnostics.чем_плох(ГОДНЫЙ + "\nОхват 118% поверхности", "Тамара Михайловна")
    assert беда is not None and "процент" in беда


def test_дробный_процент_считается():
    беда = diagnostics.чем_плох(ГОДНЫЙ + "\nОхват 100,5% поверхности", "Тамара Михайловна")
    assert беда is not None and "процент" in беда
