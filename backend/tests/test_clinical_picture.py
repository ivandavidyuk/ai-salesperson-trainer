# --- Выбор картины ---


def диагнозы(пары: list) -> list[str]:
    return [к["diagnosis"] for к, _ in пары]


def test_картина_без_услуги_выпадает():
    картины = [картина("А"), картина("Б"), картина("В")]
    услуги = [None, {"name": "Замена хрусталика"}, {"name": "Полная диагностика"}]
    assert диагнозы(choose(картины, услуги)) == ["Б", "В"]


def test_без_подходящих_услуг_список_пуст():
    картины = [картина("А"), картина("Б")]
    assert choose(картины, [None, None]) == []


def test_отдаются_все_пригодные_а_не_одна():
    # Критик, забраковав первую, берёт следующую отсюда — она уже оплачена
    # клиническим вызовом, и новый не нужен
    картины = [картина("А"), картина("Б"), картина("В")]
    услуги = [{"name": "У"}, {"name": "У"}, {"name": "У"}]
    assert len(choose(картины, услуги)) == 3


def test_занятый_диагноз_уступает_свежему():
    # Разнообразие: у другого пациента этой клиники «А» уже был
    картины = [картина("А"), картина("Б")]
    услуги = [{"name": "Замена хрусталика"}, {"name": "Замена хрусталика"}]
    assert диагнозы(choose(картины, услуги, used_diagnoses=["А"])) == ["Б", "А"]


def test_занятые_не_выбрасываются_а_уходят_в_конец():
    # Правдоподобие важнее разнообразия: повтор лучше, чем натянутая болезнь,
    # и уж точно лучше, чем пациент без случая
    картины = [картина("А"), картина("Б")]
    услуги = [{"name": "Замена хрусталика"}, {"name": "Замена хрусталика"}]
    assert диагнозы(choose(картины, услуги, used_diagnoses=["А", "Б"])) == ["А", "Б"]


def test_занятость_не_зависит_от_регистра():
    картины = [картина("Возрастная катаракта"), картина("Глаукома")]
    услуги = [{"name": "Замена хрусталика"}, {"name": "Замена хрусталика"}]
    пары = choose(картины, услуги, used_diagnoses=["возрастная КАТАРАКТА"])
    assert диагнозы(пары)[0] == "Глаукома"
