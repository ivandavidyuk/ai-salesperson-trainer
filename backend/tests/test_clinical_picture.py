"""Проверка клинического шага: формы картин и выбора из них.

Повод — разбор 06.08.2026. Врач забраковал сборку: миопия, впервые возникшая
в 48 лет, катаракта с жалобой не на ту функцию. Причина была в порядке
вопросов: диагноз выбирала та же модель, что писала продающую прозу, и она
подгоняла болезнь под услугу.

Главный инвариант всей починки проверяется здесь первым тестом: в клиническом
запросе НЕТ услуг и цен. Появятся — и подлог вернётся, а заметить его будет
уже нечем.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from services.clinical_picture import (  # noqa: E402
    build_clinical_messages,
    build_match_messages,
    choose,
    найти_услугу,
    validate_pictures,
)


def картина(diagnosis: str = "Возрастная катаракта, ядерная") -> dict:
    return {
        "diagnosis": diagnosis,
        "onset": "после 55 лет",
        "typicalFor": "самое частое в этом возрасте",
        "stage": "начальная",
        "complaints": "Зрение просто хуже стало, и вдаль, и вблизи.",
        "noticedWhen": "Замечает, когда перестали помогать привычные очки.",
        "objective": "Помутнение ядра хрусталика, передняя камера сохранена.",
        "treatment": "Факоэмульсификация с имплантацией ИОЛ",
    }


def набор(сколько: int = 3) -> dict:
    return {"pictures": [картина(f"Диагноз {n}") for n in range(1, сколько + 1)]}


def клиника() -> dict:
    return {
        "name": "Клиника",
        "industry": "офтальмология",
        "services": [
            {"name": "Замена хрусталика", "price": "от 60 000 ₽", "description": "20 минут"},
            {"name": "Полная диагностика", "price": "6 500 ₽", "description": "полтора часа"},
        ],
    }


# --- Инвариант, ради которого всё затевалось ---


def test_в_клиническом_запросе_нет_услуг_и_цен():
    сообщения = build_clinical_messages(
        {"identity": "Ты — Леонид Петрович, 74 года.", "fears": ["боится ослепнуть"]},
        клиника(),
    )
    целиком = " ".join(с["content"] for с in сообщения)
    assert "Замена хрусталика" not in целиком
    assert "60 000" not in целиком
    assert "6 500" not in целиком
    # А отрасль и человек — на месте, иначе спрашивать не о чем
    assert "офтальмология" in целиком
    assert "74 года" in целиком


def test_клинический_запрос_не_говорит_о_продаже():
    сообщения = build_clinical_messages({"identity": "Ты — Пётр, 30 лет."}, клиника())
    инструкция = сообщения[0]["content"]
    assert "О продажах, услугах и ценах тебя не спрашивают" in инструкция


def test_в_подборе_услуги_есть_и_картины_и_услуги():
    сообщения = build_match_messages([картина()], клиника())
    текст = сообщения[1]["content"]
    assert "Возрастная катаракта" in текст
    assert "Замена хрусталика" in текст


def test_название_услуги_отделено_от_описания():
    # Замер 06.08: название и описание стояли в одной строке через точку,
    # модель на просьбу вернуть название «слово в слово» отдала всю строку,
    # и поиск по списку её не нашёл. Шесть сборок из восьми провалились
    текст = build_match_messages([картина()], клиника())[1]["content"]
    assert "- Замена хрусталика\n" in текст
    assert "Замена хрусталика. 20 минут" not in текст


# --- Поиск услуги по ответу модели ---


def услуги() -> dict:
    return {у["name"]: у for у in клиника()["services"]}


def test_точное_название_находится():
    assert найти_услугу("Замена хрусталика", услуги())["price"] == "от 60 000 ₽"


def test_название_с_приписанным_описанием_находится():
    # Ровно то, на чём сломался замер 06.08
    ответ = "Замена хрусталика. 20 минут"
    assert найти_услугу(ответ, услуги())["price"] == "от 60 000 ₽"


def test_точка_и_регистр_прощаются():
    assert найти_услугу("замена хрусталика.", услуги()) is not None


def test_опечатка_в_названии_прощается():
    # Замер 06.08: модель написала «с импластрацией ИОЛ», и пациент из-за
    # одной буквы остался без случая
    услуги = {
        "Замена хрусталика с имплантацией ИОЛ": {"price": "от 60 000 ₽"},
        "Полная диагностика": {"price": "6 500 ₽"},
    }
    найдено = найти_услугу("Замена хрусталика с импластрацией ИОЛ", услуги)
    assert найдено is not None and найдено["price"] == "от 60 000 ₽"


def test_похожие_услуги_прайса_не_путаются():
    # Порог высокий намеренно: спутать «глаукому» с «катарактой» хуже,
    # чем не найти совсем
    услуги = {"Лечение глаукомы": {"price": "1"}, "Лечение катаракты": {"price": "2"}}
    assert найти_услугу("Лечение глаукомы", услуги)["price"] == "1"
    assert найти_услугу("Лечение кератоконуса", услуги) is None


def test_выдуманная_услуга_не_находится():
    # Выдуманное название — та же беда, что выдуманный диагноз, только
    # с другого конца: соглашаться на него нельзя
    assert найти_услугу("Пересадка роговицы", услуги()) is None


def test_пустой_ответ_не_находится():
    assert найти_услугу(None, услуги()) is None
    assert найти_услугу("", услуги()) is None


