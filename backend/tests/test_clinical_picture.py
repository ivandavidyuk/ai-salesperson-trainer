def _пара(имя: str):
    return картина(имя, onsetFrom=1)


def test_реже_выданный_диагноз_идёт_вперёд():
    # Со списком из пяти диагнозов на 21 пациента повтор — норма, и цель
    # не «чего ещё не было», а «кому досталось меньше всех»
    картины = [_пара("А"), _пара("Б")]
    услуги = [{"name": "У"}, {"name": "У"}]
    было = ["А", "А", "А", "Б"]
    assert диагнозы(choose(картины, услуги, было))[0] == "Б"


def test_при_равном_счёте_уважается_вероятность():
    # Картины приходят по убыванию вероятности; при равенстве счётчиков
    # порядок ломать незачем
    картины = [_пара("А"), _пара("Б")]
    услуги = [{"name": "У"}, {"name": "У"}]
    assert диагнозы(choose(картины, услуги, ["А", "Б"])) == ["А", "Б"]


def test_пустая_история_не_роняет_выбор():
    # Первый пациент клиники: выдавать ещё нечего
    картины = [_пара("А"), _пара("Б")]
    услуги = [{"name": "У"}, {"name": "У"}]
    assert диагнозы(choose(картины, услуги, [])) == ["А", "Б"]
    assert диагнозы(choose(картины, услуги, None)) == ["А", "Б"]


def test_распределение_на_закрытом_списке_ровное():
    # Сквозная проверка правила: пять диагнозов, 21 пациент, каждому
    # доступны все пять. Никто не должен уйти в отрыв
    список = ["А", "Б", "В", "Г", "Д"]
    услуги = [{"name": "У"}] * len(список)
    выдано: list[str] = []
    for _ in range(21):
        картины = [_пара(и) for и in список]
        выдано.append(диагнозы(choose(картины, услуги, выдано))[0])

    счёт = {и: выдано.count(и) for и in список}
    assert max(счёт.values()) - min(счёт.values()) <= 1, счёт
    assert sum(счёт.values()) == 21


def test_без_диагнозов_клиники_вызова_не_будет():
    # Форма диагнозы требует, но «Собрать заново» идёт мимо неё, и клиника,
    # сохранённая до этой правки, пришла бы сюда с пустым списком. Молча
    # спросить модель значило бы вернуть ей сочинение диагнозов
    import asyncio

    from services import clinical_picture

    звали = []

    async def не_должно(*args, **kwargs):
        звали.append(1)
        return {}

    прежний = clinical_picture.ask_json
    clinical_picture.ask_json = не_должно
    try:
        без_списка = dict(клиника())
        без_списка["diagnoses"] = []
        итог = asyncio.run(
            clinical_picture.generate_pictures({"identity": "Ты — Пётр, 44 года."}, без_списка)
        )
    finally:
        clinical_picture.ask_json = прежний

    assert итог is None
    assert звали == [], "модель спросили при пустом списке диагнозов"
