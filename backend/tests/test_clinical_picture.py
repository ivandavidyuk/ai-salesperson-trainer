"""Проверка клинического шага: формы картин и выбора из них.

Повод — разбор 06.08.2026. Врач забраковал сборку: миопия, впервые возникшая
в 48 лет, катаракта с жалобой не на ту функцию. Причина была в порядке
вопросов: диагноз выбирала та же модель, что писала продающую прозу, и она
подгоняла болезнь под услугу.

Главный инвариант всей починки проверяется здесь первым тестом: в клиническом
запросе НЕТ услуг и цен. Появятся — и подлог вернётся, а заметить его будет
уже нечем.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from services.clinical_picture import (  # noqa: E402
    build_clinical_messages,
    build_match_messages,
    choose,
    validate_pictures,
)


def картина(diagnosis: str = "Возрастная катаракта, ядерная") -> dict:
    return {
        "diagnosis": diagnosis,
        "ageRange": "после 60 лет",
        "complaints": "Хуже видно вдаль, вблизи стало читаться легче.",
        "objective": "Помутнение ядра хрусталика, передняя камера сохранена.",
        "treatment": "Факоэмульсификация с имплантацией ИОЛ",
    }


def набор(сколько: int = 3) -> dict:
    return {"pictures": [картина(f"Диагноз {n}") for n in range(1, сколько + 1)]}


def клиника() -> dict:
    return {
        "name": "Клиника",
        "industry": "офтальмология",
        "services": [
            {"name": "Замена хрусталика", "price": "от 60 000 ₽", "description": "20 минут"},
            {"name": "Полная диагностика", "price": "6 500 ₽", "description": "полтора часа"},
        ],
    }


# --- Инвариант, ради которого всё затевалось ---


def test_в_клиническом_запросе_нет_услуг_и_цен():
    сообщения = build_clinical_messages(
        {"identity": "Ты — Леонид Петрович, 74 года.", "fears": ["боится ослепнуть"]},
        клиника(),
    )
    целиком = " ".join(с["content"] for с in сообщения)
    assert "Замена хрусталика" not in целиком
    assert "60 000" not in целиком
    assert "6 500" not in целиком
    # А отрасль и человек — на месте, иначе спрашивать не о чем
    assert "офтальмология" in целиком
    assert "74 года" in целиком


def test_клинический_запрос_не_говорит_о_продаже():
    сообщения = build_clinical_messages({"identity": "Ты — Пётр, 30 лет."}, клиника())
    инструкция = сообщения[0]["content"]
    assert "О продажах, услугах и ценах тебя не спрашивают" in инструкция


def test_в_подборе_услуги_есть_и_картины_и_услуги():
    сообщения = build_match_messages([картина()], клиника())
    текст = сообщения[1]["content"]
    assert "Возрастная катаракта" in текст
    assert "Замена хрусталика" in текст


# --- Форма ответа с картинами ---


def test_годный_набор_проходит():
    assert validate_pictures(набор()) is None


def test_меньше_трёх_картин_не_проходит():
    # Меньше трёх — не из чего выбирать, если под первую услуги нет
    беда = validate_pictures(набор(2))
    assert беда is not None and "картин 2" in беда


def test_больше_пяти_картин_не_проходит():
    беда = validate_pictures(набор(6))
    assert беда is not None and "картин 6" in беда


def test_пустое_поле_не_проходит():
    данные = набор()
    данные["pictures"][1]["objective"] = ""
    беда = validate_pictures(данные)
    assert беда is not None and "objective" in беда


def test_гадание_в_картине_не_проходит():
    данные = набор()
    данные["pictures"][0]["objective"] = "Стадия предположительно вторая."
    беда = validate_pictures(данные)
    assert беда is not None and "гадает" in беда


def test_диагноз_через_или_не_проходит():
    # «Близорукость слабой или средней степени» прошла прежнюю проверку:
    # слов-уклонений в ней нет, а гадание — есть
    данные = набор()
    данные["pictures"][0]["diagnosis"] = "Близорукость слабой или средней степени"
    беда = validate_pictures(данные)
    assert беда is not None and "«или»" in беда


def test_пустой_список_не_проходит():
    assert validate_pictures({"pictures": []}) is not None
    assert validate_pictures({}) is not None


# --- Выбор картины ---


def test_берётся_первая_подходящая():
    картины = [картина("А"), картина("Б"), картина("В")]
    услуги = [None, {"name": "Замена хрусталика"}, {"name": "Полная диагностика"}]
    выбор = choose(картины, услуги)
    assert выбор is not None
    assert выбор[0]["diagnosis"] == "Б"


def test_без_подходящих_услуг_ничего_не_выбирается():
    картины = [картина("А"), картина("Б")]
    assert choose(картины, [None, None]) is None


def test_занятый_диагноз_уступает_свежему():
    # Разнообразие: у другого пациента этой клиники «А» уже был
    картины = [картина("А"), картина("Б")]
    услуги = [{"name": "Замена хрусталика"}, {"name": "Замена хрусталика"}]
    выбор = choose(картины, услуги, used_diagnoses=["А"])
    assert выбор is not None and выбор[0]["diagnosis"] == "Б"


def test_если_все_диагнозы_заняты_берётся_первый():
    # Правдоподобие важнее разнообразия: повтор лучше, чем натянутая болезнь
    картины = [картина("А"), картина("Б")]
    услуги = [{"name": "Замена хрусталика"}, {"name": "Замена хрусталика"}]
    выбор = choose(картины, услуги, used_diagnoses=["А", "Б"])
    assert выбор is not None and выбор[0]["diagnosis"] == "А"


def test_занятость_не_зависит_от_регистра():
    картины = [картина("Возрастная катаракта"), картина("Глаукома")]
    услуги = [{"name": "Замена хрусталика"}, {"name": "Замена хрусталика"}]
    выбор = choose(картины, услуги, used_diagnoses=["возрастная КАТАРАКТА"])
    assert выбор is not None and выбор[0]["diagnosis"] == "Глаукома"
