def test_рубли_не_считаются_матом():
    # Самый дорогой ложный срабатыв: «рубля» содержит «бля», а цену называют
    # в каждом разговоре о продаже. Поймано на боевых данных до начисления —
    # шуточный бейдж достался бы почти всем
    про_цену = разговор(
        реплики_менеджера=[
            "Стоимость за оба глаза 628 540 рублей, со скидкой 502 832 рубля.",
            "Платёж будет 83 333 рубля в месяц.",
        ]
    )
    assert "youre-crazy" not in оценить(Сводка(), про_цену)


def test_безобидные_слова_с_корнями_внутри_не_считаются():
    for слово in ("корабля", "хлебал", "погребал", "грабля", "оглобля"):
        разг = разговор(реплики_менеджера=[f"Мы тут {слово} обсуждали недолго."])
        assert "youre-crazy" not in оценить(Сводка(), разг), слово


def test_настоящий_мат_ловится():
    for фраза in (
        "Ну а если я скажу: «Мне похуй»? И чё теперь?",
        "Да блядь, ну сколько можно повторять?",
        "Заебали эти возражения, честное слово.",
    ):
        разг = разговор(реплики_менеджера=[фраза])
        assert "youre-crazy" in оценить(Сводка(), разг), фраза
