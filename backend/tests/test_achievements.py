"""Условия выдачи достижений.

Проверяется чистое ядро — без базы и без сети. Цена ошибки здесь тихая:
неверный порог не падает, а просто выдаёт бейдж не тогда, и заметить это
можно только по жалобе.

Отдельный тест закрепляет список НЕВЫДАВАЕМЫХ. Он выглядит избыточным ровно
до того дня, когда кто-то решит «починить» денежный бейдж, подставив похожее
по смыслу поле, — и механизм начнёт врать молча.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from services.achievements import (  # noqa: E402
    НЕВЫДАВАЕМЫЕ,
    Разговор,
    Сводка,
    оценить,
    продолжить,
)


def разговор(**поля) -> Разговор:
    основа = {
        "duration_sec": 600,
        "outcome": "paid",
        "patient_id": "p1",
        "started_at_day": "2026-08-20",
        "реплики_менеджера": ["Здравствуйте, а что вас беспокоит?"],
        "реплики_пациента": ["Зуб болит уже неделю, спасу нет совсем."],
    }
    основа.update(поля)
    return Разговор(**основа)


def прогнать(разговоры: list[Разговор]) -> list[set[str]]:
    """История подряд: что открылось на каждом шаге."""
    сводка = Сводка()
    итог = []
    for р in разговоры:
        итог.append(оценить(сводка, р))
        сводка = продолжить(сводка, р)
    return итог


# --- Пороги ---


def test_первый_разговор_даёт_контакт():
    assert "first-contact" in оценить(Сводка(), разговор())


def test_две_сделки_не_дают_трипл_килл_а_три_дают():
    шаги = прогнать([разговор(), разговор(), разговор()])
    assert "triple-kill" not in шаги[1]
    assert "triple-kill" in шаги[2]


def test_кенни_считает_по_одному_пациенту_а_не_суммарно():
    # Пять сделок разным людям — это не «убили Кенни»
    разным = прогнать([разговор(patient_id=f"p{n}") for n in range(5)])
    assert all("kenny" not in шаг for шаг in разным)

    одному = прогнать([разговор(patient_id="p1") for _ in range(5)])
    assert "kenny" in одному[4]


def test_скорострел_требует_закрытой_сделки():
    быстро_но_мимо = разговор(outcome="refused", duration_sec=300)
    assert "quickdraw" not in оценить(Сводка(), быстро_но_мимо)
    assert "quickdraw" in оценить(Сводка(), разговор(duration_sec=300))


def test_скорострел_не_даётся_за_долгую_сделку():
    assert "quickdraw" not in оценить(Сводка(), разговор(duration_sec=26 * 60))


def test_упал_вставай_требует_именно_десяти_подряд():
    # Девять подряд — рано
    assert "get-up" not in оценить(Сводка(подряд_без_сделки=9), разговор())
    assert "get-up" in оценить(Сводка(подряд_без_сделки=10), разговор())


def test_серия_обнуляется_закрытой_сделкой():
    сводка = Сводка(подряд_без_сделки=9)
    сводка = продолжить(сводка, разговор(outcome="paid"))
    assert сводка.подряд_без_сделки == 0


def test_три_разговора_в_один_день_дают_без_обеда():
    день = прогнать([разговор(started_at_day="2026-08-20") for _ in range(3)])
    assert "no-lunch" not in день[1]
    assert "no-lunch" in день[2]


def test_разговоры_в_разные_дни_без_обеда_не_дают():
    разные = прогнать([
        разговор(started_at_day="2026-08-18"),
        разговор(started_at_day="2026-08-19"),
        разговор(started_at_day="2026-08-20"),
    ])
    assert all("no-lunch" not in шаг for шаг in разные)


def test_акула_считает_только_сложных():
    лёгкие = прогнать([разговор(patient_id=f"p{n}") for n in range(3)])
