def test_сбой_выдачи_не_ломает_завершение(monkeypatch):
    # Функция зовётся из фоновой задачи после закрытия разговора. Брось она —
    # и упадёт задача, в которой рядом стоит разбор
    import asyncio

    import main

    async def падает(pool, session_id):
        raise RuntimeError("база недоступна")

    monkeypatch.setattr(main.achievements, "начислить_за_сессию", падает)
    # Не должно бросить
    asyncio.run(main.award_achievements("s1"))


def test_разбор_идёт_раньше_достижений(monkeypatch):
    # Порядок обязателен: достижения читают исход сделки из разбора.
    # Перепутай — и разговор с закрытой сделкой не даст «Закрывателя»
    import asyncio

    import main

    порядок = []

    async def разбор(session_id):
        порядок.append("разбор")

    async def бейджи(session_id):
        порядок.append("достижения")

    monkeypatch.setattr(main, "finalize_review", разбор)
    monkeypatch.setattr(main, "award_achievements", бейджи)
    asyncio.run(main.после_разговора("s1"))

    assert порядок == ["разбор", "достижения"]


