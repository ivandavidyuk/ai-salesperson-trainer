# --- Защита от «починки наугад» ---


def test_невыдаваемые_не_выдаются_ни_при_каких_данных():
    # Разговор нарочно выкручен: закрыт, быстрый, с максимальными оценками,
    # сложный пациент, длинная история. Если денежный бейдж когда-нибудь
    # «починят», подставив похожее поле, этот тест это заметит
    богатый = Сводка(
        завершённых=500,
        закрытых=100,
        закрытых_сложным=50,
        закрытых_по_пациентам={"p1": 50},
        подряд_без_сделки=50,
        разговоров_в_день={"2026-08-20": 50},
    )
    выдано = оценить(
        богатый,
        разговор(overall=10, needs=10, objections=10, все_этапы=True, patient_hard=True),
    )
    assert выдано & НЕВЫДАВАЕМЫЕ == set(), выдано & НЕВЫДАВАЕМЫЕ


def test_список_невыдаваемых_не_сжался_молча():
    # Восемь: пять денежных, два про счёт возражений, «Царь горы»
    assert НЕВЫДАВАЕМЫЕ == {
        "wolf", "seller", "confident-seller", "no-discount", "sold-a-pen",
        "objection-slayer", "terminator", "king-of-the-hill",
    }


