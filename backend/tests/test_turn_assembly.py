"""Сборка хода роли: постоянная часть плюс состояние (llm.собрать_ход).

Состояние — строка доверия, «до документа» и показанный документ. Место
строки в запросе выбирается замером, а история при этом не должна меняться:
пометка живёт только в копии для запроса, а в Redis, Postgres и у оценщика
остаётся то, что сказали люди.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from services import llm  # noqa: E402

РОЛЬ = "Ты — Тамара Михайловна."
ИСТОРИЯ = [
    {"role": "user", "text": "Добрый день!"},
    {"role": "assistant", "text": "Здравствуйте."},
    {"role": "user", "text": "Давайте оформим лечение?"},
]


def test_в_промпте_как_до_19_10():
    # Прежняя сборка TurnManager: роль, доверие, документ — байт в байт
    было = (
        f"{РОЛЬ}\n\n{llm.trust_instruction(False)}\n\n"
        f"{llm.diagnostics_instruction('Заключение.')}"
    )
    промпт, история = llm.собрать_ход(
        РОЛЬ, ИСТОРИЯ, доверие=False, документ="Заключение.", место="промпт"
    )
    assert промпт == было
    assert история is ИСТОРИЯ


def test_без_доверия_только_роль_и_документ():
    # Этапная тренировка и сломанный оценщик: строки доверия нет
    промпт, история = llm.собрать_ход(РОЛЬ, ИСТОРИЯ, доверие=None)
    assert промпт == РОЛЬ
    assert история is ИСТОРИЯ
    промпт, _ = llm.собрать_ход(РОЛЬ, ИСТОРИЯ, доверие=None, документ="Заключение.")
    assert промпт == f"{РОЛЬ}\n\n{llm.diagnostics_instruction('Заключение.')}"


def test_пометка_к_последней_реплике_не_трогает_историю():
    исходная = [dict(x) for x in ИСТОРИЯ]
    промпт, запрос = llm.собрать_ход(РОЛЬ, ИСТОРИЯ, доверие=False, место="пометка")
    assert ИСТОРИЯ == исходная
    assert промпт == РОЛЬ
    assert запрос[:-1] == ИСТОРИЯ[:-1]
    последняя = запрос[-1]["text"]
    assert последняя.startswith("Давайте оформим лечение?\n\n")
    assert llm.trust_instruction(False) in последняя


def test_системным_сообщением_после_истории():
    промпт, запрос = llm.собрать_ход(РОЛЬ, ИСТОРИЯ, доверие=True, место="система")
    assert промпт == РОЛЬ
    assert запрос[:-1] == ИСТОРИЯ
    assert запрос[-1] == {"role": "system", "text": llm.trust_instruction(True)}


def test_до_документа_только_пока_его_нет():
    промпт, _ = llm.собрать_ход(РОЛЬ, ИСТОРИЯ, доверие=False, до_документа=True, место="промпт")
    assert "ДИАГНОСТИКА:" in промпт
    промпт, _ = llm.собрать_ход(
        РОЛЬ, ИСТОРИЯ, доверие=False, до_документа=True, документ="Заключение.", место="промпт"
    )
    assert "ДИАГНОСТИКА:\n" not in промпт
    assert "РЕЗУЛЬТАТ ДИАГНОСТИКИ:" in промпт
