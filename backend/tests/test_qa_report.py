"""Поводы посмотреть и сравнение прогонов.

Инструмент не выносит вердиктов, но решает, на что обратить внимание.
Ошибка здесь дорога вдвойне: пропущенный повод прячет дефект, а лишний
приучает не верить сводке.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from qa.report import (  # noqa: E402
    медиана_прогона,
    поводы_посмотреть,
)


def клетка(
    пациент="tamara-sokolova",
    тип="full",
    ходов=10,
    метрики=None,
    чтение=None,
    сбои=None,
    разбор=True,
) -> dict:
    м = {
        "реплик": ходов,
        "немых_ходов": 0,
        "ходов_с_ремаркой": 0,
        "знаков_медиана": 180,
        "секунд_медиана": 12.0,
        "повторов": 0,
        "ходов_с_латиницей": 0,
        "ходов_с_чужим_именем": 0,
    }
    м.update(метрики or {})
    return {
        "разговор": {
            "пациент": пациент,
            "тип": тип,
            "ходы": [{"номер": i} for i in range(1, ходов + 1)],
            "сбои": сбои or [],
            "разбор": {"исход": "paid", "общая": 8.0} if разбор else None,
        },
        "метрики": м,
        "чтение": чтение,
    }


def test_здоровая_клетка_поводов_не_даёт():
    assert поводы_посмотреть(клетка()) == []


def test_немые_ходы_повод():
    поводы = поводы_посмотреть(клетка(метрики={"немых_ходов": 11}))
    assert any("немых ходов: 11" in п for п in поводы)


def test_несостоявшийся_разговор_повод():
    поводы = поводы_посмотреть(клетка(ходов=0))
    assert any("не состоялся" in п for п in поводы)


def test_сбой_прогона_повод():
    поводы = поводы_посмотреть(
        клетка(сбои=[{"ход": 3, "тип": "роль:пусто", "сообщение": ""}])
    )
    assert any("сбоев: 1" in п for п in поводы)


def test_многословность_видна_только_в_сравнении_с_прогоном():
    # У Оксаны 31.07 было 507 знаков при медиане 180 у остальных.
    # Абсолютного порога у нас нет, поэтому без медианы прогона повода нет
    оксана = клетка(метрики={"знаков_медиана": 651, "секунд_медиана": 43.4})
    assert поводы_посмотреть(оксана) == []

    поводы = поводы_посмотреть(оксана, медиана_по_прогону=180)
    assert any("длиннее обычных" in п for п in поводы)


def test_обычная_длина_поводом_не_становится():
    поводы = поводы_посмотреть(клетка(), медиана_по_прогону=180)
    assert поводы == []


def test_любая_находка_читателя_повод():
    # Читатель проинструктирован возвращать пустой список, когда всё хорошо.
    # Значит выписанная находка — уже повод прочесть, даже средней серьёзности
    чтение = {"находки": [{"серьёзность": "средняя", "цитата": "…", "что": "повторы"}]}
    поводы = поводы_посмотреть(клетка(чтение=чтение))
    assert any("находок читателя: 1" in п for п in поводы)


def test_серьёзные_находки_называются_отдельно():
    чтение = {
        "находки": [
            {"серьёзность": "высокая", "цитата": "…", "что": "вышла из роли"},
            {"серьёзность": "низкая", "цитата": "…", "что": "канцелярит"},
        ]
    }
    поводы = поводы_посмотреть(клетка(чтение=чтение))
    assert any("серьёзных: 1" in п for п in поводы)


def test_сбой_читателя_не_прячется():
    # «Не читали» и «чисто» — разные вещи, и путать их нельзя
    поводы = поводы_посмотреть(клетка(чтение={"ошибка": "модель не вернула JSON"}))
    assert any("читатель не отработал" in п for п in поводы)


def test_медианы_нет_когда_клеток_мало():
    # На одиночном прогоне выброс не виден по определению — сравнивать не с чем
    assert медиана_прогона([клетка() for _ in range(4)]) is None


def test_медиана_считается_на_пяти_клетках():
    результаты = [клетка(метрики={"знаков_медиана": 180}) for _ in range(4)]
    результаты.append(клетка(метрики={"знаков_медиана": 651}))
    assert медиана_прогона(результаты) == 180


def test_медиана_настоящая_а_не_серединный_индекс():
    # Реальный прогон 04.08: 96, 126, 200, 454, 482, 671. Серединный по
    # индексу давал 454 и завышал норму так, что Оксана (671) переставала
    # быть выбросом. Настоящая медиана — 327, и выброс виден
    длины = [96, 126, 200, 454, 482, 671]
    результаты = [клетка(метрики={"знаков_медиана": д}) for д in длины]
    assert медиана_прогона(результаты) == 327

    # И теперь Оксана действительно помечается
    оксана = клетка(метрики={"знаков_медиана": 671, "секунд_медиана": 44.7})
    assert поводы_посмотреть(оксана, медиана_по_прогону=327)


def test_на_чётном_числе_клеток_берётся_середина_между_двумя():
    результаты = [
        клетка(метрики={"знаков_медиана": д}) for д in (100, 200, 300, 400, 500, 600)
    ]
    assert медиана_прогона(результаты) == 350


def test_пустые_клетки_в_медиану_не_идут():
    # Разговор, который не состоялся, длину не характеризует
    результаты = [клетка(метрики={"знаков_медиана": 200}) for _ in range(5)]
    результаты += [клетка(ходов=0, метрики={"знаков_медиана": 0}) for _ in range(4)]
    assert медиана_прогона(результаты) == 200
